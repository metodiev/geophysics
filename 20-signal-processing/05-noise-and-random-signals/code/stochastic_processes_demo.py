#!/usr/bin/env python3
"""Stochastic processes: stationarity, ergodicity and the effective number of
independent samples, measured on ensembles of SYNTHETIC random processes.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python stochastic_processes_demo.py

Everything here is SYNTHETIC.  The processes are generated by the code below;
no data are read and no number is taken from a published measurement.

Sections
--------
1. Ensemble versus time statistics for a stationary AR(1) process.
2. Integrated autocorrelation time and the effective number of samples.
3. Stationarity diagnostics: split-half mean and variance.
4. A non-ergodic process, and why the single-realisation time average then fails.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC process parameters (chosen, not measured) ---------------------
PHI = 0.90          # AR(1) coefficient, dimensionless
SIGMA_W = 1.0       # white driving noise standard deviation
DT = 1.0            # sampling interval, s
N = 10000           # samples per realisation
M = 400             # number of realisations in the ensemble


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def ar1_ensemble(n, m, phi, sigma_w, rng):
    """Ensemble of m AR(1) realisations: x[i] = phi x[i-1] + w[i]."""
    w = sigma_w * rng.standard_normal((m, n))
    x = np.empty((m, n))
    x[:, 0] = w[:, 0] / np.sqrt(1.0 - phi ** 2)
    for i in range(1, n):
        x[:, i] = phi * x[:, i - 1] + w[:, i]
    return x


def random_walk_ensemble(n, m, sigma_w, rng):
    """Ensemble of m random walks (integrated white noise)."""
    increments = sigma_w * rng.standard_normal((m, n))
    return np.cumsum(increments, axis=1)


def integrated_time_theory(phi, dt):
    """Integrated autocorrelation time of AR(1): dt (1 + 2 sum_{k>=1} phi^k)."""
    return dt * (1.0 + 2.0 * phi / (1.0 - phi))


def main():
    section("1. Ensemble statistics versus time statistics (stationary AR(1))")
    x = ar1_ensemble(N, M, PHI, SIGMA_W, RNG)
    var_theory = SIGMA_W ** 2 / (1.0 - PHI ** 2)
    print(f"SYNTHETIC AR(1): phi = {PHI:.2f}, sigma_w = {SIGMA_W:.2f}, "
          f"n = {N} samples, dt = {DT:.1f} s ({N * DT:.0f} s per record)")
    print(f"  exact variance sigma_w^2/(1-phi^2) = {var_theory:.4f} "
          f"(std {np.sqrt(var_theory):.4f})")
    sample_var = x[:, 500:].var(axis=1, ddof=1)   # drop the burn-in
    print(f"  ensemble mean of the per-record variance = {sample_var.mean():.4f} "
          f"+/- {sample_var.std():.4f}  (scatter = 1 s.d. over {M} records)")
    time_avg = x[:, 500:].mean(axis=1)
    print(f"  time average exceeds the ensemble mean by "
          f"{np.abs(time_avg).mean():.4f} on average")
    print("  -> time statistics agree with ensemble statistics for THIS process,")
    print("     but only to within the scatter computed next.")

    section("2. Integrated autocorrelation time and effective sample size")
    tau_int = integrated_time_theory(PHI, DT)
    tau_e = -DT / np.log(PHI)            # lag where ACF falls to 1/e
    n_eff = (N * DT) / tau_int
    se_theory = np.sqrt(var_theory) / np.sqrt(n_eff)
    se_naive = np.sqrt(var_theory) / np.sqrt(N)
    print(f"  integrated autocorrelation time tau_int = dt (1+2 phi/(1-phi)) "
          f"= {tau_int:.2f} s")
    print(f"  ACF 1/e decay time  -dt/ln(phi) = {tau_e:.2f} s")
    print(f"  effective sample count N_eff = T/tau_int = {N * DT:.0f}/{tau_int:.2f} "
          f"= {n_eff:.1f}")
    print(f"  standard error of the mean       sigma/sqrt(N_eff) = {se_theory:.4f}")
    print(f"  naive white-noise formula        sigma/sqrt(N)     = {se_naive:.4f}")
    print(f"  the naive value is too small by  sqrt(tau_int/dt) = "
          f"{np.sqrt(tau_int / DT):.3f}x")
    print(f"  MEASURED scatter of the time average over the ensemble = "
          f"{time_avg.std():.4f}")
    print("  -> the measured scatter matches sigma/sqrt(N_eff), not sigma/sqrt(N).")

    section("3. Stationarity diagnostics: split-half mean and variance")
    first = x[:, 500:N // 2]
    second = x[:, N // 2:]
    d_mean = second.mean(axis=1) - first.mean(axis=1)
    d_var = second.var(axis=1, ddof=1) - first.var(axis=1, ddof=1)
    print(f"  stationary AR(1): second-half minus first-half mean = "
          f"{d_mean.mean():+.4f} +/- {d_mean.std():.4f} (ensemble)")
    print(f"  stationary AR(1): second-half minus first-half var  = "
          f"{d_var.mean():+.4f} +/- {d_var.std():.4f} (ensemble)")
    rw = random_walk_ensemble(N, M, SIGMA_W, RNG)
    rw_first, rw_second = rw[:, :N // 2], rw[:, N // 2:]
    print(f"  random walk: first-half variance = {rw_first.var():.1f}, "
          f"second-half variance = {rw_second.var():.1f}")
    print(f"  random walk: ratio second/first = "
          f"{rw_second.var() / rw_first.var():.3f} "
          f"(time-varying variance => NOT stationary)")

    section("4. A non-ergodic process: a random constant offset per record")
    offset = RNG.standard_normal(M)[:, None]        # same for all t in a record
    y = offset + 0.3 * RNG.standard_normal((M, N))  # ergodic noise + fixed offset
    y_avg = y[:, 500:].mean(axis=1)
    print(f"  ensemble mean at any fixed time  = {y[:, 500:].mean():+.4f}")
    print(f"  record-to-record scatter of the time average = {y_avg.std():.4f}")
    half_n = (N - 500) // 2
    y_first = y[:, 500:500 + half_n].mean(axis=1)
    y_second = y[:, 500 + half_n:].mean(axis=1)
    print(f"  scatter of the time average using only half the record = "
          f"{np.concatenate([y_first, y_second]).std():.4f}")
    print("  -> the scatter does NOT shrink as the record lengthens: the time")
    print("     average converges to the per-record offset, not to the ensemble")
    print("     mean.  Ergodicity is an extra assumption that this process breaks.")


if __name__ == "__main__":
    main()
