#!/usr/bin/env python3
"""ML for seismic event detection: a hand-built trigger versus a learned classifier.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python seismic_ml_demo.py

Everything here is SYNTHETIC.  The windows are generated by the code below from
a Ricker wavelet of chosen frequency and amplitude plus Gaussian noise; no
recording, catalogue or published detection curve is read.

Sections
--------
1. The synthetic window population and its four features.
2. A single-feature STA/LTA trigger, and the price of one threshold.
3. A learned classifier: accuracy, false-positive rate and AUC.
4. Two operating points, and what the AUC does not say.
"""

import numpy as np
from scipy.ndimage import uniform_filter1d
from scipy.stats import rankdata
from sklearn.linear_model import LogisticRegression

RNG = np.random.default_rng(20261014)

FS = 100.0          # sampling rate, Hz
NPER = 200          # samples per window (2.0 s)
N_TRAIN = 400       # training windows
N_TEST = 200        # test windows
EVENT_F = 8.0       # dominant event frequency, Hz
PEAK_RMS = 3.0      # event peak amplitude / noise RMS, dimensionless

FEATURE_NAMES = ("log10(max STA/LTA)", "log10(kurtosis)",
                 "log10(4-12 Hz / 0.5-2 Hz energy)", "peak/RMS")


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def ricker(t, f):
    a = (np.pi * f * t) ** 2
    return (1.0 - 2.0 * a) * np.exp(-a)


def window_features(x):
    """Four interpretable features of one 2 s window."""
    n = x.size
    x = x - x.mean()
    ms = x ** 2
    sta = uniform_filter1d(ms, 20, mode="nearest")
    lta = uniform_filter1d(ms, 160, mode="nearest")
    stalta = float(np.max(sta / np.maximum(lta, 1e-12)))
    kurt = float(np.mean(x ** 4) / max(np.mean(ms) ** 2, 1e-12))
    spec = np.abs(np.fft.rfft(x)) ** 2
    freq = np.fft.rfftfreq(n, d=1.0 / FS)
    e_hi = float(spec[(freq >= 4.0) & (freq <= 12.0)].sum())
    e_lo = float(spec[(freq >= 0.5) & (freq <= 2.0)].sum())
    pnr = float(np.abs(x).max() / max(np.sqrt(np.mean(ms)), 1e-12))
    return np.array([np.log10(stalta), np.log10(kurt),
                     np.log10(e_hi / max(e_lo, 1e-12)), pnr])


def make_window(event):
    """One window: noise only, or a Ricker wavelet buried in the same noise."""
    t = np.arange(NPER) / FS
    noise = RNG.standard_normal(NPER)
    if not event:
        return noise
    t0 = RNG.uniform(0.6, 1.4)
    wavelet = ricker(t - t0, EVENT_F)
    wavelet = wavelet / np.abs(wavelet).max()
    return PEAK_RMS * np.sqrt(np.mean(noise ** 2)) * wavelet + noise


def auc_score(scores, labels):
    """Rank (Mann-Whitney) AUC."""
    ranks = rankdata(scores)
    n_pos = int(labels.sum())
    n_neg = int(labels.size - n_pos)
    return (ranks[labels == 1].sum() - n_pos * (n_pos + 1) / 2.0) / (n_pos * n_neg)


def rates(score, label, threshold):
    call = score >= threshold
    tp = float(np.sum(call & (label == 1)))
    fp = float(np.sum(call & (label == 0)))
    return (tp / max(np.sum(label == 1), 1), fp / max(np.sum(label == 0), 1))


def main():
    section("1. The synthetic window population")
    features, labels = [], []
    for i in range(N_TRAIN + N_TEST):
        event = (i % 2 == 0)
        features.append(window_features(make_window(event)))
        labels.append(int(event))
    features = np.array(features)
    labels = np.array(labels)
    x_train, y_train = features[:N_TRAIN], labels[:N_TRAIN]
    x_test, y_test = features[N_TRAIN:], labels[N_TRAIN:]
    print(f"SYNTHETIC windows: {NPER} samples at {FS:.0f} Hz "
          f"({NPER / FS:.1f} s per window), {features.shape[0]} windows "
          f"({int(labels.sum())} containing an event)")
    print(f"  event: {EVENT_F:.0f} Hz Ricker wavelet, peak/RMS = {PEAK_RMS:.1f}")
    noise_med = np.median(x_train[y_train == 0], axis=0)
    event_med = np.median(x_train[y_train == 1], axis=0)
    for name, a, b in zip(FEATURE_NAMES, noise_med, event_med):
        print(f"  median {name:<34s} noise {a:+7.3f}   event {b:+7.3f}")

    section("2. A single-feature STA/LTA trigger")
    sl = x_train[:, 0]
    tpr, fpr = rates(x_test[:, 0], y_test, np.log10(2.0))
    print(f"  fixed threshold ratio = 2.0 (log10 = {np.log10(2.0):.3f}), "
          f"the usual field default")
    print(f"    test true-positive rate  = {tpr:.3f}")
    print(f"    test false-positive rate = {fpr:.3f}")
    print(f"    test accuracy            = "
          f"{0.5 * tpr + 0.5 * (1 - fpr):.3f} (classes are balanced)")
    cutoff = np.quantile(sl[y_train == 0], 0.95)
    tpr95, fpr95 = rates(x_test[:, 0], y_test, cutoff)
    print(f"  threshold calibrated to 5% TRAINING false positives "
          f"(ratio = {10 ** cutoff:.2f})")
    print(f"    measured test FPR = {fpr95:.3f}, TPR = {tpr95:.3f}")
    print("  -> one number, the ratio, decides both columns; it cannot be tuned")
    print("     to raise the TPR without raising the FPR.")

    section("3. A learned classifier on the four features")
    mean = x_train.mean(axis=0)
    sd = x_train.std(axis=0)
    z_train = (x_train - mean) / sd
    z_test = (x_test - mean) / sd
    clf = LogisticRegression(max_iter=1000)
    clf.fit(z_train, y_train)
    prob = clf.predict_proba(z_test)[:, 1]
    train_noise_prob = clf.predict_proba(z_train[y_train == 0])[:, 1]
    acc = float(np.mean((prob >= 0.5) == (y_test == 1)))
    tpr_l, fpr_l = rates(prob, y_test, 0.5)
    auc = auc_score(prob, y_test)
    print(f"  logistic regression, {z_train.shape[1]} standardised features, "
          f"fit on {N_TRAIN} windows")
    print(f"  coefficients (standardised): "
          + ", ".join(f"{c:+.2f}" for c in clf.coef_[0]))
    print(f"  test accuracy = {acc:.3f}, TPR = {tpr_l:.3f}, FPR = {fpr_l:.3f}")
    print(f"  test AUC = {auc:.3f}")
    print(f"  score at 95th percentile of TRAINING noise = "
          f"{np.quantile(train_noise_prob, 0.95):.3f}")

    section("4. Two operating points, and what the AUC does not say")
    for target in (0.05, 0.01):
        thr = float(np.quantile(train_noise_prob, 1.0 - target))
        tpr_t, fpr_t = rates(prob, y_test, thr)
        print(f"  operating point for a {100 * target:.0f}% false-positive budget: "
              f"threshold = {thr:.3f}, test FPR = {fpr_t:.3f}, TPR = {tpr_t:.3f}")
    print(f"  the AUC ({auc:.3f}) is threshold-free; the two operating points "
          f"above are not,")
    print("  and the detector that is deployed is always one (threshold, FPR, TPR)")
    print("  triple, never an AUC.")
    print(f"  the test set holds {int(y_test.sum())} events out of {y_test.size}: "
          f"one event is {100 / y_test.sum():.1f}% of the TPR.")
    print("\nSYNTHETIC: all windows were generated by this script; the rates and the")
    print("AUC quantify THIS generator and say nothing about a real network.")


if __name__ == "__main__":
    main()
