#!/usr/bin/env python3
"""AR, MA and ARMA processes: what the autocorrelation identifies.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python arima_models_demo.py

Everything here is SYNTHETIC.  The series are generated by the recursions below
with chosen coefficients; no record and no published parameter estimate is used.

Sections
--------
1. Three synthetic processes and their sample autocorrelations.
2. Parameter recovery: Yule-Walker, method of moments, and the ARMA(1,1) pair.
3. One-step-ahead prediction error against the unconditional variance.
4. Differencing a random walk: levels versus increments.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

N = 4000            # samples per series
PHI_AR = 0.70       # true AR(1) coefficient
THETA_MA = 0.50     # true MA(1) coefficient
PHI_ARMA = 0.60     # true ARMA(1,1) AR coefficient
THETA_ARMA = 0.40   # true ARMA(1,1) MA coefficient
SIGMA_W = 1.0       # innovation standard deviation, arbitrary units


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def acf(x, max_lag):
    x = x - x.mean()
    denom = np.dot(x, x)
    return np.array([np.dot(x[:x.size - k], x[k:]) / denom for k in range(max_lag + 1)])


def simulate_ar1(n, phi, sigma, rng):
    w = sigma * rng.standard_normal(n)
    x = np.empty(n)
    x[0] = w[0] / np.sqrt(1.0 - phi ** 2)
    for i in range(1, n):
        x[i] = phi * x[i - 1] + w[i]
    return x


def simulate_ma1(n, theta, sigma, rng):
    w = sigma * rng.standard_normal(n + 1)
    return w[1:] + theta * w[:-1]


def simulate_arma11(n, phi, theta, sigma, rng, burn=500):
    w = sigma * rng.standard_normal(n + burn)
    x = np.zeros(n + burn)
    for i in range(1, n + burn):
        x[i] = phi * x[i - 1] + w[i] + theta * w[i - 1]
    return x[burn:]


def main():
    section("1. Three synthetic processes and their sample autocorrelations")
    ar = simulate_ar1(N, PHI_AR, SIGMA_W, RNG)
    ma = simulate_ma1(N, THETA_MA, SIGMA_W, RNG)
    arma = simulate_arma11(N, PHI_ARMA, THETA_ARMA, SIGMA_W, RNG)
    rho_ar = acf(ar, 5)
    rho_ma = acf(ma, 5)
    rho_arma = acf(arma, 5)
    print(f"SYNTHETIC series: n = {N}, innovation sigma = {SIGMA_W:.1f} "
          f"(arbitrary units), seed 20261014")
    print("  true parameters: AR(1) phi = "
          f"{PHI_AR:.2f}; MA(1) theta = {THETA_MA:.2f}; "
          f"ARMA(1,1) phi = {PHI_ARMA:.2f}, theta = {THETA_ARMA:.2f}")
    print(f"  {'lag':>4s} {'AR(1)':>9s} {'phi^lag':>9s} {'MA(1)':>9s} "
          f"{'theory':>9s} {'ARMA':>9s}")
    for k in range(1, 6):
        ma_theory = THETA_MA / (1.0 + THETA_MA ** 2) if k == 1 else 0.0
        print(f"  {k:>4d} {rho_ar[k]:>+9.4f} {PHI_AR ** k:>+9.4f} "
              f"{rho_ma[k]:>+9.4f} {ma_theory:>+9.4f} {rho_arma[k]:>+9.4f}")
    print("  the AR(1) ACF decays geometrically; the MA(1) ACF is zero beyond")
    print("  lag 1; the ARMA(1,1) ACF decays geometrically FROM its lag-1 value,")
    print("  which is why an ARMA ACF alone cannot separate the two parameters")

    section("2. Parameter recovery from the sample autocorrelations")
    phi_hat = rho_ar[1]
    print(f"  AR(1), Yule-Walker phi = rho_1: {phi_hat:+.4f} "
          f"against {PHI_AR:+.2f} (error {phi_hat - PHI_AR:+.4f})")

    r1 = rho_ma[1]
    disc = 1.0 - 4.0 * r1 ** 2
    theta_hat = (1.0 - np.sqrt(max(disc, 0.0))) / (2.0 * r1)
    print(f"  MA(1), method of moments from rho_1 = {r1:+.4f}: "
          f"theta = {theta_hat:+.4f} against {THETA_MA:+.2f} "
          f"(error {theta_hat - THETA_MA:+.4f})")
    print(f"    the two roots are {theta_hat:+.4f} and "
          f"{1.0 / theta_hat:+.4f}; only the invertible one is admissible")

    phi_a = rho_arma[2] / rho_arma[1]
    a = rho_arma[1] - phi_a
    b = 2.0 * rho_arma[1] * phi_a - 1.0 - phi_a ** 2
    root = np.sqrt(max(b ** 2 - 4.0 * a ** 2, 0.0))
    candidates = [(-b + root) / (2.0 * a), (-b - root) / (2.0 * a)]
    theta_a = min(candidates, key=abs)
    print(f"  ARMA(1,1): phi = rho_2/rho_1 = {phi_a:+.4f} "
          f"against {PHI_ARMA:+.2f} (error {phi_a - PHI_ARMA:+.4f})")
    print(f"  ARMA(1,1): theta roots {candidates[0]:+.4f} and "
          f"{candidates[1]:+.4f}; invertible root {theta_a:+.4f} "
          f"against {THETA_ARMA:+.2f} (error {theta_a - THETA_ARMA:+.4f})")
    short = simulate_arma11(200, PHI_ARMA, THETA_ARMA, SIGMA_W, RNG)
    rho_s = acf(short, 2)
    phi_s = rho_s[2] / rho_s[1]
    a_s = rho_s[1] - phi_s
    b_s = 2.0 * rho_s[1] * phi_s - 1.0 - phi_s ** 2
    root_s = np.sqrt(max(b_s ** 2 - 4.0 * a_s ** 2, 0.0))
    cand_s = [(x) for x in ((-b_s + root_s) / (2.0 * a_s),
                            (-b_s - root_s) / (2.0 * a_s))
              if np.isfinite(x)]
    theta_s = min(cand_s, key=abs) if cand_s else float("nan")
    print(f"  the same two equations on a SHORT record (n = 200): "
          f"phi = {phi_s:+.4f} (error {phi_s - PHI_ARMA:+.4f}), "
          f"theta = {theta_s:+.4f} (error {theta_s - THETA_ARMA:+.4f})")
    print("  with a long record the moment estimates are accurate, but the")
    print("  equations divide by rho_1 and by (rho_1 - phi), so they become")
    print("  ill-conditioned as phi approaches theta and on short records --")
    print("  which is the practical reason ARMA fitting uses a likelihood")

    section("3. One-step-ahead prediction error")
    var_theory = SIGMA_W ** 2 / (1.0 - PHI_AR ** 2)
    pred = PHI_AR * ar[:-1]
    mse_1step = float(np.mean((ar[1:] - pred) ** 2))
    mse_uncond = float(np.mean((ar[1:] - ar[:-1].mean()) ** 2))
    print(f"  AR(1): unconditional variance sigma_w^2/(1-phi^2) = "
          f"{var_theory:.4f} (std {np.sqrt(var_theory):.4f})")
    print(f"    measured one-step-ahead MSE = {mse_1step:.4f}, "
          f"theoretical = {SIGMA_W ** 2:.4f}")
    print(f"    measured MSE of predicting the sample mean instead = "
          f"{mse_uncond:.4f}")
    print(f"    variance reduction from using the model = "
          f"{1.0 - mse_1step / mse_uncond:.4f} "
          f"(theoretical R^2 = {PHI_AR ** 2:.4f})")

    section("4. Differencing a random walk")
    walk = np.cumsum(SIGMA_W * RNG.standard_normal(N))
    rho_walk = acf(walk, 5)
    rho_diff = acf(np.diff(walk), 5)
    print(f"  random walk: ACF at lags 1-5 = "
          + ", ".join(f"{v:+.3f}" for v in rho_walk[1:]))
    print(f"  first differences: ACF at lags 1-5 = "
          + ", ".join(f"{v:+.3f}" for v in rho_diff[1:]))
    print(f"  variance of the first half = {walk[:N // 2].var():.1f}, "
          f"second half = {walk[N // 2:].var():.1f} "
          f"(ratio {walk[N // 2:].var() / walk[:N // 2].var():.3f})")
    print("  the levels are non-stationary and their ACF does not decay; one")
    print("  difference renders the series white, which is why the order of")
    print("  differencing is read from the ACF rather than chosen for fit")
    print("\nSYNTHETIC: every series was generated by this script; the estimates")
    print("quantify this generator and its sample size, and no real record.")


if __name__ == "__main__":
    main()
