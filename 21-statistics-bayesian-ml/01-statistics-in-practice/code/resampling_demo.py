#!/usr/bin/env python3
"""Resampling on SYNTHETIC data: the bootstrap interval for a mean and a
median, the jackknife bias and standard error, a permutation test for a group
difference, and a demonstration that the bootstrap fails for a maximum.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python resampling_demo.py

Everything is SYNTHETIC.  The samples are generated by the code below; no
measured value enters.

Sections
--------
1. Bootstrap interval for the mean and the median of a skewed sample.
2. Jackknife bias and standard error, compared with the bootstrap.
3. Permutation test against a two-sample t test.
4. Where the bootstrap fails: an extreme-order statistic.
"""

import numpy as np
from scipy import stats

RNG = np.random.default_rng(20261014)

N = 100           # sample size, dimensionless counts
B = 10000         # bootstrap replicates
N_PERM = 5000     # permutation replicates
N_A = N_B = 30    # group sizes for the two-sample test
SHIFT = 0.5       # true mean shift in standard-deviation units


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def bootstrap_statistic(sample, func, b, rng):
    idx = rng.integers(0, sample.size, size=(b, sample.size))
    return np.array([func(sample[i]) for i in idx])


def main():
    print("SYNTHETIC magnitudes: 100 draws from a standard lognormal "
          "(right-skewed), reported in arbitrary units (a.u.).")

    x = RNG.lognormal(mean=0.0, sigma=1.0, size=N)

    section("1. Bootstrap percentile intervals (95 %)")
    for name, func in (("mean", np.mean), ("median", np.median)):
        boots = bootstrap_statistic(x, func, B, RNG)
        lo, hi = np.percentile(boots, [2.5, 97.5])
        se = boots.std(ddof=1)
        print(f"  {name:7s} point estimate = {func(x):7.4f} a.u.   "
              f"bootstrap SE = {se:.4f}   interval = [{lo:.4f}, {hi:.4f}]")
        print(f"          interval width = {hi - lo:.4f}   "
              f"bootstrap skewness = {stats.skew(boots, bias=False):+.3f}")
    print("  the two intervals are almost the same width, but their shapes")
    print("  differ: the median's bootstrap distribution is strongly")
    print("  right-skewed, so its percentile interval is visibly asymmetric.")

    section("2. Jackknife bias and standard error")
    for name, func in (("mean", np.mean), ("median", np.median)):
        theta = func(x)
        loo = np.array([func(np.delete(x, i)) for i in range(N)])
        bias = (N - 1) * (loo.mean() - theta)
        se_jack = np.sqrt((N - 1) / N * np.sum((loo - loo.mean()) ** 2))
        print(f"  {name:7s} estimate = {theta:7.4f} a.u.   "
              f"jackknife bias = {bias:+.3e}   jackknife SE = {se_jack:.4f}")
    print("  the jackknife bias is an estimate of the O(1/N) bias of the letter")
    print("  value; a bias small compared with the SE is not worth correcting.")

    section("3. Permutation test for a difference in means")
    a = RNG.standard_normal(N_A)
    b = SHIFT + RNG.standard_normal(N_B)
    obs = a.mean() - b.mean()
    pooled = np.concatenate([a, b])
    count = 0
    for _ in range(N_PERM):
        RNG.shuffle(pooled)
        count += abs(pooled[:N_A].mean() - pooled[N_A:].mean()) >= abs(obs)
    p_perm = (count + 1) / (N_PERM + 1)
    t_stat, p_t = stats.ttest_ind(a, b, equal_var=False)
    print(f"  observed difference of means = {obs:+.4f} a.u.")
    print(f"  permutation p-value (two-sided, {N_PERM} shuffles) = {p_perm:.4f}")
    print(f"  Welch t test statistic = {t_stat:+.4f}, p-value = {p_t:.4f}")
    print("  the permutation p-value makes no distributional assumption, only")
    print("  that the labels are exchangeable under the null.")

    section("4. Where the bootstrap fails: the maximum")
    smax = x.max()
    boots_max = bootstrap_statistic(x, np.max, B, RNG)
    lo, hi = np.percentile(boots_max, [2.5, 97.5])
    print(f"  sample maximum = {smax:.4f} a.u.")
    print(f"  bootstrap interval for the maximum = [{lo:.4f}, {hi:.4f}] "
          f"(width {hi - lo:.4f})")
    print(f"  fraction of bootstrap maxima equal to the sample maximum = "
          f"{np.mean(boots_max == smax):.4f}")
    print("  a maximum sits at the edge of the sample space, so the upper")
    print("  endpoint is pinned to the largest observation and the interval can")
    print("  never contain a larger value; it understates the uncertainty and")
    print("  must not be reported as a confidence interval.")


if __name__ == "__main__":
    main()
