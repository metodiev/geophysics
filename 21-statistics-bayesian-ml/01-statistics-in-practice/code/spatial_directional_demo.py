#!/usr/bin/env python3
"""Spatial and directional statistics on SYNTHETIC fields and bearings: Moran's
I as a function of correlation length, the experimental semivariogram, and the
circular mean, resultant length and Rayleigh test.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python spatial_directional_demo.py

Everything is SYNTHETIC: Gaussian random fields are generated by smoothing white
noise, and bearings are drawn from a von Mises distribution. No measured value
is used.

Sections
--------
1. Moran's I for three correlation lengths on a 30 x 30 grid.
2. The experimental semivariogram on the correlated field.
3. Directional statistics: circular mean, resultant length and Rayleigh test.
"""

import numpy as np
from scipy import stats
from scipy.ndimage import gaussian_filter

RNG = np.random.default_rng(20261014)

NY = NX = 30
N = NY * NX
LENGTHS = (0.0, 0.5, 2.0, 5.0)   # Gaussian smoothing length, grid cells (0 = none)


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def morans_i(grid):
    """Moran's I with rook (4-neighbour) contiguity, non-toroidal edges."""
    ny, nx = grid.shape
    z = grid - grid.mean()
    edges = ny * (nx - 1) + (ny - 1) * nx
    s = (np.sum(z[:, :-1] * z[:, 1:]) + np.sum(z[:-1, :] * z[1:, :]))
    return (z.size / edges) * s / np.sum(z ** 2)


def semivariance(grid, lag_x):
    z = grid
    d = z[:, :-lag_x] - z[:, lag_x:]
    return 0.5 * np.mean(d ** 2)


def main():
    print("SYNTHETIC gridded field: 30 x 30 white noise smoothed with a Gaussian "
          "of the stated correlation length (grid cells).")

    section("1. Moran's I versus correlation length")
    print(f"  expectation under no spatial autocorrelation: "
          f"E[I] = -1/(N-1) = {-1.0 / (N - 1):+.4f}")
    for length in LENGTHS:
        white = RNG.standard_normal((NY, NX))
        field = (white if length == 0.0
                 else gaussian_filter(white, sigma=length, mode="wrap"))
        label = "white noise" if length == 0.0 else f"{length:.1f} cells"
        print(f"  {label:>11s} -> Moran's I = {morans_i(field):+.4f}, "
              f"field sd = {field.std():.3f}")
    print("  white noise gives I close to E[I] = -1/(N-1); even mild smoothing")
    print("  pushes I strongly positive, and I keeps rising with length.")

    section("2. Experimental semivariogram of the length-2.0 field")
    white = RNG.standard_normal((NY, NX))
    field = gaussian_filter(white, sigma=2.0, mode="wrap")
    var = field.var()
    print(f"  field variance (sill estimate) = {var:.3f}")
    print("  lag (cells)   semivariance   fraction of sill")
    for lag in (1, 2, 3, 5, 8, 12, 15):
        g = semivariance(field, lag)
        print(f"  {lag:9d}   {g:12.4f}   {g / var:15.3f}")
    print("  the semivariance grows with lag and approaches the sample variance")
    print("  (the sill); the lag at which it stops growing is the range, the")
    print("  topic of module 21-02.")

    section("3. Circular statistics of SYNTHETIC bearings")
    for kappa, label in ((0.0, "uniform (no preferred direction)"),
                         (3.0, "von Mises, kappa = 3")):
        theta = stats.vonmises.rvs(kappa, loc=np.deg2rad(45.0), size=60,
                                   random_state=RNG)
        c = np.cos(theta).mean()
        s = np.sin(theta).mean()
        r_bar = np.hypot(c, s)
        mu_hat = np.rad2deg(np.arctan2(s, c)) % 360.0
        z = theta.size * r_bar ** 2
        p = float(np.exp(-z))
        print(f"  {label}")
        print(f"    circular mean direction = {mu_hat:6.2f} deg, "
              f"resultant length R = {r_bar:.4f}")
        print(f"    Rayleigh Z = n R^2 = {z:.3f}, p = exp(-Z) = {p:.2e}")
    print("  R is 0 for a uniform direction distribution and approaches 1 for a")
    print("  tight cluster; the Rayleigh test uses exactly that contrast.")


if __name__ == "__main__":
    main()
