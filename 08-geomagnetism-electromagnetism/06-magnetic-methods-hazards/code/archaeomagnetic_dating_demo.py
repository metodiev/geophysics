#!/usr/bin/env python3
"""Archaeomagnetic dating: a synthetic secular-variation curve, the direction-age
mapping, its precision and its ambiguity, and the geocentric axial dipole check.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python archaeomagnetic_dating_demo.py

Everything here is SYNTHETIC.  The secular-variation curve is generated by this
script from a few damped oscillators plus a random walk; it is a teaching curve,
NOT a reference curve for any region, and no archaeological site or published date
is used.  All numbers are printed by this script.

Contents
--------
1. The geocentric axial dipole: inclination against latitude.
2. A synthetic secular-variation curve (declination and inclination vs time).
3. Dating a measured direction: candidate ages, precision and ambiguity.
4. A systematic curve bias and the date error it produces.
5. What a date from archaeomagnetic directions is a statement about.
"""

import numpy as np

MU0 = 4.0e-7 * np.pi          # H/m, exact in SI
RNG = np.random.default_rng(20261014)

SITE_LAT = 45.0               # degrees, SYNTHETIC site latitude
YEARS = np.arange(-2000.0, 0.0, 5.0)   # years before present, 5-year steps


def section(title):
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


def gad_inclination(lat_deg):
    """Geocentric axial dipole inclination: tan(I) = 2 tan(latitude)."""
    return np.degrees(np.arctan(2.0 * np.tan(np.radians(lat_deg))))


def dipole_field(lat_deg, m=8.0e22):
    """Field of a centred dipole: |B| at the surface, and the inclination."""
    r = 6371.0e3                      # m, Earth radius (exact standard value)
    theta = np.radians(90.0 - lat_deg)
    b_r = 2.0 * MU0 * m * np.cos(theta) / (4.0 * np.pi * r ** 3)
    b_t = MU0 * m * np.sin(theta) / (4.0 * np.pi * r ** 3)
    return np.sqrt(b_r ** 2 + b_t ** 2), np.degrees(np.arctan2(b_r, -b_t))


def synthetic_sv_curve(t):
    """A SYNTHETIC secular-variation curve: damped oscillators plus a random walk.

    Declination and inclination in degrees.  The periods (700, 1400, 2500 years)
    and amplitudes are chosen for teaching; this is not a regional curve.
    """
    d = (8.0 * np.sin(2 * np.pi * (t + 200.0) / 700.0)
         + 5.0 * np.exp(t / 3000.0) * np.sin(2 * np.pi * (t + 60.0) / 1400.0)
         + 3.0 * np.sin(2 * np.pi * (t + 900.0) / 2500.0))
    inc0 = gad_inclination(SITE_LAT)
    di = (2.5 * np.sin(2 * np.pi * (t + 300.0) / 900.0)
          - 1.5 * np.cos(2 * np.pi * (t + 100.0) / 2000.0))
    walk = np.cumsum(RNG.standard_normal(t.size)) * 0.02
    walk = walk - walk.mean()
    return d + walk, inc0 + di


def angular_distance(d1, i1, d2, i2):
    """Great-circle angular distance between two directions, in degrees."""
    d1, i1, d2, i2 = map(np.radians, (d1, i1, d2, i2))
    cos_g = (np.sin(i1) * np.sin(i2)
             + np.cos(i1) * np.cos(i2) * np.cos(d1 - d2))
    return np.degrees(np.arccos(np.clip(cos_g, -1.0, 1.0)))


def main():
    section("1. The geocentric axial dipole: inclination against latitude")
    print("  exact standard constants: Earth radius 6371 km, mu0 = 4 pi x 10^-7 H/m")
    print("\n   latitude (deg)   GAD inclination (deg)   field magnitude (microT)")
    for lat in (0.0, 15.0, 30.0, 45.0, 60.0, 75.0, 90.0):
        inc = gad_inclination(lat)
        mag, inc2 = dipole_field(lat)
        print(f"  {lat:14.1f}   {inc:21.3f}   {mag * 1e6:24.1f}")
    print("  tan I = 2 tan(latitude) is exact for a centred dipole; the synthetic")
    print("  site below is at 45 degrees, where it predicts I = "
          f"{gad_inclination(SITE_LAT):.3f} degrees.")
    print("  The magnitude is quoted for a dipole moment of 8.0e22 A m^2, which is")
    print("  the SYNTHETIC dipole used throughout this demonstration, not a")
    print("  measured value of the geomagnetic moment.")

    section("2. A synthetic secular-variation curve")
    dec, inc = synthetic_sv_curve(YEARS)
    print(f"  SYNTHETIC curve, {YEARS.size} samples from {YEARS[0]:.0f} to "
          f"{YEARS[-1]:.0f} years before present, 5-year steps")
    print(f"  declination range {dec.min():+.2f} to {dec.max():+.2f} degrees")
    print(f"  inclination range {inc.min():+.2f} to {inc.max():+.2f} degrees")
    print("\n   year (BP)   declination (deg)   inclination (deg)")
    for i in range(0, YEARS.size, 100):
        print(f"  {YEARS[i]:9.0f}   {dec[i]:17.2f}   {inc[i]:17.2f}")
    rate = np.gradient(dec, YEARS)
    print(f"\n  median |dD/dt| = {np.median(np.abs(rate)) * 100:.3f} degrees per")
    print("  century: this sets the conversion from an angular uncertainty to an")
    print("  age uncertainty, and it is the whole reason archaeomagnetic dating")
    print("  works at all in a region with a fast-moving direction.")

    section("3. Dating a measured direction")
    print("  A SYNTHETIC measured direction is taken from the curve at a known")
    print("  age and perturbed by an angular uncertainty:")
    idx_true = 250                            # index into YEARS
    t_true = YEARS[idx_true]
    d_meas = dec[idx_true] + 1.0              # SYNTHETIC measurement error, deg
    i_meas = inc[idx_true] - 0.8
    print(f"    true age {t_true:.0f} BP; measured D = {d_meas:.2f}, "
          f"I = {i_meas:.2f} degrees")
    for tol in (1.0, 2.0, 3.0, 5.0):
        ang = angular_distance(d_meas, i_meas, dec, inc)
        cand = YEARS[ang < tol]
        print(f"    tolerance {tol:.1f} deg: {cand.size * 5:4d} years of samples "
              f"pass, in {len(np.split(cand, np.where(np.diff(cand) > 10)[0] + 1)) if cand.size else 0} interval(s)")
    tol = 2.0
    ang = angular_distance(d_meas, i_meas, dec, inc)
    inside = ang < tol
    intervals = []
    start = None
    for k, ok in enumerate(inside):
        if ok and start is None:
            start = k
        if not ok and start is not None:
            intervals.append((YEARS[start], YEARS[k - 1]))
            start = None
    if start is not None:
        intervals.append((YEARS[start], YEARS[-1]))
    print(f"\n  with a {tol:.1f} degree tolerance the admissible ages are:")
    for lo, hi in intervals:
        mid = 0.5 * (lo + hi)
        print(f"    {lo:7.0f} to {hi:7.0f} BP  (width {hi - lo:4.0f} yr, "
              f"midpoint {mid:7.0f})")
    print("  Each interval is a candidate date.  Two intervals mean the direction")
    print("  curve passes through the measured direction twice: the date is")
    print("  ambiguous, and the ambiguity is a property of the CURVE, not of the")
    print("  measurement.  Resolving it needs stratigraphy, radiocarbon, or a")
    print("  second independent material.")

    section("4. Precision: angular uncertainty against rate of change")
    print("  If the direction moves at a rate of R degrees per century and the")
    print("  measurement is good to s degrees, a first-order estimate of the age")
    print("  precision is s/R centuries.  Measured from the curve:")
    print("\n   true age (BP)   |dD/dt| (deg/century)   s = 1 deg -> age (yr)"
          "   s = 3 deg -> age (yr)")
    for t0 in (-1800.0, -1200.0, -600.0, -200.0):
        k = int(np.argmin(np.abs(YEARS - t0)))
        loc_rate = abs(np.gradient(dec, YEARS)[k]) * 100.0
        print(f"  {YEARS[k]:13.0f}   {loc_rate:20.3f}   "
              f"{1.0 / loc_rate * 100:20.0f}   {3.0 / loc_rate * 100:19.0f}")
    print("  The precision is therefore a property of the CURVE at the epoch being")
    print("  dated, not of the measurement alone: at 1800 BP the direction moves at")
    print("  2.0 degrees per century and a 1 degree measurement dates to about half")
    print("  a century, while at 200 BP it moves at 8.9 degrees per century and the")
    print("  same measurement dates to 11 years.  Where the direction stands still")
    print("  (a 'still-stand' in the curve), even a perfect measurement dates")
    print("  nothing precisely, and a region without a well-constrained curve simply")
    print("  cannot be dated archaeomagnetically for that epoch.")

    section("5. A systematic curve bias")
    print("  Suppose the local curve is offset from the reference curve used for")
    print("  dating by a constant declination delta, as a tectonic rotation or a")
    print("  non-dipole field offset would produce.  Recover the date of the same")
    print("  measurement against the offset curve:")
    print("\n   offset (deg)   recovered age (BP)   age error (yr)")
    for delta in (0.0, 0.5, 1.0, 2.0, 4.0):
        ang_off = angular_distance(d_meas, i_meas, dec + delta, inc)
        k_best = int(np.argmin(ang_off))
        err = YEARS[k_best] - t_true
        print(f"  {delta:12.1f}   {YEARS[k_best]:19.0f}   {err:+12.0f}")
    print("  A one-degree offset moves the date by a few decades here, in proportion")
    print("  to 1/(rate of change), and a four-degree offset jumps to a completely")
    print("  different branch of the curve (a 575-year error).  That is why an")
    print("  archaeomagnetic date is only as good as the secular-variation curve it")
    print("  is compared with, and why curves are regional and are published with")
    print("  their own uncertainty envelopes.")

    section("6. What the date is a statement about")
    print("  An archaeomagnetic direction date is a statement of the form: the last")
    print("  heating of this material occurred at a time when the field direction,")
    print("  as recorded by THIS material and compared with THIS curve, matched the")
    print("  measured direction.  It is not a statement about when a structure was")
    print("  built, unless the heating event and the construction are independently")
    print("  linked.  Four failure modes to state explicitly:")
    print("    1. the material did not acquire a stable thermoremanent moment;")
    print("    2. the material moved (tilted, rotated, slumped) after cooling;")
    print("    3. the reference curve is wrong for this site and epoch;")
    print("    4. the direction is ambiguous on the curve (Section 3).")
    print("  Numbers 1 and 2 are measured in the laboratory; 3 and 4 are")
    print("  statements about the curve, and they are the ones this script can")
    print("  quantify.")


if __name__ == "__main__":
    main()
