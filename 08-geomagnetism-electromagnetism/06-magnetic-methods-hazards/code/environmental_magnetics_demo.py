#!/usr/bin/env python3
"""Environmental magnetism: the magnetic anomaly of a buried body, the
moment-depth (depth-to-size) ambiguity, the detection limit with depth, and the
proxy relationship between susceptibility and a pollutant concentration.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python environmental_magnetics_demo.py

Everything here is SYNTHETIC.  The bodies, susceptibilities, concentrations and
noise are generated by this script from a fixed seed; there is no real site,
sample or measured pollutant.  All numbers are printed by this script.

Contents
--------
1. The vertical-field anomaly of a magnetised body, and the (2/3) chi H (a/d)^3
   scaling.
2. The depth-to-size ambiguity: one anomaly, many bodies.
3. The detection limit: how deep a body can be seen, and how weakly it depends on
   its magnetisation.
4. A synthetic anomaly map from a synthetic susceptibility field.
5. Susceptibility as a proxy: correlation, scatter and the limits of the claim.
"""

import numpy as np

MU0 = 4.0e-7 * np.pi          # H/m, exact in SI
RNG = np.random.default_rng(20261014)

H_FIELD = 48.0                # A/m, SYNTHETIC ambient field (about 60 microtesla)
B_NOISE = 1.0e-9              # T, SYNTHETIC instrument noise (1 nT)


def section(title):
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


def sphere_anomaly(chi, radius, depth, h_field=H_FIELD):
    """Vertical-field anomaly (T) directly above a uniformly magnetised sphere.

    Induced moment m = chi H V with V = 4/3 pi a^3; the field of a vertical dipole
    at horizontal offset rho and depth d is H_z = m (2 d^2 - rho^2)/(4 pi R^5)
    with R^2 = rho^2 + d^2, so directly above the body

        B_z = mu0 H_z = mu0 chi H (4/3) pi a^3 (2 d^2)/(4 pi d^5)
            = (2/3) chi H (a/d)^3 mu0.
    """
    return (2.0 / 3.0) * chi * h_field * (radius / depth) ** 3 * MU0


def sphere_profile(chi, radius, depth, offsets, h_field=H_FIELD):
    """Vertical-field anomaly (T) on a profile at horizontal offsets (m)."""
    moment = chi * h_field * (4.0 / 3.0) * np.pi * radius ** 3
    rho = np.asarray(offsets, dtype=float)
    r5 = (rho ** 2 + depth ** 2) ** 2.5
    return MU0 * moment * (2.0 * depth ** 2 - rho ** 2) / (4.0 * np.pi * r5)


def main():
    section("1. The anomaly of a buried magnetised body")
    print("  SYNTHETIC ambient field H = 48 A/m (about 60 microtesla); induced")
    print("  magnetisation only, no remanence")
    print("\n   chi (SI)   radius (m)   depth (m)   a/d    anomaly (nT)")
    for chi, radius, depth in ((1.0e-3, 2.0, 5.0), (1.0e-3, 2.0, 10.0),
                               (1.0e-2, 2.0, 5.0), (1.0e-2, 5.0, 5.0),
                               (1.0e-2, 5.0, 20.0), (1.0e-1, 5.0, 20.0)):
        b = sphere_anomaly(chi, radius, depth)
        print(f"  {chi:10.4f}   {radius:10.1f}   {depth:9.1f}   "
              f"{radius / depth:5.2f}   {b * 1e9:12.3f}")
    print("  The anomaly is (2/3) chi H (a/d)^3 mu0: it depends on the"
          " susceptibility,")
    print("  the ambient field and the CUBE of the ratio of radius to depth.")
    print("  Read the table as three separate scalings: doubling the radius")
    print("  multiplies the anomaly by 8, doubling the depth divides it by 8, and a")
    print("  tenfold larger susceptibility multiplies it by 10.  The first two are")
    print("  geometry and are set by nature; the third is a property of the ground")
    print("  that the survey can only infer, never choose.  That asymmetry is why a")
    print("  magnetic anomaly is an excellent detector and a poor quantifier.")

    section("2. The depth-to-size ambiguity")
    chi = 1.0e-2
    b_target = 20.0e-9                      # nT, a SYNTHETIC observed anomaly
    print(f"  A survey measures an anomaly of {b_target * 1e9:.1f} nT directly")
    print(f"  above a body of unknown size and depth, with chi = {chi:.4f} and")
    print("  H = 48 A/m.  Solve (2/3) chi H (a/d)^3 mu0 = B for the radius:")
    print("\n   depth (m)   required radius (m)   required volume (m^3)")
    for depth in (2.0, 5.0, 10.0, 20.0, 50.0):
        radius = depth * (b_target / ((2.0 / 3.0) * chi * H_FIELD * MU0)) ** (1.0 / 3.0)
        vol = 4.0 / 3.0 * np.pi * radius ** 3
        print(f"  {depth:9.1f}   {radius:19.2f}   {vol:20.1f}")
    radius5 = 5.0 * (b_target / ((2.0 / 3.0) * chi * H_FIELD * MU0)) ** (1.0 / 3.0)
    print(f"\n  A radius of {radius5:.2f} m at 5 m and of "
          f"{radius5 * 10:.2f} m at 50 m produce the same anomaly to three")
    print("  figures: the measurement constrains a^3/d^3, i.e. the ratio a/d, and")
    print("  never a and d separately.  This is the fundamental non-uniqueness of")
    print("  applied magnetics, and it is why depth estimates from magnetic")
    print("  anomalies must be accompanied by an assumed or independently measured")
    print("  body size (or by a shape-dependent method such as Euler deconvolution,")
    print("  which trades that ambiguity for a structural index).")

    section("3. Detection limit: how deep can a body be seen?")
    print(f"  SYNTHETIC noise floor {B_NOISE * 1e9:.1f} nT.  A body is detectable")
    print("  when its anomaly exceeds the noise:")
    print("\n   chi (SI)   radius (m)   maximum depth (m)   anomaly at that depth (nT)")
    for chi in (1.0e-3, 1.0e-2, 1.0e-1):
        for radius in (2.0, 5.0, 20.0):
            d_max = radius * ((2.0 / 3.0) * chi * H_FIELD * MU0 / B_NOISE) ** (1.0 / 3.0)
            print(f"  {chi:10.4f}   {radius:10.1f}   {d_max:17.2f}   "
                  f"{B_NOISE * 1e9:29.3f}")
    print("  The maximum depth scales as (chi)^{1/3} a: a HUNDREDFOLD increase in")
    print("  susceptibility buys only a 4.6-fold increase in detectable depth, and a")
    print("  hundredfold better instrument buys the same.  Magnetometry is")
    print("  therefore inherently a shallow method - tens of metres for")
    print("  centimetre-to-metre scale sources - and the cube root is the reason.")

    section("4. A synthetic anomaly map")
    nx = ny = 60
    dx = 2.0                                  # m
    x = np.arange(nx) * dx
    y = np.arange(ny) * dx
    xx, yy = np.meshgrid(x, y)
    bodies = [(15.0, 30.0, 1.0e-2, 3.0, 8.0),
              (80.0, 40.0, 5.0e-3, 4.0, 15.0),
              (50.0, 90.0, 2.0e-2, 2.0, 5.0)]
    grid = np.zeros_like(xx)
    for bx, by, chi, radius, depth in bodies:
        grid += sphere_profile(chi, radius, depth,
                               np.hypot(xx - bx, yy - by).ravel()).reshape(xx.shape)
    grid += B_NOISE * RNG.standard_normal(grid.shape)
    print(f"  SYNTHETIC {nx} x {ny} grid, {dx:.0f} m spacing, three induced-dipole")
    print("  bodies plus 1 nT of noise:")
    print("\n   body   east (m)   north (m)   chi      radius (m)   depth (m)"
          "   peak anomaly (nT)")
    for i, (bx, by, chi, radius, depth) in enumerate(bodies, start=1):
        print(f"  {i:4d}   {bx:8.1f}   {by:9.1f}   {chi:7.4f}   {radius:10.1f}"
              f"   {depth:9.1f}   {sphere_anomaly(chi, radius, depth) * 1e9:15.2f}")
    print(f"\n  map statistics: min {grid.min() * 1e9:+.2f} nT, "
          f"max {grid.max() * 1e9:+.2f} nT, rms {grid.std() * 1e9:.3f} nT")
    print("  Every peak in this map is a dipole; the sign pattern (a positive")
    print("  centre with negative lobes in mid-latitudes for induced magnetisation)")
    print("  is what allows a human or an algorithm to pick bodies out, and the")
    print("  cube-of-depth dependence is what makes the deep body a broad, weak")
    print("  smudge rather than a peak.")

    section("5. Susceptibility as a proxy for a pollutant")
    n = 40
    true_conc = np.abs(20.0 + 15.0 * RNG.standard_normal(n))      # arbitrary units
    # two SYNTHETIC sites: a strong and a weak relationship
    chi_strong = 0.4 * true_conc / true_conc.mean() * 1e-3 * (1.0 + 0.15 * RNG.standard_normal(n))
    chi_weak = 0.4 * (1.0 + 0.6 * RNG.standard_normal(n)) * 1e-3
    print(f"  {n} SYNTHETIC samples; 'true concentration' is an arbitrary index")
    print("  and the two susceptibility sets model a site where the magnetic")
    print("  minerals and the pollutant share a source, and a site where they do")
    print("  not:")
    print("\n   data set        Pearson r   r^2     slope (per unit concentration)"
          "   intercept (1e-3 SI)")
    for label, chi in (("shared source", chi_strong), ("independent", chi_weak)):
        r = np.corrcoef(true_conc, chi)[0, 1]
        fit = np.polyfit(true_conc, chi, 1)
        print(f"  {label:14s}   {r:9.3f}   {r ** 2:5.3f}   {fit[0]:34.3e}   "
              f"{-fit[1] * 1e3:20.4f}")
    print("  The shared-source site gives r = "
          f"{np.corrcoef(true_conc, chi_strong)[0, 1]:.3f}; the independent site "
          f"gives")
    print(f"  r = {np.corrcoef(true_conc, chi_weak)[0, 1]:.3f}.  A high correlation")
    print("  is evidence about the CO-GENESIS of magnetic minerals and the pollutant,")
    print("  not about the pollutant's concentration: the slope is site-specific and")
    print("  must be calibrated against chemical analyses from the same site.  Using")
    print("  a published slope from another site is the commonest error in applied")
    print("  environmental magnetism.")


if __name__ == "__main__":
    main()
