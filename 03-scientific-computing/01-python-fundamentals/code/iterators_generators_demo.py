"""Iterators, generators and lazy evaluation for large data.

Run:  python3 iterators_generators_demo.py
Requires: Python standard library only.

Companion to lesson 03-01-09.  The lesson's claim is measurable: a pipeline of
generators processes a large file with a memory footprint that does not depend
on the size of the file.  This script writes a SYNTHETIC catalogue of 200,000
rows, processes it twice - once eagerly, once lazily - and reports the peak
tracked memory from tracemalloc for each.

The scratch directory is created next to this script and removed on exit.

Demonstrates:

1. The iterator protocol: iter(), next(), StopIteration.
2. A generator function, and its laziness made visible with a print.
3. A pipeline of generators: read -> parse -> filter -> aggregate.
4. Peak memory: eager list versus lazy pipeline, measured.
5. Generator expressions, itertools.islice on an infinite generator, and
   yield from.
6. The one real cost of laziness: a generator can be consumed only once.
"""

import itertools
import random
import shutil
import time
import tracemalloc
from pathlib import Path

SEED = 20261014
N_EVENTS = 200_000
HERE = Path(__file__).resolve().parent
SCRATCH = HERE / "_scratch_gen"
CATALOGUE = SCRATCH / "synthetic_big_catalogue.csv"


def section(title):
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


def write_catalogue(path, n=N_EVENTS, seed=SEED):
    """Write a SYNTHETIC catalogue of n rows as plain delimited text."""
    rng = random.Random(seed)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write("# SYNTHETIC catalogue generated by iterators_generators_demo.py\n")
        handle.write("event_id,latitude,longitude,depth_km,magnitude\n")
        for i in range(n):
            handle.write(
                f"SYN{i:06d},{rng.uniform(-70, 70):.4f},{rng.uniform(-180, 180):.4f},"
                f"{rng.uniform(1, 60):.2f},{rng.uniform(-1, 3):.2f}\n")


# --------------------------------------------------------------------------
# The lazy pipeline: three generator functions, each one small
# --------------------------------------------------------------------------

def iter_lines(path):
    """Yield the non-comment lines of a file, one at a time."""
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if not line.startswith("#"):
                yield line


def iter_records(lines):
    """Yield parsed records from an iterable of lines.

    The header row is skipped by an explicit index rather than by guessing
    whether a field is numeric - guessing is how a real event named 'SYN0000'
    gets silently dropped.
    """
    for index, line in enumerate(lines):
        if index == 0:
            continue
        event_id, lat, lon, depth, mag = line.rstrip("\n").split(",")
        yield (event_id, float(lat), float(lon), float(depth), float(mag))


def select(records, mc):
    """Yield only the records with magnitude >= mc."""
    for record in records:
        if record[4] >= mc:
            yield record


def depths(records):
    """Yield the depth field of each record."""
    for record in records:
        yield record[3]


def pipeline(path, mc):
    """The whole pipeline as one expression: nothing runs until consumed."""
    return depths(select(iter_records(iter_lines(path)), mc))


# --------------------------------------------------------------------------
# Demonstrations
# --------------------------------------------------------------------------

def part1_protocol():
    section("1. The iterator protocol, without any generators")
    values = iter([10.0, 20.0])
    print(f"  iter([10, 20]) -> {values}")
    print(f"  next(values)   = {next(values)}")
    print(f"  next(values)   = {next(values)}")
    try:
        next(values)
    except StopIteration as exc:
        print(f"  next(values)   -> StopIteration: {exc!r}")
    print()
    print("  A for loop is exactly this: call next() until StopIteration, then")
    print("  swallow the exception.  Everything else in this file is built on")
    print("  those two operations.")


def part2_laziness():
    section("2. A generator is lazy: nothing happens until you ask")
    print("  defining the generator...")

    def counting(maximum):
        print("    [generator body entered]")
        for i in range(maximum):
            print(f"    [yielding {i}]")
            yield i

    gen = counting(3)
    print("  generator created; no body has run yet")
    print(f"  first next()  -> {next(gen)}")
    print(f"  second next() -> {next(gen)}")
    print("  only two of the three yields have happened: the function is")
    print("  suspended at the second yield, holding its own local state.")
    print(f"  remaining     -> {list(gen)}")


def part3_pipeline():
    section("3. The pipeline, evaluated lazily")
    write_catalogue(CATALOGUE)
    size_mb = CATALOGUE.stat().st_size / 1e6
    print(f"  catalogue: {CATALOGUE.name}, {size_mb:.1f} MB, {N_EVENTS:,} rows")
    mc = 2.0
    print(f"  selecting magnitudes >= {mc}")
    start = time.perf_counter()
    n_total = n_selected = 0
    depth_sum = 0.0
    for depth in pipeline(CATALOGUE, mc):
        n_selected += 1
        depth_sum += depth
    elapsed = time.perf_counter() - start
    print(f"  selected   : {n_selected:,} events in {elapsed:.2f} s")
    print(f"  mean depth : {depth_sum / n_selected:.3f} km")
    print()
    print("  At no point did the program hold more than one row, plus the")
    print("  running totals.  The memory cost is O(1) in the file size.")


def part4_memory():
    section("4. Peak memory: eager list versus lazy pipeline, measured")
    mc = 2.0
    tracemalloc.start()
    eager = list(iter_records(iter_lines(CATALOGUE)))
    eager_selected = [r for r in eager if r[4] >= mc]
    eager_mean = sum(r[3] for r in eager_selected) / len(eager_selected)
    current_eager, peak_eager = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    del eager, eager_selected

    tracemalloc.start()
    n_selected = 0
    depth_sum = 0.0
    for depth in pipeline(CATALOGUE, mc):
        n_selected += 1
        depth_sum += depth
    lazy_mean = depth_sum / n_selected
    current_lazy, peak_lazy = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    import math
    rel = abs(eager_mean - lazy_mean) / lazy_mean
    same = math.isclose(eager_mean, lazy_mean, rel_tol=1e-12, abs_tol=0.0)
    print(f"  eager  : peak {peak_eager / 1e6:8.2f} MB, mean depth {eager_mean:.6f} km")
    print(f"  lazy   : peak {peak_lazy / 1e6:8.2f} MB, mean depth {lazy_mean:.6f} km")
    print(f"  ratio  : {peak_eager / peak_lazy:.0f}x less memory")
    print(f"  absolute difference in the mean: {abs(eager_mean - lazy_mean):.2e} km"
          f"  ({rel:.1e} relative)")
    print(f"  agrees to 1e-12 relative: {same}")
    print()
    print("  The two means differ in the last two digits because floating-point")
    print("  addition is not associative: the eager version sums the depths in")
    print("  the order they appear after a separate pass, the lazy one in")
    print("  selection order.  Both are correct to fourteen digits; neither is")
    print("  'the' answer.  tracemalloc counts Python-level allocations, so the")
    print("  memory numbers are indicative, not exact - the scaling is the")
    print(f"  point: the eager peak grows linearly with {N_EVENTS:,} rows, the")
    print("  lazy peak does not move.")


def part5_expressions():
    section("5. Generator expressions, islice and yield from")
    squares = (x * x for x in range(8))
    print(f"  generator expression : {squares}")
    print(f"  sum of squares       : {sum(squares)}")

    def magnitudes_infinite(start=1.0, step=0.1):
        """An INFINITE synthetic magnitude sequence - never materialise it."""
        value = start
        while True:
            yield round(value, 1)
            value += step

    first_ten = list(itertools.islice(magnitudes_infinite(), 10))
    print(f"  islice on an infinite generator: {first_ten}")

    def chained():
        yield from (1.0, 2.0)
        yield from [3.0, 4.0]

    print(f"  yield from          : {list(chained())}")

    def flatten(nested):
        for group in nested:
            yield from group

    print(f"  flatten(3 groups)   : {list(flatten([[1, 2], [3], [4, 5]]))}")
    print()
    print("  itertools.islice is how you take a finite prefix of an infinite")
    print("  sequence without writing a counter.  'yield from' delegates to a")
    print("  sub-iterable without a hand-written inner loop.")


def part6_single_use():
    section("6. The price of laziness: a generator is consumed once")
    gen = iter_records(iter_lines(CATALOGUE))
    first = next(gen)
    rest = sum(1 for _ in gen)
    print(f"  first record        : {first}")
    print(f"  remaining records   : {rest:,}")
    print(f"  sum(1 for _ in gen) again -> {sum(1 for _ in gen)}  (exhausted)")
    print()
    print(f"  The file holds {N_EVENTS:,} data rows plus a comment line and a")
    print("  header, so the generator yields every data row exactly once and")
    print("  then stops for good.")
    print("  A generator cannot be rewound.  If you need two passes, either")
    print("  re-open the file or materialise the data deliberately - and state")
    print("  which you chose in a comment, because the memory cost differs by")
    print("  orders of magnitude.")


def cleanup():
    shutil.rmtree(SCRATCH, ignore_errors=True)
    print(f"\n  scratch directory removed: {not SCRATCH.exists()}")


if __name__ == "__main__":
    part1_protocol()
    part2_laziness()
    part3_pipeline()
    part4_memory()
    part5_expressions()
    part6_single_use()
    cleanup()
