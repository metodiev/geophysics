"""Files, text I/O and data encodings, on a synthetic earthquake catalogue.

Run:  python3 files_io_demo.py
Requires: Python standard library only.

Companion to lesson 03-01-06.  Everything this script reads, it first wrote:
the catalogue is **SYNTHETIC**, generated below from a fixed seed, and it is
labelled as such in its own header line.  No real earthquake catalogue is
downloaded or embedded.

The scratch directory is created next to this script and removed on exit; the
demo never writes outside the module directory.

Demonstrates:

1. pathlib, and why you do not join paths with '/'.
2. csv.writer with a header and a comment line; RFC-4180 quoting.
3. csv.DictReader and the difference between a row and a record.
4. Encodings: UTF-8, UTF-8 with BOM, Latin-1, and the failure modes.
5. Line endings: '\\n' versus '\\r\\n', and why newline='' is mandatory.
6. Streaming a file line by line, and counting lines without loading them.
"""

import csv
import io
import math
import random
import shutil
from pathlib import Path

SEED = 20261014
N_EVENTS = 500
HERE = Path(__file__).resolve().parent
SCRATCH = HERE / "_scratch_io"
CATALOGUE = SCRATCH / "synthetic_catalogue.csv"

HEADER_COMMENT = "# SYNTHETIC data generated by files_io_demo.py - not a real catalogue"


def section(title):
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


def write_catalogue(path: Path) -> None:
    """Write a synthetic catalogue with a comment line, a header and n rows."""
    rng = random.Random(SEED)
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="" hands line-ending control to the csv module, which is what
    # RFC 4180 requires; without it you get blank lines on Windows.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(HEADER_COMMENT + "\n")
        writer = csv.writer(handle)
        writer.writerow(["event_id", "time_utc", "latitude", "longitude",
                         "depth_km", "magnitude", "place"])
        for i in range(N_EVENTS):
            magnitude = round(-1.0 + 4.0 * rng.random(), 2)
            writer.writerow([
                f"SYN{i:05d}",
                f"2026-{rng.randrange(1, 13):02d}-{rng.randrange(1, 29):02d}"
                f"T{rng.randrange(24):02d}:{rng.randrange(60):02d}:00Z",
                round(-70.0 + 140.0 * rng.random(), 4),
                round(-180.0 + 360.0 * rng.random(), 4),
                round(1.0 + 60.0 * rng.random(), 2),
                magnitude,
                "Zürich" if i % 97 == 0 else f"Station-{i % 13:02d}",
            ])


def part1_write_then_look():
    section("1. Write it, then look at the raw bytes")
    write_catalogue(CATALOGUE)
    size = CATALOGUE.stat().st_size
    print(f"  wrote {CATALOGUE.name}: {size:,} bytes")
    print("  first four lines as they sit on disk:")
    with CATALOGUE.open("r", encoding="utf-8") as handle:
        for _ in range(4):
            print("    " + handle.readline().rstrip("\n"))
    print()
    print("  The first line begins with '#': a de-facto convention for a")
    print("  comment, not part of any CSV standard.  Every consumer of this")
    print("  file must skip it, which is exactly the kind of assumption that")
    print("  should be written down in a README beside the data.")


def part2_read_rows():
    section("2. Reading it back: csv.reader and csv.DictReader")
    with CATALOGUE.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle))
    print(f"  csv.reader gave {len(rows)} rows (including the comment and header)")
    print(f"  first data row as a list : {rows[2]}")
    print()
    with CATALOGUE.open("r", encoding="utf-8", newline="") as handle:
        records = [row for row in csv.DictReader(
            line for line in handle if not line.startswith("#"))]
    print(f"  csv.DictReader gave {len(records)} records")
    print(f"  first record: {records[0]}")
    print()
    magnitudes = [float(r["magnitude"]) for r in records]
    depths = [float(r["depth_km"]) for r in records]
    places = [r["place"] for r in records]
    print(f"  magnitude range : {min(magnitudes):.2f} to {max(magnitudes):.2f}")
    print(f"  depths          : mean {sum(depths) / len(depths):.2f} km,"
          f" deepest {max(depths):.2f} km")
    print(f"  distinct places : {len(set(places))}")
    print()
    print("  A *row* is a list of strings and nothing else: no types, no units.")
    print("  Converting to a typed record is your job, and forgetting it is how")
    print("  '2.5' * 2 becomes '2.52.5' instead of 5.0.")


def part3_quoting():
    section("3. Quoting: a field containing the delimiter")
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["SYN00001", "Zürich, Switzerland", "-1.5"])
    written = buffer.getvalue()
    print(f"  written: {written!r}")
    back = next(csv.reader(io.StringIO(written)))
    print(f"  read back: {back}")
    print(f"  the comma survived inside the field: {back[1] == 'Zürich, Switzerland'}")
    print()
    print("  Splitting on commas by hand fails here.  Use csv; it implements")
    print("  the quoting rules, including embedded quotes and embedded newlines.")


def part4_encodings():
    section("4. Encodings: the same text, three byte sequences")
    text = "Zürich 47.3769° N"
    for encoding in ("utf-8", "utf-8-sig", "latin-1", "ascii"):
        try:
            raw = text.encode(encoding)
            print(f"  {encoding:<10} {len(raw):>3} bytes  {raw[:24]!r}")
        except UnicodeEncodeError as exc:
            print(f"  {encoding:<10} FAILS to encode: {exc.reason}")
    print()
    print("  Note that latin-1 succeeds here and ascii does not: the umlaut and")
    print("  the degree sign are single Latin-1 bytes, but they are not ASCII.")
    print()
    dash = "Zürich – 47.3769° N"
    try:
        dash.encode("latin-1")
    except UnicodeEncodeError as exc:
        print(f"  Add a single en dash (U+2013) and latin-1 fails: {exc.reason}")
    print("  Latin-1 cannot represent the dash, the euro sign, or any of the")
    print("  typographic characters that arrive from a word processor.  UTF-8")
    print("  can represent all of them, which is why it is the default.")
    print()
    utf8_bytes = text.encode("utf-8")
    latin1_bytes = text.encode("latin-1")
    print("  Decoding with the WRONG codec does not always raise:")
    print(f"    utf-8 bytes read as latin-1 ->"
          f" {utf8_bytes.decode('latin-1')!r}")
    print(f"    latin-1 bytes read as utf-8 -> ", end="")
    try:
        print(repr(latin1_bytes.decode("utf-8")))
    except UnicodeDecodeError as exc:
        print(f"UnicodeDecodeError: {exc.reason} at byte {exc.start}")
    print()
    print("  Mojibake (the first case) is worse than a crash: it is silent.")
    print("  The second case fails loudly, which is what you want.")
    print("  UTF-8 with a byte-order mark is 'utf-8-sig' on read and write; on")
    print("  Linux and macOS a BOM is an annoyance, on Windows it is common.")


def part5_line_endings():
    section("5. Line endings, and the newline='' rule")
    text_path = SCRATCH / "endings.txt"
    with text_path.open("w", encoding="utf-8", newline="") as handle:
        handle.write("a\r\nb\nc\r\n")
    raw = text_path.read_bytes()
    print(f"  bytes written with newline='' : {raw!r}")
    with text_path.open("r", encoding="utf-8", newline="") as handle:
        lines_raw = handle.readlines()
    print(f"  read with newline=''          : {lines_raw!r}")
    with text_path.open("r", encoding="utf-8") as handle:
        lines_normalised = handle.readlines()
    print(f"  read with universal newlines  : {lines_normalised!r}")
    print()
    print("  Universal-newline mode translates \\r\\n to \\n on read, which is")
    print("  what you want for text.  For csv you must pass newline='' so the")
    print("  reader sees the file as written - otherwise an embedded, quoted")
    print("  newline can be mistaken for a record separator.")


def part6_streaming():
    section("6. Streaming: never load a file to count it")
    with CATALOGUE.open("r", encoding="utf-8") as handle:
        n_lines = sum(1 for _ in handle)
    print(f"  lines counted by iteration : {n_lines}")
    with CATALOGUE.open("r", encoding="utf-8") as handle:
        n_readlines = len(handle.readlines())
    print(f"  lines counted by readlines : {n_readlines}")
    print()
    print("  The first version holds one line at a time; the second holds the")
    print("  whole file.  For a 500-line file the difference is invisible; for")
    print("  a 10 GB one it is the difference between working and not.")
    print("  Lesson 09 turns this into a generator pipeline.")


def part7_pathlib():
    section("7. pathlib instead of string paths")
    print(f"  this script      : {HERE.name}/")
    print(f"  catalogue        : {CATALOGUE.relative_to(HERE.parent.parent)}")
    print(f"  suffix           : {CATALOGUE.suffix}")
    print(f"  stem             : {CATALOGUE.stem}")
    print(f"  exists           : {CATALOGUE.exists()}")
    print(f"  resolved parent  : {CATALOGUE.parent.name}/")
    print()
    print("  Path objects carry their own operations and their own os-")
    print("  independence.  A string like 'code\\\\data\\\\x.csv' is correct on one")
    print("  platform only; Path('code') / 'data' / 'x.csv' is correct on all.")


def cleanup():
    shutil.rmtree(SCRATCH, ignore_errors=True)
    print(f"\n  scratch directory removed: {not SCRATCH.exists()}")


if __name__ == "__main__":
    part1_write_then_look()
    part2_read_rows()
    part3_quoting()
    part4_encodings()
    part5_line_endings()
    part6_streaming()
    part7_pathlib()
    cleanup()
