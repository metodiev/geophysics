"""The module's complete small program: catalogue in, report out.

Run:  python3 catalog_report.py
Requires: Python standard library only (it imports the module's own
``geophys_core``, which is likewise standard library only).

Companion to lessons 03-01-04, 03-01-06, 03-01-09 and 03-01-10.  This is the
program that the module builds up piece by piece: it demonstrates the whole
chain in one file.

    synthetic data  ->  CSV on disk  ->  streamed read  ->  typed records
                    ->  geophysical computation  ->  formatted report
                    ->  atomic write  ->  read back and verify

The catalogue is **SYNTHETIC**.  Magnitudes are drawn from a Gutenberg-Richter
distribution with a known input b-value, so the report can check its own
estimator against the truth; epicentres and depths are uniform synthetic noise.
No real earthquake catalogue is used, downloaded or embedded, and every number
in the output is computed by this script.
"""

import csv
import functools
import math
import os
import random
import shutil
import time
from pathlib import Path

from geophys_core import EARTH_RADIUS_KM, b_value_maxlik, haversine_km, mean

SEED = 20261014
N_EVENTS = 5_000
B_INPUT = 1.0                 # the b-value we draw from, so we can check
MC_MIN = -1.0                 # minimum synthetic magnitude

# Nominal reference site: approximate coordinates of Zurich, Switzerland.
REFERENCE = {"name": "Zurich (nominal)", "lat": 47.3769, "lon": 8.5417}
# Epicentres are scattered uniformly in a nominal box around the reference
# site, standing in for a regional network.  SYNTHETIC, like everything else.
BOX = {"dlat": 3.0, "dlon": 4.0}


def stdev(values):
    """Sample standard deviation (n - 1 denominator) of an iterable."""
    values = list(values)
    if len(values) < 2:
        raise ValueError("stdev needs at least two values")
    m = mean(values)
    return math.sqrt(sum((v - m) ** 2 for v in values) / (len(values) - 1))

HERE = Path(__file__).resolve().parent
CATALOGUE = HERE / "_scratch_report" / "synthetic_catalogue.csv"
REPORT = HERE / "_scratch_report" / "catalog_report.txt"

STEP_TIMES = {}


# --------------------------------------------------------------------------
# Infrastructure: one decorator, one context manager
# --------------------------------------------------------------------------

def report_step(func):
    """Time a step of the report and record it in STEP_TIMES."""

    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        start = time.perf_counter()
        result = func(*args, **kwargs)
        STEP_TIMES[func.__name__] = time.perf_counter() - start
        return result

    return wrapper


class atomic_write_text:
    """Publish a text file only if the whole block completes.

    Data is written to ``<name>.tmp`` and moved into place with
    ``os.replace`` (atomic on POSIX and Windows), so an interrupted run
    cannot leave a half-written report that looks complete.
    """

    def __init__(self, path):
        self.path = Path(path)
        self.tmp = self.path.with_suffix(self.path.suffix + ".tmp")
        self.handle = None

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = self.tmp.open("w", encoding="utf-8", newline="")
        return self.handle

    def __exit__(self, exc_type, exc_value, traceback):
        if self.handle is not None:
            self.handle.close()
        if exc_type is None:
            os.replace(self.tmp, self.path)
        else:
            self.tmp.unlink(missing_ok=True)
        return False


# --------------------------------------------------------------------------
# 1. Generate SYNTHETIC data
# --------------------------------------------------------------------------

@report_step
def write_synthetic_catalogue(path, n=N_EVENTS, seed=SEED):
    """Write a synthetic catalogue and return the parameters used."""
    rng = random.Random(seed)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write("# SYNTHETIC catalogue generated by catalog_report.py"
                     " - not observed data\n")
        handle.write("event_id,latitude,longitude,depth_km,magnitude\n")
        for i in range(n):
            # Inverse-transform sampling of a Gutenberg-Richter magnitude:
            # M = MC_MIN - log10(U) / b, which is exponential above MC_MIN.
            magnitude = MC_MIN - math.log10(rng.random()) / B_INPUT
            latitude = REFERENCE["lat"] + rng.uniform(-BOX["dlat"], BOX["dlat"])
            longitude = REFERENCE["lon"] + rng.uniform(-BOX["dlon"], BOX["dlon"])
            handle.write(
                f"SYN{i:06d},{latitude:.4f},{longitude:.4f},"
                f"{rng.uniform(1.0, 60.0):.2f},{magnitude:.3f}\n")
    return {"n": n, "b_input": B_INPUT, "mc_min": MC_MIN, "seed": seed}


# --------------------------------------------------------------------------
# 2. Stream the file into typed records
# --------------------------------------------------------------------------

def iter_catalogue(path):
    """Yield one typed dict per event, streaming the file a line at a time.

    This is the generator from lesson 09: the peak memory cost does not grow
    with the number of events, so the same code would run on a 10^8-row file.
    """
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(
            line for line in handle if not line.startswith("#"))
        for row in reader:
            yield {
                "event_id": row["event_id"],
                "latitude": float(row["latitude"]),
                "longitude": float(row["longitude"]),
                "depth_km": float(row["depth_km"]),
                "magnitude": float(row["magnitude"]),
            }


@report_step
def scan(path):
    """One pass over the file: counts, sums, extremes and a depth histogram."""
    n = 0
    mag_min = math.inf
    mag_max = -math.inf
    depth_sum = 0.0
    distance_sum = 0.0
    distance_max = 0.0
    within_100_km = 0
    depth_bins = [0] * 6                       # 10 km bins, 0-60 km
    for event in iter_catalogue(path):
        n += 1
        magnitude = event["magnitude"]
        depth = event["depth_km"]
        mag_min = min(mag_min, magnitude)
        mag_max = max(mag_max, magnitude)
        depth_sum += depth
        distance = haversine_km(REFERENCE["lat"], REFERENCE["lon"],
                                event["latitude"], event["longitude"])
        distance_sum += distance
        distance_max = max(distance_max, distance)
        if distance <= 100.0:
            within_100_km += 1
        depth_bins[min(int(depth // 10.0), 5)] += 1
    if n == 0:
        raise ValueError("the catalogue is empty")
    return {"n": n, "mag_min": mag_min, "mag_max": mag_max,
            "mean_depth_km": depth_sum / n, "depth_bins": depth_bins,
            "mean_distance_km": distance_sum / n, "max_distance_km": distance_max,
            "within_100_km": within_100_km}


# --------------------------------------------------------------------------
# 3. Compute the geophysics
# --------------------------------------------------------------------------

@report_step
def magnitude_frequency(path, thresholds=(0.0, 1.0, 2.0, 3.0)):
    """b-value at several completeness thresholds, plus the counts."""
    magnitudes = []                # one small list: 5,000 floats is 40 kB
    for event in iter_catalogue(path):
        magnitudes.append(event["magnitude"])
    results = []
    for mc in thresholds:
        above = [m for m in magnitudes if m >= mc]
        if len(above) < 10:
            results.append((mc, len(above), None))
            continue
        results.append((mc, len(above), b_value_maxlik(magnitudes, mc)))
    return results


@report_step
def b_value_uncertainty(n_replicas=100, n_per_replica=2000, seed=SEED + 1):
    """Monte-Carlo scatter of the b-value estimator at Mc = 0.

    A direct measurement of how precisely a b-value can be determined from a
    sample of this size, rather than a quoted formula.
    """
    rng = random.Random(seed)
    estimates = []
    for _ in range(n_replicas):
        sample = [MC_MIN - math.log10(rng.random()) / B_INPUT
                  for _ in range(n_per_replica)]
        estimates.append(b_value_maxlik(sample, 0.0))
    return mean(estimates), stdev(estimates), len(estimates)


# --------------------------------------------------------------------------
# 4. Format and write the report
# --------------------------------------------------------------------------

def build_report(params, summary, mf_rows, mc_stats):
    lines = []
    add = lines.append
    add("SYNTHETIC earthquake-catalogue report")
    add("=" * 72)
    add(f"generator seed       : {params['seed']}")
    add(f"events generated     : {params['n']:,}")
    add(f"magnitude law        : Gutenberg-Richter, input b = {params['b_input']}")
    add(f"minimum magnitude    : {params['mc_min']}")
    add(f"reference site       : {REFERENCE['name']} "
        f"({REFERENCE['lat']} N, {REFERENCE['lon']} E)")
    add("data status          : SYNTHETIC - no real catalogue is used")
    add("")
    add(f"events read          : {summary['n']:,}")
    add(f"magnitude range      : {summary['mag_min']:.3f} to"
        f" {summary['mag_max']:.3f}")
    add(f"mean depth           : {summary['mean_depth_km']:.2f} km")
    add(f"mean epicentral distance from {REFERENCE['name']}:"
        f" {summary['mean_distance_km']:.1f} km")
    add(f"farthest event       : {summary['max_distance_km']:.1f} km")
    add(f"events within 100 km : {summary['within_100_km']:,}"
        f" ({100.0 * summary['within_100_km'] / summary['n']:.1f} %)")
    add("")
    add("Depth distribution (10 km bins)")
    add(f"  {'bin (km)':<12}{'events':>8}{'per cent':>10}  histogram")
    for i, count in enumerate(summary["depth_bins"]):
        share = 100.0 * count / summary["n"]
        bar = "#" * int(round(share))
        add(f"  {i * 10:>3}-{i * 10 + 10:>3}   {count:>8,}{share:>10.1f}  {bar}")
    add("")
    add("Magnitude-frequency statistics (Aki-Utsu maximum likelihood)")
    add(f"  {'Mc':>5}{'N >= Mc':>10}{'b estimate':>14}{'b/sqrt(N)':>12}")
    for mc, count, b in mf_rows:
        if b is None:
            add(f"  {mc:>5.1f}{count:>10,}{'too few events':>22}")
        else:
            add(f"  {mc:>5.1f}{count:>10,}{b:>14.4f}{b / math.sqrt(count):>12.4f}")
    add("")
    mc_mean, mc_std, n_rep = mc_stats
    sem = mc_std / math.sqrt(n_rep)
    add("Monte-Carlo calibration of the estimator at Mc = 0")
    add(f"  replicas            : {n_rep}, each of 2,000 events")
    add(f"  mean estimate       : {mc_mean:.4f}  (input b = {params['b_input']})")
    add(f"  scatter of estimates: {mc_std:.4f}"
        f"  vs  b/sqrt(2000) = {params['b_input'] / math.sqrt(2_000):.4f}")
    add(f"  events above Mc=0   : about {0.1 * 2000:.0f}"
        f"  ->  b/sqrt(N_above) ="
        f" {params['b_input'] / math.sqrt(0.1 * 2000):.4f}")
    add("  The relevant sample size is the number of events ABOVE Mc, not the")
    add("  total: only about one event in ten clears Mc = 0 here, which is why")
    add("  the measured scatter matches the second line, not the first.")
    add(f"  standard error of the mean: {sem:.4f}")
    within = abs(mc_mean - params["b_input"]) <= 2.0 * sem
    add(f"  mean within 2 standard errors of the input: {within}")
    add("")
    add("Timing (wall clock, seconds)")
    for name, seconds in STEP_TIMES.items():
        add(f"  {name:<28}{seconds:>10.4f}")
    add(f"  {'total':<28}{sum(STEP_TIMES.values()):>10.4f}")
    add("")
    add("Notes and limits")
    add("  * Magnitudes are stored rounded to 0.001, so the continuous Aki-Utsu")
    add("    form used here is the appropriate one.  Catalogues that report")
    add("    magnitudes rounded to a bin width dM need the usual dM/2")
    add("    correction: it subtracts dM/2 from the mean before dividing, so")
    add("    it always returns a SMALLER b than the continuous form.")
    add("  * The Monte-Carlo block above measures the estimator's scatter for")
    add("    this sample size instead of asserting it.")
    add("  * Distances use a spherical Earth with R = 6371 km, so they are")
    add("    good to about 0.3 per cent against an ellipsoidal calculation.")
    add("  * Epicentres and depths are uniform synthetic noise within a box")
    add("    around the reference site: their statistics are a property of")
    add("    this generator, not of the Earth.")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# 5. Run it
# --------------------------------------------------------------------------

def main():
    params = write_synthetic_catalogue(CATALOGUE)
    summary = scan(CATALOGUE)
    mf_rows = magnitude_frequency(CATALOGUE)
    mc_stats = b_value_uncertainty()

    text = build_report(params, summary, mf_rows, mc_stats)
    with atomic_write_text(REPORT) as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())

    read_back = REPORT.read_text(encoding="utf-8")
    assert read_back == text, "the published report does not match what was written"
    print(read_back)
    print(f"report written atomically to {REPORT.name}:"
          f" {len(read_back):,} characters, verified by re-reading")
    shutil.rmtree(CATALOGUE.parent, ignore_errors=True)
    print(f"scratch directory removed: {not CATALOGUE.parent.exists()}")


if __name__ == "__main__":
    main()
