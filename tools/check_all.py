"""Repository-wide quality gate for the Geophysics curriculum.

Runs four independent checks and reports a single pass/fail summary:

1. ``check_structure``  - every lesson file carries valid frontmatter, every
                          frontmatter ``id`` matches the plan, and every
                          frontmatter path matches its location on disk.
2. ``check_links``      - relative Markdown links resolve to existing files.
3. ``check_math``       - LaTeX inline ``$...$`` and display ``$$...$$``
                          delimiters are balanced on every line/section.
4. ``check_duplicates`` - no duplicate lesson IDs, slugs or titles.

Usage
-----
    python3 tools/check_all.py            # run everything
    python3 tools/check_all.py --quiet    # only print failures

Exit status is 0 when every check passes, 1 otherwise, so the script can be
used directly as a CI gate.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import curriculum_plan as plan  # noqa: E402
from frontmatter import FrontmatterError, parse_frontmatter  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {
    ".git", "node_modules", "__pycache__", ".venv", "venv", "site-packages",
    # Tool caches. These are generated by running pytest/mypy/ruff/notebooks,
    # are gitignored, and must never be scanned as repository content: pytest
    # in particular writes a .pytest_cache/README.md that contains its own
    # documentation URL, which is not a citation the repository makes.
    ".pytest_cache", ".mypy_cache", ".ruff_cache", ".ipynb_checkpoints",
    "build", "dist",
}
# Directories whose Markdown is supporting material, not curriculum lessons.
NON_LESSON_DIRS = {"exercises", "code", "tools", "images", "data", "solutions"}

LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
FENCE_RE = re.compile(r"^\s*(```|~~~)")

# A real Markdown link target is a URL, an anchor, or a path. Anything else that
# happens to sit inside `[...](...)` is prose or code, not a link. Without this
# guard, text such as `[:,\nNone](12, 500)` -- which appears in a lesson about
# array broadcasting whenever an inline code span wraps across a line -- is
# reported as a broken link whose target is "12, 500".
_LINK_TARGET_RE = re.compile(
    r"^(?:#|/|\.\.?/|https?://|mailto:)"              # anchor, absolute or relative path, URL
    r"|/"                                              # any relative path
    r"|\.(?:md|markdown|py|txt|ya?ml|cff|toml|json|csv|tsv|ipynb)$",
    re.IGNORECASE,
)


def looks_like_link_target(target: str) -> bool:
    """True if the text could plausibly be a link target rather than stray prose."""
    if not target or any(char.isspace() for char in target):
        return False
    return bool(_LINK_TARGET_RE.search(target))


# Subdirectories that belong to the module that contains them.
_MODULE_SUBDIRS = {"exercises", "code", "images", "data", "solutions"}


def _module_dir_of(file_path: Path) -> Path:
    """The module directory that owns a file (its parent, or grandparent in exercises/)."""
    parent = file_path.parent
    return parent.parent if parent.name in _MODULE_SUBDIRS else parent


def _within_own_module(file_path: Path, resolved: Path) -> bool:
    """True if a directory target lies inside the linking file's own module."""
    module_dir = _module_dir_of(file_path)
    try:
        resolved.relative_to(module_dir)
        return True
    except ValueError:
        return False


def iter_markdown() -> list[Path]:
    files: list[Path] = []
    for path in sorted(REPO_ROOT.rglob("*.md")):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        files.append(path)
    return files


def iter_lesson_files() -> list[Path]:
    """Markdown files that are lessons.

    A lesson is a numbered Markdown file inside a module directory. Index pages
    (``README.md``), problem sets and solutions (``exercises/``), and runnable
    code (``code/``) are deliberately excluded: they carry no frontmatter and
    must not be counted as lessons.
    """
    lessons = []
    for path in iter_markdown():
        if path.name == "README.md":
            continue
        if any(part in NON_LESSON_DIRS for part in path.parts):
            continue
        if re.match(r"^\d{2}-", path.name):
            lessons.append(path)
    return lessons


# --------------------------------------------------------------------------
# Check 1: structure and frontmatter
# --------------------------------------------------------------------------

def check_structure(verbose: bool) -> list[str]:
    problems: list[str] = []
    by_path = {lesson["path"]: lesson for lesson in plan.all_lessons()}

    for path in iter_lesson_files():
        rel = path.relative_to(REPO_ROOT).as_posix()
        try:
            meta, _ = parse_frontmatter(path.read_text(encoding="utf-8"))
        except FrontmatterError as exc:
            problems.append(f"{rel}: {exc}")
            continue

        expected = by_path.get(rel)
        if expected is None:
            problems.append(f"{rel}: not declared in tools/curriculum_plan.py")
            continue
        if meta.get("id") != expected["id"]:
            problems.append(
                f"{rel}: frontmatter id {meta.get('id')!r} != planned {expected['id']!r}"
            )
        if meta.get("title") != expected["title"]:
            problems.append(
                f"{rel}: frontmatter title {meta.get('title')!r} != planned {expected['title']!r}"
            )
        if meta.get("level") != expected["level"]:
            problems.append(
                f"{rel}: frontmatter level {meta.get('level')!r} != planned {expected['level']!r}"
            )

    if verbose:
        written = len(iter_lesson_files())
        print(f"  lessons on disk: {written} / {len(by_path)} planned")
    return problems


# --------------------------------------------------------------------------
# Check 2: relative links
# --------------------------------------------------------------------------

def _known_targets() -> dict[str, list[str]]:
    """Map basename to repo-relative POSIX paths of files that exist or are planned."""
    index: dict[str, list[str]] = {}
    seen: set[str] = set()

    def add(rel: str) -> None:
        if rel in seen:
            return
        seen.add(rel)
        index.setdefault(rel.rsplit("/", 1)[-1], []).append(rel)

    for path in iter_markdown():
        add(path.relative_to(REPO_ROOT).as_posix())
    for planned in plan.planned_paths():
        add(planned)
    return index


def _suggest_target(index: dict[str, list[str]], linking_rel: str, target: str) -> str | None:
    """Suggest the correct relative path for a link whose depth is wrong.

    Link-depth mistakes are the single most common defect in this repository:
    a file one directory deeper needs one more ``../``. Rather than only
    reporting the failure, locate the intended target by matching trailing path
    components and return the relative path that would have worked.
    """
    basename = target.rstrip("/").rsplit("/", 1)[-1]
    candidates = index.get(basename, [])
    if not candidates:
        return None

    wanted = [part for part in target.split("/") if part not in ("", ".", "..")]
    best_path: str | None = None
    best_score = 0
    for candidate in candidates:
        candidate_parts = candidate.split("/")
        score = 0
        for want, have in zip(reversed(wanted), reversed(candidate_parts)):
            if want != have:
                break
            score += 1
        if score > best_score:
            best_score, best_path = score, candidate
    if best_path is None or best_score == 0:
        return None

    base_dir = Path(linking_rel).parent
    return os.path.relpath(best_path, base_dir)


def check_links(verbose: bool) -> list[str]:
    """Fail only on links that are neither present nor declared in the plan.

    Because this curriculum is written in batches, a link may legitimately point
    at a lesson that is planned but not yet written. Such links are reported as
    *pending* (informational) rather than broken (failure). A link that is
    neither on disk nor in the plan is a genuine error, and the report includes
    a suggested correct path when one can be inferred.
    """
    problems: list[str] = []
    planned = set(plan.planned_paths())
    index = _known_targets()
    checked = pending = 0

    for path in iter_markdown():
        rel = path.relative_to(REPO_ROOT).as_posix()
        text = _prose_only(path.read_text(encoding="utf-8"))
        for match in LINK_RE.finditer(text):
            target = match.group(1).strip()
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            if target.startswith("/"):
                # Absolute filesystem paths are machine-specific and break for
                # every other reader. Always use a repository-relative link.
                problems.append(f"{rel}: absolute path link -> {target}")
                continue
            target = target.split("#", 1)[0]
            if not target:
                continue
            if not looks_like_link_target(match.group(1).strip()):
                continue
            checked += 1
            resolved = (path.parent / target).resolve()
            if resolved.exists():
                if resolved.is_dir() and not _within_own_module(path, resolved):
                    # A link to a directory in ANOTHER module breaks in a fresh
                    # clone when that module has no committed files yet, because
                    # git does not track empty directories. Links to ./exercises
                    # or ./code within the same module are fine -- those always
                    # contain committed companions and demos.
                    problems.append(
                        f"{rel}: links to a directory in another module -> "
                        f"{match.group(1)}   [link to '<dir>/README.md' instead]"
                    )
                continue
            # Normalise the target back to a repository-relative path.
            try:
                rel_target = resolved.relative_to(REPO_ROOT).as_posix()
            except ValueError:
                rel_target = target
            if rel_target in planned:
                pending += 1
                continue
            message = f"{rel}: broken relative link -> {match.group(1)}"
            suggestion = _suggest_target(index, rel, target)
            if suggestion and suggestion != target:
                message += f"   [did you mean '{suggestion}'?]"
            problems.append(message)

    if verbose:
        print(f"  relative links checked: {checked} ({pending} pending, planned but "
              f"not yet written)")
    return problems


# --------------------------------------------------------------------------
# Check 3: LaTeX delimiter balance
# --------------------------------------------------------------------------


def strip_inline_code(text: str) -> str:
    """Remove backtick-delimited spans, matching equal-length backtick runs.

    Two subtleties that a single regex gets wrong, both of which caused this
    checker to fail lessons for writing correct Markdown:

    * A lesson teaching fences legitimately writes a four-backtick span wrapping
      a three-backtick one (```` ```` ``` ```` ````). Runs must be paired by
      length, or a half-stripped span leaves a stray ``$`` behind that then
      looks like an unclosed math delimiter.
    * CommonMark allows a code span to contain line breaks, so a span may open
      on one line and close on the next. Refusing to pair across lines left such
      spans in place. Newlines inside a removed span are re-emitted so that
      reported line numbers stay correct.

    An unmatched run is left untouched rather than swallowing the rest of the
    file.
    """
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        if text[i] != "`":
            out.append(text[i])
            i += 1
            continue
        j = i
        while j < n and text[j] == "`":
            j += 1
        run = j - i
        closer = j
        while True:
            closer = text.find("`" * run, closer)
            if closer == -1:
                break
            after = closer + run
            if after < n and text[after] == "`":
                closer = after  # part of a longer run; keep searching
                continue
            break
        if closer == -1:
            out.append(text[i:j])
            i = j
        else:
            span = text[i : closer + run]
            out.append("\n" * span.count("\n"))
            i = closer + run
    return "".join(out)


def _strip_code(text: str) -> list[str]:
    """Return lines with fenced code blocks replaced by blanks."""
    out: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if FENCE_RE.match(line):
            in_fence = not in_fence
            out.append("")
            continue
        out.append("" if in_fence else line)
    return out


def _prose_only(text: str) -> str:
    """Remove fenced code blocks and inline code spans before link extraction.

    Code samples legitimately contain text that looks like a Markdown link --
    for example ``datetime64[ns](1)`` in a pandas lesson, or the literal
    ``[text](target)`` used when teaching Markdown itself. Neither is a link,
    and reporting them as broken targets is a false positive that costs an agent
    time to work around.
    """
    joined = "\n".join(_strip_code(text))
    return strip_inline_code(joined)


def check_math(verbose: bool) -> list[str]:
    """Check LaTeX delimiter balance.

    Inline ``$...$`` spans are tracked *across* lines, because inline math
    legitimately wraps in Markdown source. A single file-level unbalanced state
    is reported with the line where the unclosed span began.

    Inline code spans are removed first. A lesson *about* Markdown and LaTeX
    has to write a bare ``$`` inside backticks to explain the delimiters, and
    counting those made the checker fail the one file that teaches correct
    delimiter use.
    """
    problems: list[str] = []
    files = 0
    for path in iter_markdown():
        files += 1
        lines = strip_inline_code(
            "\n".join(_strip_code(path.read_text(encoding="utf-8")))
        ).split("\n")
        rel = path.relative_to(REPO_ROOT).as_posix()

        # Display math: count $$ delimiters across the whole file.
        doubled = sum(line.count("$$") for line in lines)
        if doubled % 2 != 0:
            problems.append(f"{rel}: unbalanced '$$' display-math delimiters ({doubled})")

        # Inline math: a running toggle across the file. A line with an even
        # number of '$' toggles twice and leaves the state unchanged.
        open_at: int | None = None
        for index, line in enumerate(lines, start=1):
            residue = line.replace("$$", "")
            count = residue.count("$") - residue.count(r"\$")
            if count % 2 == 1:
                if open_at is None:
                    open_at = index
                else:
                    open_at = None
        if open_at is not None:
            problems.append(
                f"{rel}: unclosed inline '$' math opened at line {open_at}"
            )
    if verbose:
        print(f"  files scanned for formulas: {files}")
    return problems


# --------------------------------------------------------------------------
# Check 4: duplicate identifiers
# --------------------------------------------------------------------------

def check_duplicates(verbose: bool) -> list[str]:
    problems: list[str] = []
    seen_ids: dict[str, str] = {}
    seen_titles: dict[str, str] = {}
    for path in iter_lesson_files():
        rel = path.relative_to(REPO_ROOT).as_posix()
        try:
            meta, _ = parse_frontmatter(path.read_text(encoding="utf-8"))
        except FrontmatterError:
            continue
        lesson_id = str(meta.get("id", ""))
        title = str(meta.get("title", ""))
        if lesson_id in seen_ids:
            problems.append(f"{rel}: duplicate id {lesson_id!r} (also in {seen_ids[lesson_id]})")
        else:
            seen_ids[lesson_id] = rel
        if title in seen_titles:
            problems.append(f"{rel}: duplicate title {title!r} (also in {seen_titles[title]})")
        else:
            seen_titles[title] = rel
    if verbose:
        print(f"  distinct lesson ids: {len(seen_ids)}")
    return problems


# --------------------------------------------------------------------------
# Runner
# --------------------------------------------------------------------------

CHECKS = (
    ("structure & frontmatter", check_structure),
    ("relative links", check_links),
    ("LaTeX delimiters", check_math),
    ("duplicate identifiers", check_duplicates),
)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quiet", action="store_true", help="only report failures")
    args = parser.parse_args(argv)
    verbose = not args.quiet

    if verbose:
        counts = plan.summary()
        print("Geophysics curriculum quality gate")
        print(f"  plan: {counts['folders']} folders, {counts['modules']} modules, "
              f"{counts['lessons']} lessons\n")

    failed = False
    for name, fn in CHECKS:
        print(f"[{'..' if verbose else ''}] {name}")
        problems = fn(verbose)
        if problems:
            failed = True
            for problem in problems[:40]:
                print(f"      FAIL {problem}")
            if len(problems) > 40:
                print(f"      ... and {len(problems) - 40} more")
        else:
            print("      ok")

    print()
    if failed:
        print("RESULT: FAIL")
        return 1
    print("RESULT: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
