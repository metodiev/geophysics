#!/usr/bin/env python3
"""Aftershock sequences: Omori-Utsu decay, ETAS branching, the largest
aftershock, and productivity -- all measured on SYNTHETIC catalogues.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python aftershocks_demo.py

Everything is SYNTHETIC.  Catalogues are generated by a chosen Epidemic-Type
Aftershock Sequence (ETAS) model; the parameters are teaching values, not fitted
to any real sequence, and no published Omori or ETAS parameter is quoted.

Contents
--------
1. One ETAS catalogue: counts and the measured mean number of offspring per
   event (the branching ratio), checked against K b/(b - alpha).
2. Modified Omori-Utsu fit (p, c by maximum likelihood, normalisation analytic).
3. Why the window matters: pooled ensemble fits with the correct window
   normalisation versus the naive one that ignores when observation started.
4. The largest aftershock: how dM depends on how long you look.
5. Productivity measured over an ensemble: log10 N_aft ~ alpha (M - M_c).
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC ETAS parameters (chosen teaching values) ----------------------
P_TRUE = 1.10          # Omori-Utsu decay exponent
C_TRUE = 0.05          # days; time offset of the Omori-Utsu law
K_TRUE = 0.02          # mean direct offspring at m = MC, events per event
ALPHA_TRUE = 0.90      # productivity exponent (must be < b for a finite mean)
B_GR = 1.00            # Gutenberg-Richter b of all events
MC = 1.00              # reference/completeness magnitude
MU_BG = 0.02           # background rate, events per day
T_DAYS = 365.0         # length of the single simulated catalogue, days
M_MAIN = 6.00          # mainshock magnitude of the single sequence
T_MAIN = 10.0          # mainshock time, days
BRANCH_THEORY = K_TRUE * B_GR / (B_GR - ALPHA_TRUE)


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def gr_magnitudes(n, rng):
    """n magnitudes from a Gutenberg-Richter law with b = B_GR above MC."""
    u = rng.random(n)
    return MC + (-np.log10(1.0 - u)) / B_GR


def omori_offsets(n, p, c, rng):
    """n waiting times from a modified Omori-Utsu law K/(t+c)^p.

    The density f(t) = (p-1) c^(p-1) (t+c)^-p has CDF
    F(t) = 1 - ((t+c)/c)^(1-p), so t = c[(1-u)^(-1/(p-1)) - 1].
    """
    u = rng.random(n)
    return c * ((1.0 - u) ** (-1.0 / (p - 1.0)) - 1.0)


def simulate_etas(mainshock_mag, t_end, rng, t_main=0.0, background=True,
                  alpha=ALPHA_TRUE, k=K_TRUE):
    """Background plus one mainshock and its whole cascade.

    Returns (times, mags, generation, sum_offspring, n_parents): generation 0 is
    background or mainshock; sum_offspring counts every Poisson offspring draw,
    including offspring whose times fall beyond t_end.  ``alpha`` and ``k`` are
    exposed so that the parameter dependence of the largest aftershock can be
    measured.
    """
    times, mags, gen = [], [], []
    if background:
        n_bg = rng.poisson(MU_BG * t_end)
        times.extend(rng.uniform(0.0, t_end, n_bg))
        mags.extend(gr_magnitudes(n_bg, rng))
        gen.extend([0] * n_bg)
    times.append(t_main)
    mags.append(mainshock_mag)
    gen.append(0)

    sum_offspring = 0
    n_parents = 0
    frontier = [(t_main, mainshock_mag, 0)]
    while frontier:
        t_parent, m_parent, g_parent = frontier.pop()
        n_parents += 1
        mean_offspring = k * 10.0 ** (alpha * (m_parent - MC))
        n_off = int(rng.poisson(mean_offspring))
        sum_offspring += n_off
        if n_off == 0:
            continue
        t_off = t_parent + omori_offsets(n_off, P_TRUE, C_TRUE, rng)
        m_off = gr_magnitudes(n_off, rng)
        for t_child, m_child in zip(t_off, m_off):
            if t_child > t_end:
                continue
            times.append(t_child)
            mags.append(m_child)
            gen.append(g_parent + 1)
            frontier.append((t_child, m_child, g_parent + 1))
    order = np.argsort(times)
    return (np.array(times)[order], np.array(mags)[order],
            np.array(gen)[order], sum_offspring, n_parents)


def omori_loglikelihood(dt, t1, t2, p, c, from_origin):
    """Poisson log-likelihood of a rate K (t+c)^-p on a window (t1, t2].

    With N events at offsets dt inside the window and the profile solution for K,
    K = N / L where L = integral of (t+c)^-p over the window; the profile
    log-likelihood is  -p sum ln(dt+c) - N ln L + N (ln N - 1).  If
    ``from_origin`` is True the integral runs from 0, the *naive* normalisation
    that pretends observation began at the mainshock.
    """
    lo = 0.0 if from_origin else t1
    if abs(p - 1.0) < 1e-9:
        lam = np.log((t2 + c) / (lo + c))
    else:
        lam = ((t2 + c) ** (1.0 - p) - (lo + c) ** (1.0 - p)) / (1.0 - p)
    if lam <= 0.0:
        return -np.inf
    n = dt.size
    return -p * np.sum(np.log(dt + c)) - n * np.log(lam) + n * (np.log(n) - 1.0)


def fit_omori(dt, t1, t2, from_origin=False):
    """Grid-search (p, c) maximising the window log-likelihood."""
    dt = dt[(dt > t1) & (dt <= t2)]
    if dt.size < 20:
        return np.nan, np.nan, dt.size
    best = (-np.inf, np.nan, np.nan)
    for c in np.geomspace(0.005, 5.0, 80):
        s = np.sum(np.log(dt + c))
        for p in np.arange(0.20, 1.801, 0.005):
            ll = omori_loglikelihood(dt, t1, t2, p, c, from_origin)
            if ll > best[0]:
                best = (ll, p, c)
    return best[1], best[2], dt.size


def main():
    section("1. One synthetic ETAS catalogue")
    print(f"SYNTHETIC ETAS: p = {P_TRUE:.2f}, c = {C_TRUE:.2f} d, "
          f"K = {K_TRUE:.3f}, alpha = {ALPHA_TRUE:.2f}, b = {B_GR:.2f}, "
          f"M_c = {MC:.2f}")
    print(f"background rate = {MU_BG:.2f} events/day, mainshock M{M_MAIN:.1f} "
          f"at t = {T_MAIN:.0f} d, catalogue length {T_DAYS:.0f} d")
    t, m, g, s_off, n_par = simulate_etas(M_MAIN, T_DAYS, RNG, t_main=T_MAIN)
    n_trig = int(np.sum(g >= 1))
    print(f"\ntotal events in the catalogue       = {t.size:d}")
    print(f"  background + mainshock            = {int(np.sum(g == 0)):d}")
    print(f"  triggered (generation >= 1)       = {n_trig:d}")
    print(f"dominant event magnitude            = M{m.max():.2f}")
    exp_direct = K_TRUE * 10.0 ** (ALPHA_TRUE * (M_MAIN - MC))
    print(f"\nmainshock direct offspring expected = K 10^(alpha (M-M_c)) = "
          f"{exp_direct:.1f} events")
    print(f"mainshock direct offspring observed = "
          f"{int(np.sum(g == 1)):d} events (generation 1, any time)")
    print(f"whole cascade inside the catalogue  = {n_trig:d} events")
    print(f"\nETAS branching ratio of the model, K b/(b - alpha) = "
          f"{BRANCH_THEORY:.4f} events per event")
    print("  this is the mean offspring count averaged over the magnitude")
    print("  distribution of the population.  A mean below 1 makes the process")
    print("  subcritical: cascades die out.  The average over the parents of ONE")
    print(f"  catalogue is not this number -- here it is "
          f"{s_off / n_par:.3f} over {n_par:d} parents, because a single M6.0")
    print("  mainshock dominates its own catalogue.")

    section("2. Modified Omori-Utsu fit by maximum likelihood")
    dt_all = t[g >= 1] - T_MAIN
    dt_all = dt_all[dt_all > 0.0]
    print(f"triggered events attributed to the mainshock cascade: "
          f"{dt_all.size:d}")
    p_hat, c_hat, n_used = fit_omori(dt_all, 0.0, T_DAYS - T_MAIN)
    print(f"  fitted p = {p_hat:.3f}   (true {P_TRUE:.2f})   N = {n_used:d}")
    print(f"  fitted c = {c_hat:.4f} d   (true {C_TRUE:.2f} d)")
    lam = ((T_DAYS - T_MAIN + c_hat) ** (1.0 - p_hat)
           - c_hat ** (1.0 - p_hat)) / (1.0 - p_hat)
    print(f"  fitted normalisation K = N / integral = {n_used / lam:.1f} events")
    print("  (K is the total number the fitted law predicts in the window; it is")
    print("   not the per-event productivity of the ETAS model.)")
    print("\n  observed decay in logarithmic time bins versus the fitted law:")
    print("      t range (d)        observed   fitted (events/bin)")
    edges = np.geomspace(0.01, T_DAYS - T_MAIN, 9)
    for lo, hi in zip(edges[:-1], edges[1:]):
        n_obs = int(np.sum((dt_all >= lo) & (dt_all < hi)))
        pred = n_used / lam * (1.0 / (0.5 * (lo + hi) + c_hat) ** p_hat) * (
            hi - lo)
        print(f"      {lo:6.3f}-{hi:7.2f}   {n_obs:8d}   {pred:14.1f}")

    section("3. Windows matter: pooled fits, correct and naive normalisation")
    print("  pool 60 synthetic sequences (mainshock M5.5-M6.5, 200 days each)")
    pool = []
    for _ in range(60):
        m_main = 5.5 + RNG.random()
        ts, ms, gs, _, _ = simulate_etas(m_main, 200.0, RNG, t_main=0.0,
                                        background=False)
        d = ts[gs >= 1]
        pool.extend(d[d > 0.0])
    pool = np.array(pool)
    print(f"  pooled triggered events: {pool.size:d}")
    print("\n      window (d)        N    p_hat (correct)   p_hat (naive from 0)")
    for t1, t2 in ((0.0, 200.0), (1.0, 200.0), (10.0, 200.0), (1.0, 20.0),
                   (20.0, 200.0)):
        p_ok, c_ok, n_w = fit_omori(pool, t1, t2, from_origin=False)
        p_na, c_na, _ = fit_omori(pool, t1, t2, from_origin=True)
        print(f"      {t1:6.1f}-{t2:7.1f}   {n_w:6d}   {p_ok:14.3f}   "
              f"{p_na:20.3f}")
    print("  the 'correct' column normalises the rate on the window actually")
    print("  observed.  The 'naive' column keeps the integral running from the")
    print("  mainshock even though those events were removed, which biases p.")
    print("  An early-only window (1-20 d) contains almost no late-time")
    print("  information, so p and c trade off against each other and neither is")
    print("  well determined.")

    section("4. The largest aftershock: a model output, not a constant")
    print("  ensembles of 40 sequences; mainshock M4.0-M7.0; window 120 d unless")
    print("  stated.  dM = M_mainshock - M_largest aftershock.")
    print("      model                     mean dM   s.e.    s.d.    min dM   "
          "frac. dM < 0")
    for label, t_end, al, kk in (("window  30 d", 30.0, ALPHA_TRUE, K_TRUE),
                                 ("window 120 d", 120.0, ALPHA_TRUE, K_TRUE),
                                 ("window 365 d", 365.0, ALPHA_TRUE, K_TRUE),
                                 ("alpha 0.60, K 0.050", 120.0, 0.60, 0.050),
                                 ("alpha 1.20, K 0.008", 120.0, 1.20, 0.008)):
        deltas = np.empty(40)
        for i in range(40):
            m_main = 4.0 + 3.0 * RNG.random()
            ts, ms, gs, _, _ = simulate_etas(m_main, t_end, RNG, t_main=0.0,
                                             background=False, alpha=al, k=kk)
            aft = ts > 1e-9
            largest = ms[aft].max() if aft.any() else m_main
            deltas[i] = m_main - largest
        se = deltas.std(ddof=1) / np.sqrt(deltas.size)
        print(f"      {label:22s}   {deltas.mean():7.3f}   {se:5.3f}   "
              f"{deltas.std(ddof=1):6.3f}   {deltas.min():7.3f}   "
              f"{np.mean(deltas < 0.0):12.3f}")
    print("\n  the three window lengths agree to well within their standard")
    print("  errors: in this model the largest aftershock almost always occurs")
    print("  within days of the mainshock, so dM is not a function of how long")
    print("  you look.  Changing the productivity parameters moves dM by a")
    print("  comparable amount, so dM is a property of the model, not a")
    print("  constant of nature.")
    m_main_ref = 7.0
    print(f"\n  for an offspring drawn from the same Gutenberg-Richter law, the")
    print(f"  probability that ONE offspring exceeds its M{m_main_ref:.1f} "
          f"mainshock is")
    print(f"      10^(-b (M_main - M_c)) = 10^(-1.00 x "
          f"{m_main_ref - MC:.0f}) = {10.0 ** (-B_GR * (m_main_ref - MC)):.1e}.")
    print("  with a few thousand offspring this is still rare, which is why the")
    print("  mainshock normally remains the largest event of its own sequence,")
    print("  and why occasional exceedances cost nothing to the theory.")

    section("5. Productivity: aftershock count versus mainshock magnitude")
    mags_test = [5.0, 5.5, 6.0, 6.5, 7.0]
    reps = 30
    counts = np.empty((len(mags_test), reps))
    for j, mm in enumerate(mags_test):
        for i in range(reps):
            ts, ms, gs, _, _ = simulate_etas(mm, 30.0, RNG, t_main=0.0,
                                             background=False)
            counts[j, i] = np.sum((ts > 1e-9) & (ms >= MC))
    med = np.median(counts, axis=1)
    slope = np.polyfit(mags_test, np.log10(med), 1)[0]
    print("      M_main   median N_aft(30 d)   log10 of the median")
    for mm, md in zip(mags_test, med):
        print(f"      {mm:6.1f}   {md:16.1f}   {np.log10(md):16.3f}")
    print(f"  measured productivity exponent alpha = {slope:.3f} per magnitude"
          f" unit (true {ALPHA_TRUE:.2f})")
    print("  the number of aftershocks grows as 10^(alpha M), so large")
    print("  mainshocks are disproportionately productive.  This is the same")
    print("  alpha that sets the branching ratio in Section 1; it must be")
    print("  evaluated against the magnitude distribution of the population.")


if __name__ == "__main__":
    main()
