#!/usr/bin/env python3
"""Persistent identifiers: check digits, structural validation and error detection.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python persistent_identifiers_demo.py

Everything here is SYNTHETIC.  The identifiers are generated by the code below; no
registry was queried and no real record is looked up.  The check-character algorithm
is ISO/IEC 7064 MOD 11-2, the scheme ORCID uses.

Sections
--------
1. Generating valid identifiers with a check character.
2. Error detection: substitutions, transpositions and shifts.
3. Comparison with an identifier that has no check character.
4. Structural validation of DOI-style strings.
"""

import re

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC parameters (chosen teaching values) --------------------------
N_IDS = 400
N_ERRORS_PER_ID = 3
DOI_LIKE = 300
DOI_PATTERN = re.compile(r"^10\.\d{4,9}/[^\s]+$")


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def check_character(first15: str) -> str:
    """ISO/IEC 7064 MOD 11-2 check character over 15 digits."""
    total = 0
    for ch in first15:
        total = (total + int(ch)) * 2 % 11
    c = (12 - total % 11) % 11
    return "X" if c == 10 else str(c)


def make_id(digits12: str) -> str:
    """A 16-digit identifier body: 12 chosen digits plus a 3-digit block, plus check."""
    first15 = digits12 + "000"
    return first15 + check_character(first15)


def corrupt(identifier: str, kind: str, rng) -> str:
    """Change one digit; for a transposition, retry until the string changes."""
    digits = [i for i, ch in enumerate(identifier) if ch.isdigit()]
    pairs = [i for i in digits[:-1] if (i + 1) in digits]
    for _ in range(20):
        body = list(identifier)
        if kind == "substitution":
            i = digits[int(rng.integers(0, len(digits)))]
            body[i] = str((int(body[i]) + int(rng.integers(1, 9))) % 10)
        elif kind == "transposition":
            i = pairs[int(rng.integers(0, len(pairs)))]
            body[i], body[i + 1] = body[i + 1], body[i]
        elif kind == "shift":
            i = digits[int(rng.integers(0, len(digits)))]
            body[i] = str((int(body[i]) + 1) % 10)
        result = "".join(body)
        if result != identifier:
            return result
    return identifier


def is_valid(identifier: str) -> bool:
    return check_character(identifier[:15]) == identifier[15]


def main():
    section("1. Generating valid identifiers with a check character")
    first12 = ["".join(str(int(d)) for d in RNG.integers(0, 10, 12))
               for _ in range(N_IDS)]
    ids = [make_id(d) for d in first12]
    formatted = [f"{i[:4]}-{i[4:8]}-{i[8:12]}-{i[12:]}" for i in ids]
    print(f"SYNTHETIC corpus: {N_IDS} identifiers, 16 characters, "
          f"check character = ISO 7064 MOD 11-2")
    for example in formatted[:3]:
        print(f"  {example}  (valid: {is_valid(example.replace('-', ''))})")
    valid_count = sum(is_valid(i) for i in ids)
    print(f"  generated identifiers that validate = {valid_count} of {N_IDS}")
    print("  the check character costs one character and detects a defined class of")
    print("  transcription errors; it does not detect a well-formed wrong identifier.")

    section("2. Error detection: substitutions, transpositions and shifts")
    print(f"  {N_ERRORS_PER_ID} corrupted variants per identifier "
          f"({N_IDS * N_ERRORS_PER_ID} total)")
    for kind in ("substitution", "transposition", "shift"):
        caught = 0
        total = 0
        for identifier in ids:
            for _ in range(N_ERRORS_PER_ID):
                bad = corrupt(identifier, kind, RNG)
                total += 1
                caught += int(not is_valid(bad))
        print(f"  {kind:<14s} detected {caught:4d} of {total} "
              f"({caught / total * 100:5.1f} %)")
    print("  -> a single-character substitution or a single-digit shift changes the")
    print("     check character and is always caught.  A transposition of two unequal")
    print("     digits also changes it, because the weights alternate.")

    section("3. Comparison with an identifier that has no check character")
    print(f"  a 12-digit sequential identifier has no check character, so a corrupted")
    print(f"  identifier is a valid-looking identifier whenever the digits are legal")
    for kind in ("substitution", "transposition", "shift"):
        # Every 12-digit string is a legal sequential identifier, so a corrupted one
        # is never detectable: the detection rate is zero by construction.
        changed = sum(int(corrupt(i[:12], kind, RNG) != i[:12]) for i in ids)
        print(f"  {kind:<14s} corrupted {changed:4d} of {N_IDS} identifiers, "
              f"detected 0 ({0.0:.1f} %) — no redundancy in the string")
    print(f"  rate of silent failure at scale: with {10 ** 6} identifiers and a")
    print(f"  transcription error rate of 1 per 1000 entries, "
          f"{10 ** 6 * 0.001:.0f} wrong identifiers would not be flagged without a")
    print("  check character, and 0 would be flagged with one (for the error types")
    print("  above).  That is the whole argument for the extra character.")

    section("4. Structural validation of DOI-style strings")
    prefixes = ["10.1000", "10.12345", "10.5555", "101000", "10.12", "10.1234567890"]
    suffixes = ["j.geo.2026.01.001", "zenodo.1234567", "item-12345", "data set 12",
                "abc.def", ""]
    records = []
    for _ in range(DOI_LIKE):
        prefix = prefixes[int(RNG.integers(0, len(prefixes)))]
        suffix = suffixes[int(RNG.integers(0, len(suffixes)))]
        records.append(f"{prefix}/{suffix}")
    valid = [r for r in records if DOI_PATTERN.match(r)]
    print(f"  SYNTHETIC strings generated from {len(prefixes)} prefixes x "
          f"{len(suffixes)} suffixes: {DOI_LIKE} strings")
    print(f"  structurally valid (10.NNNN/suffix, NNNN 4-9 digits, no whitespace) = "
          f"{len(valid)} ({len(valid) / DOI_LIKE * 100:.1f} %)")
    for r in records[:6]:
        print(f"    {'valid  ' if DOI_PATTERN.match(r) else 'invalid'} {r!r}")
    print("  -> structural validation catches malformed strings and nothing else: a")
    print("     well-formed identifier that does not resolve passes this test.  Only")
    print("     resolving the identifier establishes that it refers to something.")
    print("     This demo never resolves anything: no network access, no registry.")


if __name__ == "__main__":
    main()
