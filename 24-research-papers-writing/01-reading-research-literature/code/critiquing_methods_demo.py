#!/usr/bin/env python3
"""Critiquing methods, data and inference: what a reporting audit can measure.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python critiquing_methods_demo.py

Everything here is SYNTHETIC.  The audited corpus, the per-item reporting rates
and the detection model are generated by the code below; the rates are chosen
teaching values describing a plausible literature, not measurements of a real one.

Sections
--------
1. Reporting-profile audit of a synthetic corpus.
2. The reproducibility-critical subset and its joint occurrence.
3. Weighted audit score and reviewer workload.
4. What the audit cannot see: defect detectability.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC audit parameters (chosen teaching values) ---------------------
N_PAPERS = 150
ITEMS = (
    ("problem statement", 0.97, 1.0),
    ("data provenance", 0.84, 1.0),
    ("data availability statement", 0.61, 3.0),
    ("acquisition parameters", 0.79, 2.0),
    ("processing parameters", 0.68, 3.0),
    ("software and version", 0.57, 2.0),
    ("code availability statement", 0.46, 3.0),
    ("uncertainty / error bars", 0.72, 3.0),
    ("parameter choices justified", 0.49, 2.0),
    ("limitations discussed", 0.74, 1.0),
)
CRITICAL = (2, 4, 6, 7)      # indices of the four reproducibility-critical items
IMPROVED_RATE = 0.90         # hypothetical reporting rate for the weakest item
DETECT_IF_REPORTED = 0.50    # P(a defect is visible | the relevant item is reported)
DETECT_IF_MISSING = 0.15     # P(a defect is visible | the item is absent)
DEFECT_RATE = 0.35           # P(a paper contains a defect of this kind)
REVIEW_HOURS = 4.0           # h per review
N_REVIEWERS = 3


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def main():
    rates = [rate for _, rate, _ in ITEMS]
    weights = np.array([w for _, _, w in ITEMS])
    reported = np.array([RNG.random(N_PAPERS) < rate for rate in rates]).T

    section("1. Reporting-profile audit of a synthetic corpus")
    print(f"SYNTHETIC corpus: {N_PAPERS} papers, {len(ITEMS)} reporting items, "
          f"chosen reporting rates")
    print("  item                          chosen   measured   papers compliant")
    for k, (name, rate, _) in enumerate(ITEMS):
        col = reported[:, k]
        print(f"  {name:<28s} {rate * 100:5.1f} %  {col.mean() * 100:6.1f} %   "
              f"{int(col.sum()):3d} / {N_PAPERS}")
    print(f"  mean compliance over all items = {reported.mean() * 100:.1f} % "
          f"+/- {reported.mean(axis=1).std(ddof=1) * 100:.1f} % (between papers)")

    section("2. The reproducibility-critical subset and its joint occurrence")
    critical = reported[:, list(CRITICAL)]
    print(f"  critical items: {', '.join(ITEMS[k][0] for k in CRITICAL)}")
    for k, col in zip(CRITICAL, critical.T):
        print(f"    {ITEMS[k][0]:<28s} reported in {col.mean() * 100:5.1f} % of papers")
    all4 = critical.all(axis=1)
    print(f"  papers reporting all four critical items = {int(all4.sum())} / {N_PAPERS} "
          f"= {all4.mean() * 100:.1f} %")
    print(f"  expected by multiplication if independent = "
          f"{np.prod([rates[k] for k in CRITICAL]) * 100:.1f} %")
    weakest_k = CRITICAL[int(np.argmin([rates[k] for k in CRITICAL]))]
    improved = reported.copy()
    improved[:, weakest_k] = RNG.random(N_PAPERS) < IMPROVED_RATE
    all4_improved = improved[:, list(CRITICAL)].all(axis=1)
    print(f"  raising '{ITEMS[weakest_k][0]}' from {rates[weakest_k] * 100:.0f} % to "
          f"{IMPROVED_RATE * 100:.0f} % moves the joint rate from "
          f"{all4.mean() * 100:.1f} % to {all4_improved.mean() * 100:.1f} %")
    print("  -> the joint rate is governed by the weakest item, not the average one.")

    section("3. Weighted audit score and reviewer workload")
    score = (reported * weights).sum(axis=1) / weights.sum() * 100.0
    print(f"  weighted audit score = {score.mean():.1f} / 100 "
          f"+/- {score.std(ddof=1):.1f} (1 s.d. between papers)")
    print(f"  papers scoring below 60 = {int((score < 60).sum())} "
          f"({(score < 60).mean() * 100:.1f} %)")
    print(f"  reviewer effort = {N_PAPERS} papers x {N_REVIEWERS} reviewers x "
          f"{REVIEW_HOURS:.0f} h = {N_PAPERS * N_REVIEWERS * REVIEW_HOURS:.0f} h "
          f"({N_PAPERS * N_REVIEWERS * REVIEW_HOURS / 40:.0f} working weeks)")

    section("4. What the audit cannot see: defect detectability")
    item_present = reported[:, weakest_k]
    has_defect = RNG.random(N_PAPERS) < DEFECT_RATE
    visible = np.where(item_present, RNG.random(N_PAPERS) < DETECT_IF_REPORTED,
                       RNG.random(N_PAPERS) < DETECT_IF_MISSING) & has_defect
    n_defect = int(has_defect.sum())
    print(f"  modelled defect of the '{ITEMS[weakest_k][0]}' kind in "
          f"{DEFECT_RATE * 100:.0f} % of papers = {n_defect} papers")
    print(f"  detectability from the text alone: {DETECT_IF_REPORTED:.2f} if the item "
          f"is reported, {DETECT_IF_MISSING:.2f} if not")
    print(f"  defects visible to a reader = {int(visible.sum())} / {n_defect} = "
          f"{visible.sum() / max(n_defect, 1) * 100:.1f} %")
    print(f"  defects invisible to a reader = {n_defect - int(visible.sum())} papers")
    print("  -> a reporting audit scores what IS written; the defects that matter are")
    print("     precisely the ones that leave no textual trace and need the data.")


if __name__ == "__main__":
    main()
