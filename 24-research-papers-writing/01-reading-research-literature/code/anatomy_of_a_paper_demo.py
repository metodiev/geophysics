#!/usr/bin/env python3
"""Anatomy of a research paper: the measurable shape of the IMRaD skeleton.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python anatomy_of_a_paper_demo.py

Everything here is SYNTHETIC.  The corpus is generated by the code below; no
paper is read, no PDF is opened and no number is taken from a published
measurement.  The parameters describe what a *well-formed* paper tends to look
like for teaching purposes and are chosen, not measured.

Sections
--------
1. Corpus shape: length, reference count and their coupling.
2. Sectional word budget of the IMRaD body.
3. Where the citations sit: reference density by section.
4. The hourglass: does the Discussion widen what the Introduction narrowed?
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC corpus parameters (chosen teaching values) --------------------
N_PAPERS = 400
MEAN_WORDS = 6200.0        # words in the whole manuscript (abstract..references)
SIGMA_LOG_WORDS = 0.34     # lognormal spread of manuscript length
BODY_FRACTION = 0.78       # share of the manuscript inside IMRaD sections
SECTIONS = ("Introduction", "Methods", "Results", "Discussion")
SECTION_CONCENTRATION = (1.9, 2.6, 2.2, 2.4)  # Dirichlet alpha: higher = less variable
REFS_PER_1000_WORDS = 7.0  # chosen centre of the reference density
CITATION_SHARE = (0.40, 0.15, 0.15, 0.30)  # fraction of citations placed per section


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def corpus(n, rng):
    """Return (total words, body words per section, reference counts)."""
    total = MEAN_WORDS * rng.lognormal(0.0, SIGMA_LOG_WORDS, n)
    body = BODY_FRACTION * total[:, None]
    shares = rng.dirichlet(np.array(SECTION_CONCENTRATION), size=n)
    per_section = shares * body
    refs = np.maximum(6, np.rint(total / 1000.0 * REFS_PER_1000_WORDS
                                 + rng.normal(0.0, 4.0, n))).astype(int)
    return total, per_section, refs


def main():
    total, per_section, refs = corpus(N_PAPERS, RNG)

    section("1. Corpus shape: length, reference count and their coupling")
    print(f"SYNTHETIC corpus: {N_PAPERS} generated manuscripts, "
          f"whole-manuscript length ~ lognormal(mean {MEAN_WORDS:.0f} words)")
    print(f"  mean manuscript length      = {total.mean():.0f} words "
          f"+/- {total.std(ddof=1):.0f} (1 s.d. across papers)")
    print(f"  median manuscript length    = {np.median(total):.0f} words")
    print(f"  mean reference count        = {refs.mean():.1f} refs +/- {refs.std(ddof=1):.1f}")
    print(f"  reference density           = "
          f"{(refs.sum() / total.sum() * 1000.0):.2f} refs per 1000 words")
    r = np.corrcoef(total, refs)[0, 1]
    print(f"  Pearson r(length, refs)     = {r:+.3f} "
          f"(longer papers cite more, but far from proportionally)")
    print(f"  ratio mean/median length    = {total.mean() / np.median(total):.3f} "
          f"(right-skewed length distribution)")

    section("2. Sectional word budget of the IMRaD body")
    body = per_section.sum(axis=1)
    print(f"  IMRaD body = {BODY_FRACTION:.2f} of the manuscript = "
          f"{body.mean():.0f} words +/- {body.std(ddof=1):.0f}")
    for k, name in enumerate(SECTIONS):
        words = per_section[:, k]
        share = words / body
        print(f"  {name:<13s} {words.mean():6.0f} words +/- {words.std(ddof=1):5.0f} "
              f"| share {share.mean() * 100:5.1f} % +/- {share.std(ddof=1) * 100:4.1f} %")
    ratio = per_section[:, 3] / per_section[:, 0]
    print(f"  Discussion/Introduction word ratio = {ratio.mean():.3f} "
          f"+/- {ratio.std(ddof=1):.3f}")
    print(f"  fraction of papers with Discussion longer than Introduction = "
          f"{np.mean(per_section[:, 3] > per_section[:, 0]) * 100:.1f} %")

    section("3. Where the citations sit: reference density by section")
    citation_share = RNG.dirichlet(np.array(CITATION_SHARE) * 40.0, size=N_PAPERS)
    for k, name in enumerate(SECTIONS):
        cites = citation_share[:, k] * refs
        density = cites / (per_section[:, k] / 1000.0)
        print(f"  {name:<13s} {cites.mean():5.1f} refs placed "
              f"| density {density.mean():5.2f} (mean) / "
              f"{np.median(density):5.2f} (median) refs per 1000 words")
    print(f"  Introduction + Discussion hold "
          f"{np.mean(citation_share[:, 0] + citation_share[:, 3]) * 100:.1f} % "
          f"of the citations")
    print(f"  but only "
          f"{(per_section[:, 0] + per_section[:, 3]).sum() / body.sum() * 100:.1f} % "
          f"of the body words -- citations cluster where the argument is made")

    section("4. The hourglass: does the Discussion widen what the Introduction narrowed?")
    intro = per_section[:, 0]
    disc = per_section[:, 3]
    print(f"  Introduction: {intro.mean():.0f} words, "
          f"Discussion: {disc.mean():.0f} words")
    print(f"  hourglass widening (Discussion - Introduction) = "
          f"{(disc - intro).mean():+.0f} words +/- {(disc - intro).std(ddof=1):.0f}")
    print("  -> the body narrows to the specific result and the Discussion widens again")
    print("     to consequences; a paper whose Discussion is shorter than its")
    print("     Introduction has usually stopped before saying what changed.")


if __name__ == "__main__":
    main()
