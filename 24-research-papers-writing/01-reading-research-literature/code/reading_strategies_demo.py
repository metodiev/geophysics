#!/usr/bin/env python3
"""Reading strategies: the measurable cost and yield of skim, map and deep-read.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python reading_strategies_demo.py

Everything here is SYNTHETIC.  The reading queue, the relevance labels and the
screening performance are generated by the code below; the time costs per pass
and the information yields are chosen teaching values, not measured ones.

Sections
--------
1. The queue and the cost of reading everything.
2. Triage: precision, recall and the number needed to screen.
3. Cost of the three-pass strategy versus brute force.
4. Information yield per hour, and the break-even relevance rate.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC queue and chosen cost model ----------------------------------
N_PAPERS = 240
RELEVANT_FRACTION = 0.25
SCREEN_SENSITIVITY = 0.90   # P(positive screen | relevant)
SCREEN_SPECIFICITY = 0.82   # P(negative screen | not relevant)
MIN_SKIM = 3.0              # skim / triage minutes per paper
MIN_MAP = 10.0              # structured map minutes per paper
MIN_DEEP = 45.0             # deep read minutes per paper
INFO_SKIM = 0.30            # fraction of the usable content captured
INFO_MAP = 0.65
INFO_DEEP = 0.95


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def screen(relevant, rng):
    return np.where(relevant, rng.random(relevant.size) < SCREEN_SENSITIVITY,
                    rng.random(relevant.size) < (1.0 - SCREEN_SPECIFICITY))


def main():
    section("1. The queue and the cost of reading everything")
    relevant = RNG.random(N_PAPERS) < RELEVANT_FRACTION
    n_rel = int(relevant.sum())
    print(f"SYNTHETIC queue: {N_PAPERS} papers, "
          f"{RELEVANT_FRACTION * 100:.0f} % prior relevance -> {n_rel} relevant papers")
    brute_hours = N_PAPERS * MIN_DEEP / 60.0
    print(f"  deep-read everything: {N_PAPERS} x {MIN_DEEP:.0f} min = "
          f"{brute_hours:.1f} h")
    print(f"  cost per relevant paper found = {brute_hours / n_rel * 60:.0f} min")

    section("2. Triage: precision, recall and the number needed to screen")
    pos = screen(relevant, RNG)
    tp = int(np.sum(pos & relevant))
    fp = int(np.sum(pos & ~relevant))
    fn = int(np.sum(~pos & relevant))
    tn = int(np.sum(~pos & ~relevant))
    precision = tp / (tp + fp)
    recall = tp / (tp + fn)
    f1 = 2 * precision * recall / (precision + recall)
    print(f"  title+abstract screen at sensitivity {SCREEN_SENSITIVITY:.2f}, "
          f"specificity {SCREEN_SPECIFICITY:.2f}")
    print(f"  true positive {tp}, false positive {fp}, false negative {fn}, "
          f"true negative {tn} (counts, papers)")
    print(f"  precision = {precision * 100:.1f} %, recall = {recall * 100:.1f} %, "
          f"F1 = {f1:.3f}")
    print(f"  number needed to screen (1 / precision) = {1.0 / precision:.2f} papers "
          f"per relevant hit")

    section("3. Cost of the three-pass strategy versus brute force")
    skim_hours = N_PAPERS * MIN_SKIM / 60.0
    map_hours = N_PAPERS * MIN_MAP / 60.0
    deep_n = tp + fp
    strategy_b_hours = skim_hours + deep_n * MIN_DEEP / 60.0
    strategy_c_hours = skim_hours + map_hours + deep_n * MIN_DEEP / 60.0
    print(f"  brute force (deep-read all)          = {brute_hours:6.1f} h, "
          f"{n_rel} relevant found")
    print(f"  skim all, deep-read screens only      = {strategy_b_hours:6.1f} h, "
          f"{tp} relevant found")
    print(f"  skim, map, deep-read screens only     = {strategy_c_hours:6.1f} h, "
          f"{tp} relevant found")
    print(f"  saving of the two-pass strategy       = "
          f"{(brute_hours - strategy_b_hours) / brute_hours * 100:.1f} % of the hours, "
          f"at the cost of {fn} relevant papers missed")

    section("4. Information yield per hour, and the break-even relevance rate")
    for name, minutes, info in (("skim", MIN_SKIM, INFO_SKIM),
                                ("map", MIN_MAP, INFO_MAP),
                                ("deep read", MIN_DEEP, INFO_DEEP)):
        print(f"  {name:<9s} {minutes:4.0f} min/paper -> "
              f"{info / minutes * 60:.2f} information-units per hour "
              f"({info:.2f} of the content)")
    total_info_b = N_PAPERS * INFO_SKIM + deep_n * INFO_DEEP
    total_info_a = N_PAPERS * INFO_DEEP
    print(f"  information captured, brute force = {total_info_a:.1f} content-units")
    print(f"  information captured, two-pass    = {total_info_b:.1f} content-units")
    print(f"  two-pass recovers {total_info_b / total_info_a * 100:.1f} % of the content "
          f"for {strategy_b_hours / brute_hours * 100:.1f} % of the time")
    for prior in (0.05, 0.25, 0.50, 0.75, 1.00):
        rel = RNG.random(N_PAPERS) < prior
        n_pos = int(screen(rel, RNG).sum())
        cost = skim_hours + n_pos * MIN_DEEP / 60.0
        print(f"  prior relevance {prior * 100:5.1f} % -> screens {n_pos:3d} papers, "
              f"two-pass cost {cost:6.1f} h vs {brute_hours:.1f} h brute force")
    print("  -> the triage saving is largest exactly where relevance is rare, which is")
    print("     why it matters most in a new field and little in your own.")


if __name__ == "__main__":
    main()
