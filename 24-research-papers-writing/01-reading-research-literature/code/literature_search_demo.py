#!/usr/bin/env python3
"""Systematic literature search: measuring precision, recall and de-duplication.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python literature_search_demo.py

Everything here is SYNTHETIC.  The corpus, the relevance labels, the duplicate
pairs and the queries are generated by the code below.  No database is queried
and no API is called.

Sections
--------
1. The search corpus and the five queries.
2. Precision, recall and F1 per query, with the screening load.
3. Combining a broad and a narrow query.
4. Duplicate detection by title similarity.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC corpus and query model (chosen teaching values) ---------------
N_RECORDS = 4000
N_RELEVANT = 240
N_DUPLICATE_PAIRS = 240
TOKEN_HIT = {"broad": 0.55, "narrow": 0.30, "method": 0.45, "region": 0.40}
TOKEN_FALSE = {"broad": 0.34, "narrow": 0.03, "method": 0.18, "region": 0.10}
KEYS = tuple(TOKEN_HIT)


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def build_corpus(rng):
    """Token table: rows = records, columns = broad, narrow, method, region."""
    relevant = np.zeros(N_RECORDS, dtype=bool)
    relevant[rng.choice(N_RECORDS, N_RELEVANT, replace=False)] = True
    tokens = np.empty((N_RECORDS, len(KEYS)), dtype=bool)
    for j, key in enumerate(KEYS):
        p = np.where(relevant, TOKEN_HIT[key], TOKEN_FALSE[key])
        tokens[:, j] = rng.random(N_RECORDS) < p
    return relevant, tokens


def metrics(hit, relevant):
    tp = int(np.sum(hit & relevant))
    fp = int(np.sum(hit & ~relevant))
    fn = int(np.sum(~hit & relevant))
    precision = tp / max(tp + fp, 1)
    recall = tp / max(tp + fn, 1)
    f1 = 0.0 if precision + recall == 0 else 2 * precision * recall / (precision + recall)
    return tp, fp, fn, precision, recall, f1


def trigrams(text):
    return {text[i:i + 3] for i in range(len(text) - 2)}


def jaccard(a, b):
    return len(a & b) / len(a | b)


def main():
    relevant, tokens = build_corpus(RNG)
    broad, narrow, method, region = tokens.T

    section("1. The search corpus and the five queries")
    print(f"SYNTHETIC corpus: {N_RECORDS} records, {int(relevant.sum())} truly relevant "
          f"({relevant.mean() * 100:.1f} % prior prevalence)")
    queries = {
        "Q1 single keyword": broad,
        "Q2 exact phrase": narrow,
        "Q3 method keyword": method,
        "Q4 region keyword": region,
        "Q5 Boolean: method AND region": method & region,
    }
    for name, hit in queries.items():
        print(f"  {name:<32s} retrieves {int(hit.sum()):4d} records")

    section("2. Precision, recall and F1 per query, with the screening load")
    print("  query                              TP   FP   FN   precision  recall    F1")
    for name, hit in queries.items():
        tp, fp, fn, p, r, f1 = metrics(hit, relevant)
        print(f"  {name:<32s} {tp:4d} {fp:4d} {fn:4d}   {p * 100:6.1f} %  "
              f"{r * 100:5.1f} %  {f1:.3f}")
    print("  -> a single keyword buys recall with screening load; a Boolean AND")
    print("     buys screening economy with recall; neither is 'best' in the abstract.")

    section("3. Combining a broad and a narrow query")
    union = broad | narrow
    inter = broad & narrow
    for name, hit in (("broad OR narrow (union)", union),
                      ("broad AND narrow (intersection)", inter)):
        tp, fp, fn, p, r, f1 = metrics(hit, relevant)
        print(f"  {name:<34s} retrieves {int(hit.sum()):4d}, TP {tp:4d}, "
              f"precision {p * 100:5.1f} %, recall {r * 100:5.1f} %, F1 {f1:.3f}")
    print(f"  screening load of the union = {int(union.sum())} title/abstracts to read")
    print(f"  at 1.5 min per screen that is {int(union.sum()) * 1.5:.0f} min "
          f"({int(union.sum()) * 1.5 / 60:.1f} h)")

    section("4. Duplicate detection by title similarity")
    # SYNTHETIC titles: 12 words drawn from a 24-word vocabulary.  A duplicate
    # record is the same title with one word swapped for another and one
    # adjacent pair transposed -- the kind of drift a re-indexed title shows.
    vocab = [f"w{i:02d}" for i in range(24)]
    originals = []
    duplicates = []
    for _ in range(N_DUPLICATE_PAIRS):
        words = list(RNG.choice(vocab, 12))
        dup = list(words)
        dup[RNG.integers(1, 11)] = RNG.choice(vocab)
        i = int(RNG.integers(0, 11))
        dup[i], dup[i + 1] = dup[i + 1], dup[i]
        originals.append(words)
        duplicates.append(dup)
    shingles = lambda ws: {" ".join(ws[i:i + 3]) for i in range(len(ws) - 2)}
    sims = np.array([jaccard(shingles(a), shingles(b))
                     for a, b in zip(originals, duplicates)])
    random_pairs = np.array([
        jaccard(shingles(originals[i]), shingles(list(RNG.choice(vocab, 12))))
        for i in range(0, N_DUPLICATE_PAIRS, 2)])
    for threshold in (0.30, 0.40, 0.50, 0.60, 0.70):
        detected = int(np.sum(sims >= threshold))
        false_merge = float(np.mean(random_pairs >= threshold))
        print(f"  threshold {threshold:.2f}: duplicate pairs caught {detected:3d} / "
              f"{N_DUPLICATE_PAIRS} "
              f"({detected / N_DUPLICATE_PAIRS * 100:5.1f} %), "
              f"false-merge rate on unrelated pairs {false_merge * 100:5.1f} %")
    print(f"  mean 3-shingle Jaccard of true pairs   = {sims.mean():.3f} "
          f"+/- {sims.std(ddof=1):.3f}")
    print(f"  mean 3-shingle Jaccard of random pairs = {random_pairs.mean():.3f} "
          f"+/- {random_pairs.std(ddof=1):.3f}")
    print("  -> a threshold can be chosen, but it trades missed duplicates against")
    print("     wrongly merged records; no threshold makes both rates zero.")


if __name__ == "__main__":
    main()
