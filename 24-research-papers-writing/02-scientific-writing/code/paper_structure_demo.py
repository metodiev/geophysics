#!/usr/bin/env python3
"""Paper structure: word budgets, the hourglass, and section variants.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python paper_structure_demo.py

Everything here is SYNTHETIC.  The corpus is generated by the code below with
chosen teaching parameters; no published paper was measured.

Sections
--------
1. Whole-paper word budget including the abstract and captions.
2. Sectional shares and the specificity index of the hourglass.
3. How often the shape is varied: merged and added sections.
4. Where the numbers live: quantitative content by section.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC corpus parameters (chosen teaching values) -------------------
N_PAPERS = 300
MEAN_WORDS = 6400.0
SIGMA_LOG_WORDS = 0.32
BODY_FRACTION = 0.76
SECTIONS = ("Introduction", "Methods", "Results", "Discussion")
SECTION_CONCENTRATION = (1.8, 2.5, 2.1, 2.3)
MEAN_ABSTRACT_WORDS = 248.0
P_MERGED_RESULTS_DISCUSSION = 0.28
P_EXTRA_THEORY_SECTION = 0.17
P_GEOLOGICAL_SETTING = 0.34
NUMBERS_PER_1000_WORDS = {"Introduction": 1.5, "Methods": 6.0,
                          "Results": 14.0, "Discussion": 4.0}


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def main():
    total = MEAN_WORDS * RNG.lognormal(0.0, SIGMA_LOG_WORDS, N_PAPERS)
    abstract = RNG.normal(MEAN_ABSTRACT_WORDS, 42.0, N_PAPERS).clip(120.0, 400.0)
    body = BODY_FRACTION * total
    shares = RNG.dirichlet(np.array(SECTION_CONCENTRATION), size=N_PAPERS)
    per_section = shares * body[:, None]

    section("1. Whole-paper word budget including the abstract and captions")
    new = {
        "abstract": abstract.mean(),
        "IMRaD body": body.mean(),
        "captions, acknowledgements, references": (total - body - abstract).mean(),
    }
    print(f"SYNTHETIC corpus: {N_PAPERS} manuscripts, mean length "
          f"{total.mean():.0f} words +/- {total.std(ddof=1):.0f}")
    for name, value in new.items():
        print(f"  {name:<38s} {value:6.0f} words "
              f"({value / total.mean() * 100:4.1f} % of the mean paper)")
    print(f"  mean abstract length = {abstract.mean():.0f} words "
          f"+/- {abstract.std(ddof=1):.0f}")
    print(f"  abstracts longer than 300 words = "
          f"{np.mean(abstract > 300) * 100:.1f} % of papers")

    section("2. Sectional shares and the specificity index of the hourglass")
    for k, name in enumerate(SECTIONS):
        words = per_section[:, k]
        print(f"  {name:<13s} {words.mean():6.0f} words +/- {words.std(ddof=1):5.0f} "
              f"| share {words.mean() / body.mean() * 100:5.1f} % "
              f"| between-paper s.d. of share "
              f"{words.std(ddof=1) / body.mean() * 100:4.1f} %")
    narrow = per_section[:, 1] + per_section[:, 2]
    wide = per_section[:, 0] + per_section[:, 3]
    index = narrow / wide
    print(f"  specificity index (Methods+Results)/(Introduction+Discussion) = "
          f"{index.mean():.3f} +/- {index.std(ddof=1):.3f}")
    print(f"  fraction of papers with a Discussion longer than the Introduction = "
          f"{np.mean(per_section[:, 3] > per_section[:, 0]) * 100:.1f} %")
    print("  -> the waist is wider than either wide end on average, which is what")
    print("     'the evidence carries the argument' looks like in word counts.")

    section("3. How often the shape is varied: merged and added sections")
    merged = RNG.random(N_PAPERS) < P_MERGED_RESULTS_DISCUSSION
    theory = RNG.random(N_PAPERS) < P_EXTRA_THEORY_SECTION
    setting = RNG.random(N_PAPERS) < P_GEOLOGICAL_SETTING
    print(f"  Results and Discussion merged      = {merged.mean() * 100:.1f} % "
          f"({int(merged.sum())} of {N_PAPERS} papers)")
    print(f"  a separate Theory section present  = {theory.mean() * 100:.1f} %")
    print(f"  a Geological setting section       = {setting.mean() * 100:.1f} %")
    print(f"  papers with at least one variant   = "
          f"{np.mean(merged | theory | setting) * 100:.1f} %")
    print(f"  papers with all three variants     = "
          f"{np.mean(merged & theory & setting) * 100:.1f} %")
    print("  -> 'IMRaD' names the four jobs, not the four headings; a majority of")
    print("     papers rename or merge at least one of them.")

    section("4. Where the numbers live: quantitative content by section")
    per_paper = {}
    for k, name in enumerate(SECTIONS):
        per_1000 = NUMBERS_PER_1000_WORDS[name]
        per_paper[name] = per_section[:, k].mean() / 1000.0 * per_1000
    total_numbers = sum(per_paper.values())
    for name in SECTIONS:
        print(f"  {name:<13s} {NUMBERS_PER_1000_WORDS[name]:5.1f} numbers per 1000 words "
              f"-> {per_paper[name]:5.1f} numbers per paper "
              f"({per_paper[name] / total_numbers * 100:4.1f} % of the paper's numbers)")
    print(f"  total numeric tokens per paper = {total_numbers:.1f}")
    print(f"  Results alone carries "
          f"{per_paper['Results'] / total_numbers * 100:.1f} % of the numbers")
    print(f"  Introduction + Discussion carry "
          f"{(per_paper['Introduction'] + per_paper['Discussion']) / total_numbers * 100:.1f} % "
          f"in {(per_section[:,0].mean() + per_section[:,3].mean()) / body.mean() * 100:.1f} % "
          f"of the words")
    print("  -> if a claim is quantitative, its number is in Results; if it is")
    print("     qualitative, it is in the Discussion.  Search accordingly.")


if __name__ == "__main__":
    main()
