#!/usr/bin/env python3
"""Intermediate project 1: travel-time curves, first arrivals and the inversion
of a 1-D velocity structure from a picked travel-time curve.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python travel_time_curves_demo.py

Everything here is SYNTHETIC.  The velocity model and the picks are generated by
the code below; no catalogue, no seismogram and no published model is used.

Sections
--------
1. The two-branch travel-time curve: direct wave and Moho head wave.
2. First arrivals and the crossover distance.
3. Inverting picked arrival times for velocity and depth.
4. What the inversion cannot separate: the velocity-depth trade-off.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC 1-D model (chosen, not measured) ------------------------------
V1 = 5.90          # crustal velocity, km/s
V2 = 8.05          # sub-Moho velocity, km/s
H1 = 32.0          # crustal thickness, km
PICK_SIGMA = 0.05  # pick uncertainty, s


def section(title):
    print(f"\n{'=' * 68}\n{title}\n{'=' * 68}")


def t_direct(x, v1):
    return x / v1


def t_head(x, v1, v2, h):
    """Head wave: T = X/V2 + 2H cos(theta_c)/V1 with sin(theta_c) = V1/V2."""
    intercept = 2.0 * h * np.sqrt(v2 ** 2 - v1 ** 2) / (v1 * v2)
    return x / v2 + intercept


def main():
    section("1. The two-branch travel-time curve")
    print(f"SYNTHETIC model: V1 = {V1:.2f} km/s, V2 = {V2:.2f} km/s, "
          f"H1 = {H1:.1f} km")
    x = np.arange(10.0, 501.0, 10.0)
    t1 = t_direct(x, V1)
    t2 = t_head(x, V1, V2, H1)
    print(f"  critical angle sin(theta_c) = V1/V2 = {V1 / V2:.4f}, "
          f"theta_c = {np.degrees(np.arcsin(V1 / V2)):.2f} deg")
    intercept = 2.0 * H1 * np.sqrt(V2 ** 2 - V1 ** 2) / (V1 * V2)
    print(f"  intercept time t_i = 2H sqrt(V2^2-V1^2)/(V1 V2) = {intercept:.4f} s")
    print(f"{'X (km)':>8}{'T direct (s)':>14}{'T head (s)':>12}"
          f"{'first (s)':>12}{'phase':>10}")
    for xa in (20.0, 100.0, 158.7, 200.0, 300.0, 500.0):
        ta, tb = t_direct(xa, V1), t_head(xa, V1, V2, H1)
        first, phase = (ta, "direct") if ta <= tb else (tb, "head")
        print(f"{xa:>8.1f}{ta:>14.4f}{tb:>12.4f}{first:>12.4f}{phase:>10}")

    section("2. First arrivals and the crossover distance")
    x_c = 2.0 * H1 * np.sqrt((V2 + V1) / (V2 - V1))
    print(f"  crossover distance X_c = 2H sqrt((V2+V1)/(V2-V1)) = {x_c:.2f} km")
    print(f"  T at the crossover = {t_direct(x_c, V1):.4f} s "
          f"(both branches agree)")
    first = np.minimum(t1, t2)
    n_head = int(np.sum(t2 < t1))
    print(f"  the head wave is first arrival for {n_head} of {x.size} "
          f"distances, from {x[np.argmax(t2 < t1)]:.1f} km outward")
    app = (t_head(500.0, V1, V2, H1) - t_head(300.0, V1, V2, H1))
    print(f"  apparent slowness between 300 and 500 km = "
          f"{app / 200.0:.6f} s/km -> apparent velocity "
          f"{200.0 / app:.4f} km/s (true V2 = {V2:.2f})")

    section("3. Inverting picked arrival times")
    x_pick = np.arange(200.0, 501.0, 20.0)
    t_pick = t_head(x_pick, V1, V2, H1) + PICK_SIGMA * RNG.standard_normal(x_pick.size)
    print(f"  {x_pick.size} picks from {x_pick[0]:.0f} to {x_pick[-1]:.0f} km, "
          f"Gaussian noise sigma = {PICK_SIGMA:.2f} s")
    design = np.column_stack([np.ones_like(x_pick), x_pick])
    coeff, *_ = np.linalg.lstsq(design, t_pick, rcond=None)
    a, b = coeff
    v2_est = 1.0 / b
    h_est = a * V1 * v2_est / (2.0 * np.sqrt(v2_est ** 2 - V1 ** 2))
    resid = t_pick - design @ coeff
    dof = x_pick.size - 2
    sigma_fit = np.sqrt(resid @ resid / dof)
    cov = sigma_fit ** 2 * np.linalg.inv(design.T @ design)
    sigma_b = np.sqrt(cov[1, 1])
    print(f"  least-squares line T = a + b X: a = {a:.4f} s, "
          f"b = {b:.6f} s/km")
    print(f"  recovered V2 = 1/b = {v2_est:.4f} km/s "
          f"(+/- {v2_est ** 2 * sigma_b:.4f} km/s from the slope fit)")
    print(f"  recovered H1 = a V1 V2 / (2 sqrt(V2^2-V1^2)) = {h_est:.2f} km "
          f"(true {H1:.1f} km)")
    print(f"  rms residual after the fit = {sigma_fit:.4f} s "
          f"(input {PICK_SIGMA:.2f} s)")

    section("4. The velocity-depth trade-off")
    print("  fixing V2 and the intercept, H scales with the assumed V1:")
    for v1_try in (5.60, 5.90, 6.20):
        h_try = a * v1_try * v2_est / (2.0 * np.sqrt(v2_est ** 2 - v1_try ** 2))
        print(f"    V1 = {v1_try:.2f} km/s -> H1 = {h_try:.2f} km "
              f"({h_try / h_est - 1.0:+.1%} relative to the V1 = {V1:.2f} result)")
    h_a = a * 5.60 * v2_est / (2.0 * np.sqrt(v2_est ** 2 - 5.60 ** 2))
    h_b = a * 6.20 * v2_est / (2.0 * np.sqrt(v2_est ** 2 - 6.20 ** 2))
    print(f"  a 0.60 km/s change in the assumed crustal velocity moves the "
          f"depth from {h_a:.1f} to {h_b:.1f} km "
          f"({(h_b - h_a) / h_a:+.1%})")
    print("  -> the travel-time curve constrains the SLOPE (velocity) far better")
    print("     than the INTERCEPT (depth); the depth needs an independent V1.")


if __name__ == "__main__":
    main()
