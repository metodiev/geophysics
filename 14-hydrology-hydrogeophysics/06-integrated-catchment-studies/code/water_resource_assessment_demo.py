#!/usr/bin/env python3
"""Water resource assessment on an idealised, SYNTHETIC aquifer: recharge from
water-table fluctuations and from a chloride mass balance, capture of streamflow
by a pumping well (Glover image-well solution), an uncertainty propagation, and
the difference between a recharge-limited and a capture-limited yield.

Run with the project virtual environment:

    cd 14-hydrology-hydrogeophysics/06-integrated-catchment-studies/code
    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python water_resource_assessment_demo.py

Everything here is SYNTHETIC.  There is no real aquifer, well, stream or
rainfall record in this file.  The water-table record is generated by the model
below, the chloride concentrations are chosen teaching values, and no site is
named and no published measurement is quoted.

Contents
--------
1. A synthetic water-table record from a stated recharge and specific yield.
2. Recharge by water-table fluctuation (WTF): window dependence and the role
   of the specific yield.
3. Recharge by chloride mass balance (CMB), and the disagreement between two
   accepted methods.
4. Stream depletion by pumping: the Glover image-well solution.
5. Uncertainty propagation over T, S, L and the recharge.
6. The decision: recharge-limited against capture-limited yield.
"""

import numpy as np
from scipy.special import erfc

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC, IDEALISED aquifer parameters (chosen, not measured) -----------
SY_TRUE = 0.10         # true specific yield of the unconfined aquifer
RECHARGE_TRUE = 90.0   # mm/a, mean recharge used to generate the water table
WET_START, WET_END = 60, 120     # day of water year with recharge
K_DRAIN = 0.15         # mm/d per m of head above the notional base level
N_YEARS = 4
NOISE_WT = 0.02        # m, water-level measurement noise
CV_RECHARGE = 0.13     # coefficient of variation of the annual recharge
CL_DEP = 0.5           # mg/L, chloride in bulk deposition (SYNTHETIC value)
CL_GW = 12.0           # mg/L, chloride in groundwater (SYNTHETIC value)
P_ANNUAL = 800.0       # mm/a, annual rainfall
T_MED = 200.0          # m^2/d, transmissivity (median)
S_MED = 0.10           # storativity (median)
L_MED = 1500.0         # m, distance from the well to the stream
Q_PUMP = 1000.0        # m^3/d, pumping rate
LOW_FLOW = 4320.0      # m^3/d, synthetic low-flow stream discharge
AREA_KM2 = 20.0        # km^2, idealised assessment area


def section(title):
    print(f"\n{'=' * 74}\n{title}\n{'=' * 74}")


def synthetic_water_table(n_years=N_YEARS, recharge=RECHARGE_TRUE,
                          sy=SY_TRUE, seed=1):
    """Daily water-table elevation above a fixed reference level.

    dz/dt = (r(t) - k_d z) / Sy, with r in mm/d (wet season only, a total
    drawn each year from a normal distribution) and k_d z the drainage in mm/d.
    z is in metres above the notional base level (the stream stage).

    Returns (t in days, measured z', true z', true annual recharge in mm/a).
    """
    rng = np.random.default_rng(seed)
    n = int(n_years * 365)
    t = np.arange(n, dtype=float)
    doy = t % 365.0
    wet = (doy >= WET_START) & (doy < WET_END)
    totals = recharge * (1.0 + CV_RECHARGE * rng.standard_normal(n_years))
    r = np.where(wet, np.repeat(totals, 365) / (WET_END - WET_START), 0.0)
    z = 1.65
    z_true = np.zeros(n)
    for k in range(n):
        z = z + (r[k] - K_DRAIN * z) / (sy * 1000.0)
        z_true[k] = z
    return t, z_true + NOISE_WT * rng.standard_normal(n), z_true, totals


def window_rise(t, z, start, end):
    """Rise of the water table (m) inside a window: maximum minus minimum."""
    m = (t >= start) & (t < end)
    return float(z[m].max() - z[m].min())


def glover_fraction(t_days, L=L_MED, T=T_MED, S=S_MED):
    """Fraction of pumpage derived from stream depletion (Glover, image well)."""
    arg = L * np.sqrt(S / (4.0 * T * np.maximum(t_days, 1e-12)))
    return erfc(arg)


def depleted_volume(t_days, L=L_MED, T=T_MED, S=S_MED, Q=Q_PUMP):
    """Cumulative volume (m^3) taken from the stream by time t."""
    tt = np.linspace(1.0, t_days, 20000)
    return float(Q * np.trapezoid(glover_fraction(tt, L, T, S), tt))


def main():
    section("1. A synthetic water-table record")
    t, z_meas, z_true, totals = synthetic_water_table()
    print(f"  SYNTHETIC unconfined aquifer: true Sy = {SY_TRUE:.2f}, drainage "
          f"k_d = {K_DRAIN:.2f} mm/d per m")
    print(f"  recharge imposed in a {WET_END - WET_START}-day wet season each "
          f"year, annual total varying by CV = {CV_RECHARGE:.2f}")
    print(f"  true annual recharge: " + ", ".join(f"{v:.1f}" for v in totals)
          + f" mm/a (mean {totals.mean():.1f})")
    print(f"  {N_YEARS} years of daily water levels, measurement noise sd "
          f"{NOISE_WT:.2f} m")
    print(f"  modelled elevations span {z_true.min():.2f}-{z_true.max():.2f} m "
          f"above the base level")
    print(f"  the annual minimum still drifts by "
          f"{min(z_true[y * 365:(y + 1) * 365].min() for y in range(1, N_YEARS)) - z_true[:365].min():+.3f} m")
    print("  over the record, so the record is not perfectly stationary: this")
    print("  is a real complication of the WTF method, not an artefact.")

    section("2. Recharge by water-table fluctuation")
    print("   window (d)    rise (m)   R(Sy=0.05)   R(Sy=0.10)   R(Sy=0.15)"
          "   (mm/a)")
    rises = []
    for start, end in ((0, 365), (365, 730), (730, 1095), (1095, 1460),
                       (60, 425), (30, 395)):
        rise = window_rise(t, z_meas, start, end)
        rises.append(rise)
        vals = [rise * 1000.0 * sy for sy in (0.05, 0.10, 0.15)]
        print(f"   {start:4.0f}-{end:4.0f}   {rise:9.4f}   {vals[0]:11.1f}   "
              f"{vals[1]:11.1f}   {vals[2]:11.1f}")
    r_wtf = rises[1] * 1000.0 * SY_TRUE
    print(f"  the measured rise is not one number: the window definition changes")
    print(f"  it from {min(rises):.3f} to {max(rises):.3f} m, a factor "
          f"{max(rises) / min(rises):.2f}.")
    print(f"  with the TRUE Sy = {SY_TRUE:.2f} the water-year windows give "
          f"R = {r_wtf:.1f} mm/a")
    print(f"  against an imposed mean of {totals.mean():.1f} mm/a: a bias of "
          f"{100 * (r_wtf / totals.mean() - 1):+.1f}%.")
    print("  the bias has a physical cause: drainage continues during the rise,")
    print("  and the uncorrected WTF method counts only the water that stayed.")
    print(f"  a 50% error in Sy is a 50% error in the answer:")
    for sy in (0.05, 0.10, 0.15):
        print(f"    Sy = {sy:.2f} -> R = {rises[1] * 1000.0 * sy:.1f} mm/a")
    print("\n  the same annual cycles measured over the recharge season itself")
    print("  (from the noiseless model states), to expose the drainage term:")
    print("   year   z start (m)   z end (m)   Sy*dz (mm)   drainage (mm)"
          "   sum (mm)   recharge (mm)")
    for y in range(N_YEARS):
        s0, s1 = y * 365 + WET_START, y * 365 + WET_END
        dz = z_true[s1] - z_true[s0]
        drain = K_DRAIN * z_true[s0:s1].mean() * (WET_END - WET_START)
        print(f"   {y + 1:4d}   {z_true[s0]:10.3f}   {z_true[s1]:9.3f}   "
              f"{dz * SY_TRUE * 1000:11.1f}   {drain:12.1f}   "
              f"{dz * SY_TRUE * 1000 + drain:8.1f}   {totals[y]:13.1f}")
    print("  the sum Sy*dz + drainage reproduces the recharge to a few per cent:")
    print("  that is the correction the uncorrected WTF method omits, and it is")
    print("  computable from the recession curve that gives k_d.")
    print("  -> the geophysics in this module is what could bound Sy; without it")
    print("     the WTF recharge is a restatement of an assumption, and the")
    print("     method's own drainage bias cannot be seen.")

    section("3. Recharge by chloride mass balance")
    r_cmb = P_ANNUAL * CL_DEP / CL_GW
    print(f"  SYNTHETIC teaching values: rainfall {P_ANNUAL:.0f} mm/a, chloride "
          f"in deposition {CL_DEP:.1f} mg/L,")
    print(f"  chloride in groundwater {CL_GW:.1f} mg/L")
    print(f"  R = P Cl_dep / Cl_gw = {P_ANNUAL:.0f} x {CL_DEP:.1f} / {CL_GW:.1f}"
          f" = {r_cmb:.1f} mm/a")
    print(f"  the WTF estimate with the true Sy is {r_wtf:.1f} mm/a, "
          f"{r_wtf / r_cmb:.2f} times the CMB")
    print(f"  estimate, and the imposed truth is {totals.mean():.1f} mm/a, "
          f"{totals.mean() / r_cmb:.2f} times it.")
    sy_match = r_cmb / (rises[1] * 1000.0)
    print(f"  forcing agreement would require Sy = {sy_match:.4f}, i.e. a")
    print("  specific yield less than half the true value.  Using one method to")
    print("  calibrate the other and then reporting both as independent evidence")
    print("  is a circular argument.")
    print("  -> two accepted methods, one data set, a factor "
          f"{r_wtf / r_cmb:.1f}")
    print("     disagreement.  The honest report is the pair and the reason they")
    print("     differ, not the mean.")

    section("4. Stream depletion by pumping (Glover image-well solution)")
    print(f"  SYNTHETIC: T = {T_MED:.0f} m^2/d, S = {S_MED:.2f}, well "
          f"{L_MED:.0f} m from the stream, Q = {Q_PUMP:.0f} m^3/d")
    print("   time      Q_stream/Q_pump   depletion (m^3/d)   cumulative volume"
          " (m^3)")
    for years in (1.0, 5.0, 10.0, 30.0):
        td = years * 365.0
        frac = float(glover_fraction(td))
        vol = depleted_volume(td)
        print(f"   {years:4.0f} y   {frac:15.4f}   {frac * Q_PUMP:16.1f}   "
              f"{vol:20.0f}")
    t10 = L_MED ** 2 * S_MED / (4.0 * T_MED * 1.1631 ** 2)
    print(f"  the depletion reaches 10% of the pumpage at t = {t10:.1f} d "
          f"({t10 / 365.0:.2f} y)")
    print("  (1.1631 is the argument at which erfc = 0.1)")
    print(f"  the remaining fraction of the pumpage comes from aquifer storage:")
    print(f"  {1 - float(glover_fraction(365.0)):.4f} at 1 year, "
          f"{1 - float(glover_fraction(30 * 365.0)):.4f} at 30 years.")
    print("  -> capture and storage depletion are two names for the same water;")
    print("     a yield that is 'sustainable' over one year may not be over")
    print("     thirty, and the formula above says how the answer moves.")

    section("5. Uncertainty: what the yield estimate actually depends on")
    n = 4000
    T_s = np.exp(np.log(T_MED) + 0.30 * RNG.standard_normal(n))
    S_s = np.clip(S_MED + 0.05 * RNG.standard_normal(n), 0.02, 0.25)
    L_s = np.clip(L_MED + 250.0 * RNG.standard_normal(n), 500.0, 3000.0)
    sy_s = np.clip(SY_TRUE + 0.05 * RNG.standard_normal(n), 0.01, 0.30)
    frac5 = glover_fraction(5.0 * 365.0, L_s, T_s, S_s)
    frac10 = glover_fraction(10.0 * 365.0, L_s, T_s, S_s)
    t10_s = L_s ** 2 * S_s / (4.0 * T_s * 1.1631 ** 2)
    r_s = np.array([rises[1] * 1000.0 * sv for sv in sy_s])
    print(f"  {n} Monte Carlo samples: T lognormal(sd of ln = 0.30), "
          f"S = {S_MED:.2f} +/- 0.05,")
    print(f"  L = {L_MED:.0f} +/- 250 m, Sy = {SY_TRUE:.2f} +/- 0.05")
    for name, arr, unit in (("time to 10% depletion", t10_s / 365.0, "y"),
                            ("depletion fraction at 5 y", frac5, "-"),
                            ("depletion fraction at 10 y", frac10, "-"),
                            ("WTF recharge", r_s, "mm/a")):
        q = np.percentile(arr, [5, 50, 95])
        print(f"   {name:26s}  5%: {q[0]:8.3f} {unit}   median: {q[1]:8.3f} "
              f"{unit}   95%: {q[2]:8.3f} {unit}")
    print("  the 5-95% range spans a factor "
          f"{np.percentile(t10_s, 95) / np.percentile(t10_s, 5):.1f} in the")
    print("  depletion time and a factor "
          f"{np.percentile(r_s, 95) / np.percentile(r_s, 5):.1f} in the recharge.")
    print("  -> a single-number recharge or safe yield is the median of a")
    print("     distribution whose width is set by parameters that were not")
    print("     measured.")
    q5 = 0.10 * LOW_FLOW / frac5
    q_lo, q_hi = np.percentile(q5, [95, 5])
    print(f"  the same arithmetic applied to the DECISION: the capture-limited")
    print(f"  pumping rate for 10% of the low flow at 5 years is")
    print(f"  {np.percentile(q5, 50):.0f} m^3/d (median), with a 5-95% range of "
          f"{q_lo:.0f} to {q_hi:.0f} m^3/d")

    section("6. The decision: two different yields")
    r_median = float(np.percentile(r_s, 50))
    yield_recharge = r_median / 1000.0 * AREA_KM2 * 1e6 / 365.0     # m^3/d
    print(f"  recharge-limited yield: R x A = {r_median:.1f} mm/a x "
          f"{AREA_KM2:.0f} km^2 = {yield_recharge:.0f} m^3/d")
    allowed = 0.10 * LOW_FLOW
    q_allow = allowed / float(glover_fraction(5.0 * 365.0))
    print(f"  capture-limited yield: the depletion at 5 years must stay below")
    print(f"  10% of a low-flow discharge of {LOW_FLOW:.0f} m^3/d, i.e. "
          f"{allowed:.0f} m^3/d;")
    print(f"  with a depletion fraction of "
          f"{float(glover_fraction(5.0 * 365.0)):.4f} at 5 years the permitted")
    print(f"  pumping is Q <= {q_allow:.0f} m^3/d.")
    print(f"  the recharge limit ({yield_recharge:.0f} m^3/d) is "
          f"{yield_recharge / q_allow:.1f} times the capture limit "
          f"({q_allow:.0f} m^3/d), so the")
    print("  binding constraint here is the stream, not the recharge.")
    print("  -> these two numbers answer different questions: 'how much water")
    print("     arrives' and 'how much can be taken without an unacceptable")
    print("     change somewhere else'.  'Sustainable yield' is a decision about")
    print("     the second, informed by the first, and it must name the")
    print("     receptor, the time horizon and the tolerated change.")
    print("\n   quantity                     value            measured or assumed")
    print(f"   specific yield               {SY_TRUE:.2f}             assumed in "
          f"the WTF inversion")
    print(f"   recharge (WTF, true Sy)      {r_wtf:6.1f} mm/a      model-derived "
          f"from a synthetic record")
    print(f"   recharge (CMB)               {r_cmb:6.1f} mm/a      assumed "
          f"chloride values")
    print(f"   time to 10% depletion        {t10:.0f} d           assumed T, S, L")
    print(f"   capture-limited yield        {q_allow:.0f} m^3/d        chosen "
          f"tolerance and low-flow value")


if __name__ == "__main__":
    main()
