#!/usr/bin/env python3
"""Notebooks versus pipelines: hidden state, execution order and stale outputs.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python notebooks_vs_pipelines_demo.py

Everything here is SYNTHETIC.  The notebook's cell graph is generated by the code
below with chosen parameters; no notebook file is parsed and no survey of
notebooks is quoted.  The results are properties of the generated graph.

Sections
--------
1. Execution orders: how many orderings of the cells are valid, exactly.
2. The probability that a random execution order is a valid one.
3. Stale outputs: how many cells are silently wrong after editing one cell.
4. The same graph as a pipeline: one state, no orderings.
"""

import numpy as np
from math import factorial

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC notebook model (chosen, not measured) ------------------------
N_CELLS = 14
N_EDGES = 20


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def build_cell_graph(n_cells, n_edges, rng):
    edges = set()
    while len(edges) < n_edges:
        i = int(rng.integers(0, n_cells - 1))
        j = int(rng.integers(i + 1, n_cells))
        edges.add((i, j))
    return sorted(edges)


def count_linear_extensions(n_cells, edges):
    """Exact count of orders where every dependency runs before its dependents.

    Dynamic programming over subsets of already-executed cells; the graph is
    small enough that 2**n_cells states are affordable.
    """
    preds = [0] * n_cells
    for i, j in edges:
        preds[j] |= 1 << i
    counts = np.zeros(1 << n_cells, dtype=np.float64)
    counts[0] = 1.0
    for mask in range(1 << n_cells):
        c = counts[mask]
        if c == 0.0:
            continue
        for j in range(n_cells):
            bit = 1 << j
            if mask & bit:
                continue
            if preds[j] & ~mask:
                continue
            counts[mask | bit] += c
    return float(counts[(1 << n_cells) - 1])


def descendants(n_cells, edges, start):
    out = set()
    frontier = [start]
    while frontier:
        node = frontier.pop()
        for i, j in edges:
            if i == node and j not in out:
                out.add(j)
                frontier.append(j)
    return out


def main():
    section("1. Execution orders: how many cell orders are valid?")
    edges = build_cell_graph(N_CELLS, N_EDGES, RNG)
    order_count = count_linear_extensions(N_CELLS, edges)
    total_orders = factorial(N_CELLS)
    print(f"SYNTHETIC notebook: {N_CELLS} cells, {N_EDGES} definition-use "
          f"dependencies (chosen)")
    print(f"  all possible execution orders            = {total_orders}")
    print(f"  valid orders (dependencies respected)    = {order_count:.0f}")
    print(f"  fraction of orders that are valid        = "
          f"{(order_count / total_orders):.9f}")
    print("  -> the notebook's output is a function of *which* valid order ran;")
    print("     the file records one order, the possible set is this size")

    section("2. Probability a random execution order is valid")
    print(f"  model: the saved outputs correspond to one valid order out of "
          f"{order_count:.0f}")
    print("  cells | dependencies | valid orders | P(a given order is valid)")
    for n_cells, n_edges in ((6, 4), (8, 8), (10, 12), (12, 16)):
        e = build_cell_graph(n_cells, n_edges, RNG)
        count = count_linear_extensions(n_cells, e)
        print(f"  {n_cells:>5d} | {n_edges:>12d} | {count:>12.0f} | "
              f"{count / factorial(n_cells):>28.3e}")
    print(f"  {N_CELLS:>5d} | {N_EDGES:>12d} | {order_count:>12.0f} | "
          f"{order_count / factorial(N_CELLS):>28.3e}   (the graph of section 1)")
    print("  -> for a dozen interacting cells the saved state is unreachable by")
    print("     chance; it exists only because someone ran the cells in an order")

    section("3. Stale outputs after editing one cell")
    stale = np.array([len(descendants(N_CELLS, edges, i))
                      for i in range(N_CELLS)])
    print(f"  edit any one cell -> mean {stale.mean():.1f} downstream cells "
          f"have stale output")
    print(f"  worst case        -> {int(stale.max())} of {N_CELLS} cells")
    print(f"  cells with no downstream dependents = {int((stale == 0).sum())}")
    print("  -> a notebook shows no warning for a stale cell: the output is simply")
    print("     the previous run's number, formatted the same way")

    section("4. The same graph as a pipeline")
    print(f"  pipeline states for the same graph = 1 (the scheduler re-runs the "
          f"invalidated subgraph)")
    print(f"  notebook states for the same graph = {order_count:.0f} valid orders")
    print(f"  ratio = {order_count:.0f} states to 1")
    print("  -> the pipeline does not make the analysis correct; it removes the")
    print("     order as a variable, which is what makes a wrong result visible")


if __name__ == "__main__":
    main()
