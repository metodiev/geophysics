#!/usr/bin/env python3
"""Environment pinning: how large is the space of "it worked on my machine"?

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python environment_pinning_demo.py

Everything here is SYNTHETIC.  The dependency sets, their admissible version
ranges and the re-upload model are generated by the code below with chosen
parameters.  No package index, lock file or artefact repository is queried.

Sections
--------
1. The admissible version space of an unpinned install.
2. What a lock file changes, and what it does not.
3. Detecting a silent artefact change: hashes, and how many are needed.
4. Transitive dependencies: the growth of the closure with depth.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC dependency model (chosen, not measured) ----------------------
N_DIRECT = 40          # direct dependencies of the analysis
MIN_VERSIONS = 3
MAX_VERSIONS = 9


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def main():
    section("1. The admissible version space of an unpinned install")
    n_versions = RNG.integers(MIN_VERSIONS, MAX_VERSIONS + 1, N_DIRECT)
    total = np.sum(np.log10(n_versions))
    print(f"SYNTHETIC environment: {N_DIRECT} direct dependencies, each with "
          f"{MIN_VERSIONS}-{MAX_VERSIONS} admissible releases (chosen)")
    print(f"  mean admissible releases per dependency = {n_versions.mean():.1f}")
    print(f"  number of admissible combinations       = 10^{total:.1f}")
    print(f"  probability two independent unpinned installs agree = "
          f"10^{-total:.1f}")
    print("  -> 'it worked on my machine' is a statement about one draw from a")
    print("     space this large; the draw is not recorded by a requirements list")

    section("2. What a lock file changes")
    print(f"  exact pins plus a record of the resolved set: 1 combination, "
          f"probability 1.0")
    print(f"  the same file with a floating patch version (e.g. '>=1.4,<2'): "
          f"mean {n_versions.mean():.1f} draws per dependency")
    print(f"  recording hashes of the artefacts as well: also detects a changed")
    print("  file at an unchanged version string")

    section("3. Detecting a silent artefact change")
    n_artefacts = 60
    p_change = 0.02       # chosen: fraction re-uploaded at the same version
    expected_changes = n_artefacts * p_change
    print(f"  {n_artefacts} artefacts, {p_change:.0%} re-uploaded at the same "
          f"version string (chosen)")
    print(f"  expected number of silent changes = {expected_changes:.2f}")
    print("  hashes recorded | coverage | P(a silent change is detected)")
    for k in (0, 1, 10, 30, 60):
        coverage = k / n_artefacts
        print(f"  {k:>15d} | {coverage:>8.3f} | {coverage:>32.3f}")
    print(f"  expected silent changes detected at full coverage = "
          f"{expected_changes * 1.0:.2f}")
    print("  -> a version string is an assertion; a hash is evidence, and the")
    print("     detection probability is the coverage of the hash set")

    section("4. Growth of the transitive dependency closure")
    print("  chosen branching factor 2.2 per depth, capped at 400 new packages")
    print("  depth | new packages at this depth | cumulative closure")
    frontier, cumulative = 6.0, 6
    for depth in range(1, 7):
        frontier = min(frontier * 2.2, 400.0)
        cumulative += int(frontier)
        print(f"  {depth:>5d} | {frontier:>27.0f} | {cumulative:>18d}")
    print("  -> the closure is where the unpinned space lives; a lock file pins")
    print("     the transitive set as well, which is the part a human never reads")


if __name__ == "__main__":
    main()
