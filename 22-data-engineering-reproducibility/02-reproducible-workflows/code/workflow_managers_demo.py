#!/usr/bin/env python3
"""Workflow managers: dependency graphs, scheduling and caching, on SYNTHETIC jobs.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python workflow_managers_demo.py

Everything here is SYNTHETIC.  The task graph, durations and cache behaviour are
generated by the code below with chosen parameters; no workflow engine is run and
no benchmark of a real system is quoted.

Sections
--------
1. The graph: serial cost, critical path and available parallelism.
2. Scheduling with W workers: makespan, speedup and efficiency.
3. Caching: recomputation after an input changes, with dependency-aware keys.
4. Core-hours versus wall time, and the cost of a wide graph.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC workflow model (chosen, not measured) ------------------------
N_TASKS = 24
MIN_DUR = 2.0          # minutes
MAX_DUR = 25.0
N_EDGES = 40
N_INPUTS = 6


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def build_dag(n_tasks, n_edges, rng):
    """Acyclic task graph: edge i -> j means j depends on i."""
    edges = set()
    while len(edges) < n_edges:
        i = int(rng.integers(0, n_tasks - 1))
        j = int(rng.integers(i + 1, n_tasks))
        edges.add((i, j))
    return sorted(edges)


def critical_path(n_tasks, durations, edges):
    """Longest path length through the DAG."""
    preds = {i: [] for i in range(n_tasks)}
    for i, j in edges:
        preds[j].append(i)
    finish = np.zeros(n_tasks)
    for j in range(n_tasks):
        finish[j] = durations[j] + max(
            [finish[i] for i in preds[j]], default=0.0)
    return float(finish.max())


def schedule(n_tasks, durations, edges, workers):
    """Greedy list schedule respecting dependencies: largest ready task first.

    A task starts no earlier than the finish of every predecessor and no earlier
    than the moment a worker is free; it takes the worker that frees earliest.
    """
    succ = {i: [] for i in range(n_tasks)}
    preds = {i: set() for i in range(n_tasks)}
    for i, j in edges:
        succ[i].append(j)
        preds[j].add(i)
    remaining = {i: set(s) for i, s in preds.items()}
    finish = np.zeros(n_tasks)
    free_at = np.zeros(workers)
    ready = [i for i in range(n_tasks) if not preds[i]]
    done = 0
    while done < n_tasks:
        ready.sort(key=lambda i: durations[i], reverse=True)
        i = ready.pop(0)
        earliest = max((finish[p] for p in preds[i]), default=0.0)
        starts = np.maximum(free_at, earliest)
        slot = int(np.argmin(starts))
        finish[i] = starts[slot] + durations[i]
        free_at[slot] = finish[i]
        done += 1
        for j in succ[i]:
            remaining[j].discard(i)
            if not remaining[j] and j not in ready:
                ready.append(j)
    return float(finish.max())


def invalidated(task_inputs, edges, changed):
    """Tasks re-run when `changed` inputs change, with descendant propagation."""
    dirty = {i for i, s in enumerate(task_inputs) if s & changed}
    frontier = list(dirty)
    while frontier:
        node = frontier.pop()
        for i, j in edges:
            if i == node and j not in dirty:
                dirty.add(j)
                frontier.append(j)
    return dirty


def main():
    section("1. The graph: serial cost, critical path and available parallelism")
    durations = RNG.uniform(MIN_DUR, MAX_DUR, N_TASKS).round(1)
    edges = build_dag(N_TASKS, N_EDGES, RNG)
    task_inputs = [set(RNG.choice(N_INPUTS, size=int(RNG.integers(1, 4)),
                                  replace=False)) for _ in range(N_TASKS)]
    serial = float(durations.sum())
    cp = critical_path(N_TASKS, durations, edges)
    print(f"SYNTHETIC workflow: {N_TASKS} tasks, {N_EDGES} dependencies, "
          f"durations {MIN_DUR:.0f}-{MAX_DUR:.0f} min (chosen)")
    print(f"  serial cost (one core, in order)   = {serial:.1f} min")
    print(f"  critical path (longest chain)      = {cp:.1f} min")
    print(f"  maximum speedup available          = {serial / cp:.2f}x")
    print(f"  mean parallelism during the run    = {serial / cp:.2f} tasks")

    section("2. Scheduling with W workers")
    print("  workers | makespan (min) | speedup | efficiency")
    for w in (1, 2, 4, 8):
        makespan = schedule(N_TASKS, durations, edges, w)
        speedup = serial / makespan
        print(f"  {w:>7d} | {makespan:>14.1f} | {speedup:>7.2f} | "
              f"{speedup / w:>10.2f}")
    print("  -> a workflow manager buys the critical path, not the task count;")
    print("     beyond a few workers the graph, not the machine, is the limit")

    section("3. Caching: recomputation after an input changes")
    print("  model: a task is re-run if any of its inputs changed, and every")
    print("  descendant is then re-run too (chosen dependency-aware rule)")
    print(f"  each task reads 1-3 of the {N_INPUTS} inputs; 200 draws per row")
    print("  inputs changed | tasks re-run (mean) | fraction of the workflow")
    for n_change in (1, 2, 3, N_INPUTS):
        counts = []
        for _ in range(200):
            changed = set(RNG.choice(N_INPUTS, size=n_change, replace=False))
            counts.append(len(invalidated(task_inputs, edges, changed)))
        mean_recomputed = float(np.mean(counts))
        print(f"  {n_change:>14d} | {mean_recomputed:>19.1f} | "
              f"{100.0 * mean_recomputed / N_TASKS:>23.0f} %")
    print("  -> caching is what makes a 30-minute workflow affordable to edit;")
    print("     the invalidation rule is where its correctness lives")

    section("4. Core-hours versus wall time")
    w = 4
    makespan = schedule(N_TASKS, durations, edges, w)
    core_hours = serial / 60.0
    wall = makespan / 60.0
    idle = w * wall - core_hours
    print(f"  serial core-time = {core_hours:.2f} core-hours, "
          f"wall time on {w} workers = {wall:.2f} h")
    print(f"  idle allocation while waiting = {idle:.2f} core-hours "
          f"({100.0 * idle / (w * wall):.0f} % of the allocation)")
    print("  -> the ceiling is the critical path: past about eight workers this")
    print("     graph cannot go faster, and most of a four-worker allocation waits")


if __name__ == "__main__":
    main()
