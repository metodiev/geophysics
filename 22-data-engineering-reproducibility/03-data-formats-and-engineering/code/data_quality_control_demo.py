#!/usr/bin/env python3
"""Automated quality control: flagging rules measured against known truth.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python data_quality_control_demo.py

Everything here is SYNTHETIC.  The record, the injected spikes and the gaps are
generated by the code below, so the true labels are known exactly; no real record
is used and no published QC threshold is quoted.

Sections
--------
1. A synthetic record with known outliers, in two contamination levels.
2. Three flagging rules and their confusion matrices.
3. Threshold stability: masking by the very outliers being detected.
4. Gaps: missing is not zero, and what a fill does to a rate detector.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC record and QC model (chosen, not measured) -------------------
N = 2000             # samples at 1 Hz
SIGMA = 1.0          # background noise, data units
SPIKES = [(12, 12.0), (100, 4.0)]   # (count, size in sigma) scenarios
N_GAPS = 4
GAP_LEN = 25


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def confusion(flagged, truth):
    tp = int((flagged & truth).sum())
    fp = int((flagged & ~truth).sum())
    fn = int((~flagged & truth).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    return tp, fp, fn, precision, recall


def make_record(n_spikes, size):
    x = RNG.normal(0.0, SIGMA, N)
    truth = np.zeros(N, dtype=bool)
    if n_spikes == 0:
        return x, truth
    idx = RNG.choice(N, size=n_spikes, replace=False)
    x[idx] += size * SIGMA * RNG.choice([-1.0, 1.0], n_spikes)
    truth[idx] = True
    return x, truth


def main():
    section("1. A synthetic record with known outliers")
    print(f"SYNTHETIC record: {N} samples at 1 Hz, sigma = {SIGMA:.1f} (data "
          f"units)")
    print(f"  a 3-sigma rule on clean Gaussian data flags {100 * 0.0027:.2f} % of")
    print(f"  samples, i.e. {0.0027 * N:.1f} of {N} by chance: that is the "
          f"false-positive budget")
    print("  scenario           | naive 3 sd | robust 3 x 1.4826 MAD")
    for n_sp, size in SPIKES:
        x, _ = make_record(n_sp, size)
        med = np.median(x)
        robust = 1.4826 * np.median(np.abs(x - med))
        print(f"  {n_sp:>3d} spikes at {size:>2.0f} sigma | "
              f"{3 * x.std():>10.3f} | {3 * robust:>22.3f}")
    print("  -> the naive scale is set by the outliers themselves; the robust")
    print("     scale is set by the bulk of the data and barely moves")

    section("2. Three flagging rules and their confusion matrices")
    for n_sp, size in SPIKES:
        x, truth = make_record(n_sp, size)
        med = np.median(x)
        robust = 1.4826 * np.median(np.abs(x - med))
        rules = {
            "mean +/- 3 sd": np.abs(x - np.mean(x)) > 3 * x.std(),
            "median +/- 3 x 1.4826 MAD": np.abs(x - med) > 3 * robust,
            "rate of change > 8 sigma":
                np.abs(np.diff(x, prepend=x[0])) > 8 * SIGMA,
        }
        print(f"  scenario: {n_sp} spikes at {size:.0f} sigma")
        print("    rule                         |  TP |  FP |  FN | precision | "
              "recall")
        for name, flagged in rules.items():
            tp, fp, fn, prec, rec = confusion(flagged, truth)
            print(f"    {name:<28} | {tp:>3d} | {fp:>3d} | {fn:>3d} | "
                  f"{prec:>9.3f} | {rec:>6.3f}")
    print("  -> a rule is a decision with two error rates, and the trade changes")
    print("     with the contamination: at 12 large spikes the naive threshold is")
    print("     conservative because the spikes inflate it; at 100 moderate spikes")
    print("     the naive rule misses most of them and the robust rule does not")

    section("3. Threshold stability: masking by the outliers")
    print("  contamination          | naive 3 sd | robust 3 x MAD | ratio")
    scenarios = [(0, 0.0)] + SPIKES
    for n_sp, size in scenarios:
        x, _ = make_record(n_sp, size)
        med = np.median(x)
        robust = 1.4826 * np.median(np.abs(x - med))
        naive_th = 3 * x.std()
        robust_th = 3 * robust
        label = "clean" if n_sp == 0 else f"{n_sp} at {size:.0f} sigma"
        print(f"  {label:<22} | {naive_th:>10.3f} | {robust_th:>14.3f} | "
              f"{naive_th / robust_th:>5.2f}")
    print("  -> the naive threshold moves with the contamination, so it cannot be")
    print("     quoted as a fixed number, and its recall falls exactly when the")
    print("     data are worst; that is masking")

    section("4. Gaps: missing is not zero")
    print("  model: a clean record, with a stated fraction of samples missing")
    print("  missing | fill  | mean      | sd      | fake zeros presented as data")
    for frac, n_gaps in ((0.05, 4), (0.30, 12)):
        x, _ = make_record(0, 0.0)
        gap_len = int(frac * N / n_gaps)
        for _ in range(n_gaps):
            start = int(RNG.integers(1, N - gap_len))
            x[start:start + gap_len] = np.nan
        gap_mask = np.isnan(x)
        filled = np.where(gap_mask, 0.0, x)
        print(f"  {100 * frac:>6.0f} % | NaN   | {np.nanmean(x):+.5f}  | "
              f"{np.nanstd(x):.4f}  | {0:>28d}")
        print(f"  {100 * frac:>6.0f} % | zero  | {filled.mean():+.5f}  | "
              f"{filled.std():.4f}  | {int(gap_mask.sum()):>28d}")
    print("  -> the zero fill moves the mean and, more importantly, shrinks the")
    print("     standard deviation, because the fake zeros are closer to the mean")
    print("     than the data they replaced. The damage is silent: each fake zero")
    print("     carries no flag, no NaN and no marker, so every later statistic")
    print("     treats it as a measurement")
    print("  -> NaN is the only honest placeholder, and every estimator must then")
    print("     state how it treats missing values")


if __name__ == "__main__":
    main()
