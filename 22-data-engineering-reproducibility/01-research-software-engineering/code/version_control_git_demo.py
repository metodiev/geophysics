#!/usr/bin/env python3
"""Git-style branching, merging and conflict rates on SYNTHETIC histories.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python version_control_git_demo.py

Everything here is SYNTHETIC.  The commit history is generated by the code below
and the conflict statistics come from a line-overlap model of a three-way merge.
No real repository is read and no published conflict rate is quoted.

Sections
--------
1. A generated branch/merge history: shape and merge-base distances.
2. Conflict probability as a function of how far apart two edits are.
3. Why the context window, not the edit size, sets the conflict distance.
4. Rebase cost: conflicts per rebase, and the effect of rebasing early.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC history parameters (chosen, not measured) --------------------
N_BRANCHES = 40          # feature branches
FILE_LINES = 800         # size of the file under concurrent editing
CONTEXT = 3              # merge context lines kept around a change
EDIT_LEN = 20            # lines an average change rewrites
TRIALS = 20000           # Monte Carlo trials per separation


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def branch_history(n_branches, file_lines, rng):
    """SynthETIC feature-branch history: (base, length, merges)."""
    base = rng.integers(0, file_lines, size=n_branches)
    length = np.clip(rng.poisson(EDIT_LEN, size=n_branches), 1, None)
    lifetime_days = np.clip(rng.exponential(9.0, size=n_branches), 1, None)
    commits = np.clip(rng.poisson(6.0, size=n_branches), 1, None)
    return base, length, lifetime_days, commits


def conflict_probability(separation, context, edit_len, trials, rng):
    """P(two edits conflict) given the gap between their start lines.

    Edit lengths are random (Poisson with mean `edit_len`), so the region gap
    between the two edits is a random variable and the result is a probability.
    A conflict occurs when the two regions are closer than twice the merge
    context.
    """
    a_len = np.clip(rng.poisson(edit_len, size=trials), 1, None)
    a_start = rng.integers(0, 10_000, size=trials)
    gap = (a_start + separation) - (a_start + a_len)
    return float((gap <= 2 * context).mean())


def main():
    section("1. A generated branch/merge history")
    base, length, lifetime, commits = branch_history(N_BRANCHES, FILE_LINES, RNG)
    total_commits = int(commits.sum()) + N_BRANCHES      # + one merge each
    print(f"SYNTHETIC history: {N_BRANCHES} feature branches over a "
          f"{FILE_LINES}-line file")
    print(f"  total commits including merges          = {total_commits}")
    print(f"  mean commits per branch                 = {commits.mean():.1f}")
    print(f"  mean branch lifetime                    = {lifetime.mean():.1f} days "
          f"+/- {lifetime.std():.1f} (s.d.)")
    print(f"  mean lines touched per branch           = {length.mean():.1f} "
          f"+/- {length.std():.1f}")
    overlap = np.zeros((N_BRANCHES, N_BRANCHES), dtype=bool)
    for i in range(N_BRANCHES):
        lo_i, hi_i = base[i], base[i] + length[i]
        for j in range(i + 1, N_BRANCHES):
            lo_j, hi_j = base[j], base[j] + length[j]
            overlap[i, j] = (min(hi_i, hi_j) + 2 * CONTEXT) >= max(lo_i, lo_j)
    pairs = N_BRANCHES * (N_BRANCHES - 1) // 2
    n_conf = int(overlap.sum())
    print(f"  branch pairs whose edits overlap        = {n_conf} / {pairs} "
          f"({100.0 * n_conf / pairs:.1f} %)")
    print("  -> integration pain is a property of the file layout and branch "
          "lifetime, not of the tool")

    section("2. Conflict probability versus separation of two edits")
    print(f"  edit length {EDIT_LEN} lines, merge context {CONTEXT} lines, "
          f"{TRIALS} trials per row")
    print("  separation (lines) | conflict probability")
    for sep in (0, 5, 10, 15, 20, 30, 40, 60):
        p = conflict_probability(sep, CONTEXT, EDIT_LEN, TRIALS, RNG)
        print(f"  {sep:>18d} | {p:6.3f}")
    p_zero = conflict_probability(0, CONTEXT, EDIT_LEN, TRIALS, RNG)
    print(f"  -> the risk decays over roughly one edit length "
          f"({EDIT_LEN} lines); at zero separation it is {p_zero:.3f}")

    section("3. The context window sets the conflict distance")
    for ctx in (0, 1, 3, 6):
        p = conflict_probability(EDIT_LEN, ctx, EDIT_LEN, TRIALS, RNG)
        print(f"  context = {ctx:>2d} lines -> conflict probability at "
              f"separation {EDIT_LEN} lines = {p:.3f}")
    print("  -> shrinking the context window near a boundary (or keeping edits "
          "short) buys integration, not cleverness in the merge tool")

    section("4. Rebase cost and the effect of rebasing early")
    print("  model: a branch that waits W days accumulates W x 5 edits/day, "
          "each conflicting with probability 0.03 (chosen)")
    for wait_days in (1, 3, 10, 30):
        edits = wait_days * 5
        prob_any = 1.0 - (1.0 - 0.03) ** edits
        print(f"  wait {wait_days:>2d} days, {edits:>3d} upstream edits -> "
              f"P(at least one conflict) = {prob_any:.3f}")
    print("  -> rebasing on a one-day cadence holds the conflict probability "
          "near 10 %, while a monthly wait makes it a near-certainty")


if __name__ == "__main__":
    main()
