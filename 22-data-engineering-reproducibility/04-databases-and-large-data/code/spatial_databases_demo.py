#!/usr/bin/env python3
"""Spatial databases: grid indexes, bounding boxes and distance queries.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python spatial_databases_demo.py

Everything here is SYNTHETIC.  The point set is generated by the code below and the
cell model uses chosen tile sizes; no spatial database was queried and no real
station catalogue is used.

Sections
--------
1. A synthetic point set and the cost of a naive bounding-box scan.
2. Tile size versus candidate count: the spatial equivalent of chunking.
3. Distance queries: spherical distance and the planar approximation's error.
4. Spatial joins: how many candidate pairs the grid produces.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC point set and model (chosen, not measured) -------------------
N_POINTS = 200_000
LON_RANGE = (-125.0, -114.0)
LAT_RANGE = (32.0, 42.0)
TILE_DEG = [0.05, 0.1, 0.25, 0.5, 1.0]
EARTH_RADIUS_KM = 6371.0088


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def haversine(lon1, lat1, lon2, lat2):
    p1, p2 = np.radians(lat1), np.radians(lat2)
    dp = p2 - p1
    dl = np.radians(lon2 - lon1)
    a = np.sin(dp / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * EARTH_RADIUS_KM * np.arcsin(np.sqrt(a))


def main():
    section("1. A synthetic point set and a naive bounding-box scan")
    lon = RNG.uniform(*LON_RANGE, N_POINTS)
    lat = RNG.uniform(*LAT_RANGE, N_POINTS)
    q = (-120.5, -119.5, 36.5, 37.5)     # lon_min, lon_max, lat_min, lat_max
    inside = ((lon >= q[0]) & (lon <= q[1]) & (lat >= q[2]) & (lat <= q[3]))
    area_frac = ((q[1] - q[0]) * (q[3] - q[2])) / \
        ((LON_RANGE[1] - LON_RANGE[0]) * (LAT_RANGE[1] - LAT_RANGE[0]))
    print(f"SYNTHETIC point set: {N_POINTS:,} points over "
          f"{LON_RANGE[1] - LON_RANGE[0]:.0f} x {LAT_RANGE[1] - LAT_RANGE[0]:.0f} "
          f"degrees (chosen)")
    print(f"  query box area fraction = {100 * area_frac:.4f} %")
    print(f"  points returned = {int(inside.sum())}")
    print(f"  work without an index = {N_POINTS:,} point tests "
          f"({N_POINTS / 1e6:.2f} M)")
    print("  -> the scan's cost is set by the table, not by the answer; an index")
    print("     is what makes a small box cheap")

    section("2. Tile size versus candidate count")
    print("  tile (deg) | tiles | candidates tested | fraction of the table")
    for tile in TILE_DEG:
        i0 = int(np.floor((q[0] - LON_RANGE[0]) / tile))
        i1 = int(np.floor((q[1] - LON_RANGE[0]) / tile))
        j0 = int(np.floor((q[2] - LAT_RANGE[0]) / tile))
        j1 = int(np.floor((q[3] - LAT_RANGE[0]) / tile))
        tiles_x = int(np.ceil((LON_RANGE[1] - LON_RANGE[0]) / tile))
        tiles_y = int(np.ceil((LAT_RANGE[1] - LAT_RANGE[0]) / tile))
        n_tiles = (i1 - i0 + 1) * (j1 - j0 + 1)
        cand = n_tiles / (tiles_x * tiles_y) * N_POINTS
        print(f"  {tile:>10.2f} | {tiles_x * tiles_y:>5d} | {cand:>17.0f} | "
              f"{100 * cand / N_POINTS:>19.2f} %")
    print("  -> smaller tiles cut the candidate count but multiply the index")
    print("     entries; the query box size sets the useful tile size")

    section("3. Distance queries: spherical versus planar")
    a_lon, a_lat = -120.0, 37.0
    for d_deg in (0.01, 0.1, 1.0, 5.0, 20.0, 45.0):
        b_lon, b_lat = a_lon + d_deg, a_lat + d_deg / 2.0
        sph = haversine(a_lon, a_lat, b_lon, b_lat)
        mean_lat = np.radians((a_lat + b_lat) / 2)
        planar = EARTH_RADIUS_KM * np.hypot(
            np.radians(b_lon - a_lon) * np.cos(mean_lat),
            np.radians(b_lat - a_lat))
        err = abs(planar - sph) / sph
        print(f"  separation {d_deg:>5.2f} deg: spherical {sph:>10.2f} km, "
              f"planar {planar:>10.2f} km, error {100 * err:>6.3f} %")
    print("  -> the planar approximation is exact enough at short range and")
    print("     degrades steadily with separation; state which one a tolerance")
    print("     relies on, because the error is silent")

    section("4. Spatial joins: candidate pairs from the grid")
    lon2 = RNG.uniform(*LON_RANGE, N_POINTS // 2)
    lat2 = RNG.uniform(*LAT_RANGE, N_POINTS // 2)
    tile = 0.25
    key1 = (np.floor((lon - LON_RANGE[0]) / tile).astype(int),
            np.floor((lat - LAT_RANGE[0]) / tile).astype(int))
    key2 = (np.floor((lon2 - LON_RANGE[0]) / tile).astype(int),
            np.floor((lat2 - LAT_RANGE[0]) / tile).astype(int))
    from collections import Counter
    c1 = Counter(zip(key1[0].tolist(), key1[1].tolist()))
    candidates = sum(c1[k] * n for k, n in Counter(
        zip(key2[0].tolist(), key2[1].tolist())).items())
    cross = N_POINTS * (N_POINTS // 2)
    print(f"  two sets of {N_POINTS:,} and {N_POINTS // 2:,} points, tile "
          f"{tile} deg")
    print(f"  pairs without an index = {cross / 1e9:.2f} billion")
    print(f"  candidate pairs within a shared tile = {candidates / 1e6:.2f} million")
    print(f"  reduction = {cross / max(candidates, 1):.0f}x")
    print("  -> the grid turns a quadratic join into a local one; a neighbouring-")
    print("     tile rule is still needed, because points near a boundary pair")
    print("     across tiles")


if __name__ == "__main__":
    main()
