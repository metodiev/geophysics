#!/usr/bin/env python3
"""Time-series databases: compression, downsampling and retention.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python timeseries_databases_demo.py

Everything here is SYNTHETIC.  The series is generated by the code below, and the
compression model is the standard delta-of-delta plus bit-packing idea applied with
chosen widths; no database was queried.

Sections
--------
1. A sensor series and the storage of the naive representation.
2. Delta and delta-of-delta compression: measured ratios on a synthetic series.
3. Downsampling for queries: bytes read for a coarse query.
4. Retention: the cost of keeping raw, and what an aggregate buys.
"""

import zlib

import numpy as np

RNG = np.random.default_rng(20261014)

# --- SYNTHETIC series and model (chosen, not measured) ----------------------
N = 1_000_000          # samples at 1 Hz (~11.6 days)
SIGMA = 1.0            # noise, data units
TREND = 0.0005         # slow drift per sample, data units
RAW_BITS = 64          # float64
PRECISION = 1e-3       # quantisation step of the compressed representation
TIMESTAMP_BITS = 32


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def main():
    section("1. A sensor series and its naive storage")
    t = np.arange(N)
    x = TREND * t + RNG.normal(0.0, SIGMA, N)
    raw_bytes = N * RAW_BITS / 8
    raw_ts = N * TIMESTAMP_BITS / 8
    print(f"SYNTHETIC series: {N:,} samples at 1 Hz, sigma = {SIGMA:.1f} "
          f"(chosen)")
    print(f"  span = {N / 86400:.1f} days")
    print(f"  values only        = {raw_bytes / 1e6:.1f} MB "
          f"({RAW_BITS / 8:.0f} B per sample)")
    print(f"  with 4-byte stamps = {(raw_bytes + raw_ts) / 1e6:.1f} MB")
    print(f"  a station archive needs {365 / (N / 86400):.0f}x this per year, "
          f"per channel")

    section("2. Compression: bit-packing the second difference")
    print(f"  model: quantise the second difference at {PRECISION:.1e} data units,")
    print("  store it in the bits its magnitude needs plus a sign (Gorilla-style);")
    print("  the scheme is lossy by construction, with error <= precision/2")
    print("  series                    | s.d. of 2nd diff | mean bits | ratio")
    series = {
        "noise-dominated (sigma 1)": TREND * t + RNG.normal(0.0, SIGMA, N),
        "smooth (sigma 0.01)": TREND * t + RNG.normal(0.0, 0.01, N),
    }
    for name, s in series.items():
        d2 = np.diff(np.diff(s))
        q = np.round(d2 / PRECISION)
        bits = 2 + np.ceil(np.log2(np.abs(q) + 1.0))
        mean_bits = float(np.clip(bits, 2, 32).mean())
        print(f"  {name:<25} | {d2.std():>16.2e} | {mean_bits:>9.1f} | "
              f"{RAW_BITS / mean_bits:>7.2f}x")
    print(f"  quantisation error bound = {PRECISION / 2:.1e} data units, against a")
    print(f"  signal of order {SIGMA:.1f}: the loss is far below the noise")
    print("  -> the second difference removes the trend, so the ratio is set by")
    print("     how much of the signal is noise; the same scheme gives different")
    print("     numbers on different series, so measure rather than assume")

    section("3. Downsampling for queries")
    print("  query interval | raw bytes read | downsampled bytes | ratio")
    for hours in (1, 24, 24 * 7):
        n_raw = hours * 3600                     # 1 Hz samples
        n_down = hours * 60                      # 1-minute means
        raw = n_raw * RAW_BITS / 8
        down = n_down * RAW_BITS / 8
        print(f"  {hours:>14.0f} h | {raw / 1e3:>14.1f} kB | "
              f"{down / 1e3:>17.1f} kB | {raw / down:>5.0f}x")
    print("  -> a plotted day needs a downsampled view; reading raw and reducing")
    print("     in the client costs the full byte count for every plot")

    section("4. Retention: raw against aggregates")
    per_year_raw = 365 * 86400 * (RAW_BITS / 8) / 1e9
    per_year_1min = 365 * 1440 * (RAW_BITS / 8) / 1e9
    per_year_1h = 365 * 24 * (RAW_BITS / 8) / 1e9
    print(f"  per channel per year: raw {per_year_raw:.2f} GB, "
          f"1-minute means {per_year_1min:.3f} GB, "
          f"hourly means {per_year_1h:.5f} GB")
    print(f"  a 100-channel network's raw archive = "
          f"{100 * per_year_raw:.0f} GB/year")
    print(f"  keeping raw plus both aggregates = "
          f"{100 * (per_year_raw + per_year_1min + per_year_1h):.1f} GB/year "
          f"({100 * (per_year_1min + per_year_1h) / per_year_raw:.2f} % overhead)")
    print("  -> aggregates are a negligible storage cost and a large query")
    print("     saving; the decision to keep raw is about what may need")
    print("     reprocessing, not about space")


if __name__ == "__main__":
    main()
