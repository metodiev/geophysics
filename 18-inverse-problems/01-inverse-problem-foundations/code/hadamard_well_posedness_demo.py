#!/usr/bin/env python3
"""Hadamard's three conditions, tested numerically one at a time.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python hadamard_well_posedness_demo.py

Everything here is SYNTHETIC.  The mass and layer models are teaching models and
all noise is generated in this script.

Contents
--------
1. Existence: data generated by a deep source cannot be fitted by a shallow
   parameterisation -- the misfit floor sits far above the noise.
2. Uniqueness: for a horizontally layered Earth the surface gravity fixes only
   the total mass per unit area, so the null space is (M-1)-dimensional and two
   very different models give bit-identical data.
3. Uniqueness can be bought with data: borehole gravity levels raise the rank
   one at a time until the null space closes at 12 independent measurements.
4. Rank is tolerance-dependent for a discretised compact operator.
5. Stability: the condition number of the discretised kernel grows under
   refinement, and central-difference differentiation diverges like 1/h.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

G_CONST = 6.67430e-11        # m^3 kg^-1 s^-2, exact (2018 CODATA)
MGAL = 1.0e-5                # m/s^2 per mGal, exact by definition
X_KM = np.linspace(-10.0, 10.0, 21)


def gravity_kernel(x_km, z_km):
    """Vertical gravity per unit mass, mGal/kg: G z / (x^2+z^2)^(3/2)."""
    x = x_km[:, None] * 1e3
    z = z_km[None, :] * 1e3
    return (G_CONST * z / (x ** 2 + z ** 2) ** 1.5) / MGAL


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def main():
    section("1. EXISTENCE: data outside the range of the operator")
    z_shallow = np.array([1.0, 2.0, 3.0])
    G_shallow = gravity_kernel(X_KM, z_shallow)
    d_true = gravity_kernel(X_KM, np.array([8.0, 12.0])) @ (np.array([1.0, 1.2]) * 1e10)
    noise = 1e-3 * np.abs(d_true).max() * RNG.standard_normal(d_true.size)
    d_obs = d_true + noise
    m_ls, *_ = np.linalg.lstsq(G_shallow, d_obs, rcond=None)
    r = d_obs - G_shallow @ m_ls
    print(f"  model space: 3 masses at depths {z_shallow} km")
    print(f"  true source: masses at 8 and 12 km (not representable)")
    print(f"  data space : {X_KM.size} gravity readings in mGal")
    print(f"  noise rms            = {noise.std():.4e} mGal "
          f"({noise.std() / np.abs(d_true).max() * 100:.3f}% of peak |d|)")
    print(f"  ||d_obs||            = {np.linalg.norm(d_obs):.6e} mGal")
    print(f"  ||d_obs - G m_ls||   = {np.linalg.norm(r):.6e} mGal")
    print(f"  relative misfit      = {np.linalg.norm(r) / np.linalg.norm(d_obs) * 100:.3f}%")
    print(f"  misfit / noise norm  = {np.linalg.norm(r) / np.linalg.norm(noise):.1f}")
    print("  The best shallow model leaves a misfit 182 times the noise.  No model")
    print("  in this parameterisation explains the data: existence fails.")

    section("2. UNIQUENESS: an exactly non-unique layered gravity problem")
    # For a horizontally layered Earth, the surface gravity anomaly is the
    # Bouguer-slab sum  g = 2 pi G  sum_k rho_k h_k.  The kernel row is constant,
    # so any zero-mean redistribution of density has exactly zero effect.
    h_m = 1000.0
    c_mgal = 2.0 * np.pi * G_CONST * h_m * 1e5      # mGal per (kg/m^3) per layer
    z_c = np.arange(12) + 0.5                       # layer centres, km
    G_row = c_mgal * np.ones((1, 12))
    m1 = np.full(12, 100.0)                         # kg/m^3, uniform
    n_null = 50.0 * np.array([1.0, -1.0] * 6)       # zero-mean perturbation
    m2 = m1 + n_null
    s = np.linalg.svd(G_row, compute_uv=False)
    rank = int(np.sum(s > 1e-10 * s[0]))
    print(f"  model: {12} layers of {h_m / 1000.0:.1f} km, density rho_k in kg/m^3")
    print(f"  data : one surface gravity value, g = 2*pi*G*h*sum(rho_k), in mGal")
    print(f"  kernel value c = 2*pi*G*h = {c_mgal:.8f} mGal per (kg/m^3) per layer")
    print(f"  (equivalently 0.0419 mGal per metre per g/cm^3: the Bouguer constant)")
    print(f"  model space dimension M = 12, data rank = {rank}, "
          f"null-space dimension = {12 - rank}")
    print(f"  ||G n_null||_inf         = {np.max(np.abs(G_row @ n_null)):.3e} mGal")
    print(f"  g(m1) = {(G_row @ m1)[0]:.6f} mGal, "
          f"g(m2) = {(G_row @ m2)[0]:.6f} mGal, "
          f"difference = {(G_row @ (m1 - m2))[0]:.3e} mGal")
    print(f"  ||m2 - m1|| / ||m1||     = {np.linalg.norm(m2 - m1) / np.linalg.norm(m1):.4f}")
    print(f"  max_k |m2_k - m1_k|      = {np.max(np.abs(m2 - m1)):.1f} kg/m^3")
    print("  Two models differing by 50 kg/m^3 in every layer produce BIT-IDENTICAL")
    print("  surface gravity, because the data constrain only the total mass per")
    print("  unit area.  Uniqueness fails exactly, not approximately.")

    section("3. UNIQUENESS CAN BE BOUGHT: borehole gravity levels")
    # A sensor at depth d sees a layer below it (z_k > d) pull downward (+) and a
    # layer above it pull upward (-): the classic slab sign convention.
    def G_layered(depths):
        rows = [np.ones(12)]
        for d in depths:
            rows.append(np.where(z_c > d, 1.0, -1.0))
        return c_mgal * np.array(rows)

    print("   borehole levels   data rows   rank   null-space dimension")
    for nbh in (0, 1, 3, 5, 8, 11):
        depths = np.linspace(1.0, 12.0, nbh, endpoint=False) if nbh else np.array([])
        Gm = G_layered(depths)
        sv = np.linalg.svd(Gm, compute_uv=False)
        rk = int(np.sum(sv > 1e-8 * sv[0]))
        print(f"   {nbh:15d}   {Gm.shape[0]:9d}   {rk:4d}   {12 - rk:18d}")
    Gm = G_layered(np.linspace(1.0, 12.0, 11, endpoint=False))
    d_full = Gm @ m1
    errs = []
    for _ in range(200):
        nn = 1e-3 * np.abs(d_full).max() * RNG.standard_normal(d_full.size)
        me, *_ = np.linalg.lstsq(Gm, d_full + nn, rcond=None)
        errs.append(np.linalg.norm(me - m1) / np.linalg.norm(m1))
    print(f"  with 12 independent levels and noise at 0.1% of the peak datum,")
    print(f"  the recovered density profile has mean error {np.mean(errs) * 100:.3f}%")
    print("  (worst of 200 realisations: {:.3f}%).  The formerly invisible".format(np.max(errs) * 100))
    print("  direction is now measured, at a cost of 11 extra soundings.")

    section("4. RANK IS TOLERANCE-DEPENDENT (discretised compact operator)")
    z_thin = 5.00 + 0.05 * np.arange(8)
    G_thin = gravity_kernel(X_KM, z_thin)
    sv = np.linalg.svd(G_thin, compute_uv=False)
    print(f"  G_thin: {G_thin.shape[0]} stations x {G_thin.shape[1]} closely spaced masses")
    print(f"  relative singular values: {np.array2string(sv / sv[0], precision=3)}")
    print("   relative tolerance   numerical rank   null-space dimension")
    for tol in (1e-6, 1e-10, 1e-12):
        rk = int(np.sum(sv > tol * sv[0]))
        print(f"   {tol:18.0e}   {rk:14d}   {8 - rk:20d}")
    print("  Section 2 had an exact null space.  Here the null space is only")
    print("  'effective': how many directions you call unresolved depends on the")
    print("  data precision you declare.  Always state the tolerance.")

    section("5. STABILITY: refinement and differentiation")
    print("(a) condition number of the discretised gravity kernel under refinement")
    print("    cells M   cell size (km)   sigma_max     sigma_min     kappa(G)      eps*sigma_max")
    for M in (4, 8, 16, 32, 64):
        zz = 5.0 + (np.arange(M) - (M - 1) / 2.0) * (4.0 / M)
        sM = np.linalg.svd(gravity_kernel(X_KM, zz), compute_uv=False)
        print(f"    {M:7d}   {4.0 / M:14.3f}   {sM[0]:.4e}   {sM[-1]:.4e}   "
              f"{sM[0] / sM[-1]:.4e}   {np.finfo(float).eps * sM[0]:.3e}")
    print("    kappa grows by orders of magnitude per refinement until, at M = 64,")
    print("    sigma_min drops below eps*sigma_max and the printed value is roundoff.")
    print("    Every discrete problem has a bounded inverse; the continuum problem")
    print("    it approximates does not, and refinement is what exposes that.")
    print()
    print("(b) f(t) = sin(t) at t = 1, central difference, sample error +-1e-6")
    print(f"    exact derivative cos(1) = {np.cos(1.0):.7f}")
    print("    h        |measured f' - cos 1|   truncation ~ cos(1)h^2/6   noise ~ 1e-6/h")
    for h in (1e-1, 3e-2, 1e-2, 3e-3, 1e-3, 3e-4):
        n1 = 1e-6 * (2.0 * RNG.random() - 1.0)
        n2 = 1e-6 * (2.0 * RNG.random() - 1.0)
        num = (np.sin(1.0 + h) + n1 - np.sin(1.0 - h) - n2) / (2.0 * h)
        print(f"    {h:.0e}   {abs(num - np.cos(1.0)):22.3e}   "
              f"{np.cos(1.0) * h ** 2 / 6.0:24.3e}   {1e-6 / h:15.3e}")
    print("    Below h ~ 1e-2 the noise term 1e-6/h dominates and the error GROWS")
    print("    as h shrinks: the inverse operator d/dt has no Lipschitz constant.")
    print("    This is Hadamard's own example of an ill-posed problem.")


if __name__ == "__main__":
    main()
