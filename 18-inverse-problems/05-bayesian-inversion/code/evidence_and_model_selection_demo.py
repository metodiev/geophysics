#!/usr/bin/env python3
"""Bayesian evidence and model selection: Occam's razor, measured.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python evidence_and_model_selection_demo.py

All models and data in this demo are SYNTHETIC.  The polynomial family, the
prior width and the noise level are chosen teaching values, not measurements.

Contents
--------
1. The model family and the exact (analytic) evidence for each order.
2. Evidence, BIC and AIC compared on the same data.
3. The Laplace approximation to the evidence, and its measured error.
4. The Occam factor: evidence as best-fit likelihood times prior volume ratio.
5. Independent check of the analytic evidence by direct numerical integration.
6. Sensitivity to the prior width (the Jeffreys-Lindley effect).
"""

import numpy as np

RNG = np.random.default_rng(20261014)

X = np.linspace(-1.0, 1.0, 12)      # standardised abscissa, dimensionless
SIGMA = 0.5                          # noise standard deviation, same units as y
TAU = 1.0                            # prior standard deviation of coefficients
A0, A1 = 0.5, 1.0                    # SYNTHETIC true intercept and slope
MAX_ORDER = 3


def section(title):
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def design(order, x=X):
    return np.column_stack([x ** j for j in range(order + 1)])


def log_evidence_analytic(y, order, tau=TAU, x=X):
    """Exact log p(y | order) marginalising Gaussian coefficients.

    y ~ N(0, sigma^2 I + tau^2 Phi Phi^T) after the coefficients are integrated
    out, because the prior on c is N(0, tau^2 I) and the likelihood is
    N(Phi c, sigma^2 I).
    """
    Phi = design(order, x)
    n = y.size
    C = SIGMA ** 2 * np.eye(n) + tau ** 2 * (Phi @ Phi.T)
    L = np.linalg.cholesky(C)
    z = np.linalg.solve(L, y)
    logdet = 2.0 * np.sum(np.log(np.diag(L)))
    return -0.5 * (n * np.log(2.0 * np.pi) + logdet + z @ z)


def map_coefficients(y, order, tau=TAU):
    Phi = design(order)
    d = order + 1
    H = Phi.T @ Phi / SIGMA ** 2 + np.eye(d) / tau ** 2
    c_map = np.linalg.solve(H, Phi.T @ y / SIGMA ** 2)
    return c_map, H


def main():
    y = A0 + A1 * X + SIGMA * RNG.standard_normal(X.size)
    n = y.size

    section("1. The SYNTHETIC data and the model family")
    print(f"12 points, x uniform on [-1, 1]; y = {A0} + {A1} x + "
          f"N(0, {SIGMA}^2)  (SYNTHETIC)")
    print(f"model M_k: polynomial of order k, coefficients c ~ N(0, {TAU}^2 I)")
    print(f"model prior: uniform over k = 0, 1, 2, 3")
    print("reported quantities are the marginal likelihood p(y | M_k), with the")
    print("coefficients integrated out, and the implied posterior over k")

    section("2. Evidence, BIC and AIC on the same data")
    rows = []
    for k in range(MAX_ORDER + 1):
        loge = log_evidence_analytic(y, k)
        c_map, H = map_coefficients(y, k)
        rss = float(np.sum((y - design(k) @ c_map) ** 2))
        logL_max = -0.5 * n * np.log(2 * np.pi * SIGMA ** 2) - rss / (2 * SIGMA ** 2)
        bic = -2 * logL_max + (k + 1) * np.log(n)
        aic = -2 * logL_max + 2 * (k + 1)
        rows.append((k, loge, logL_max, rss, bic, aic))
    best = max(rows, key=lambda r: r[1])
    logZ = np.log(np.mean([np.exp(r[1] - best[1]) for r in rows]))
    print("  k  dim   log evidence     BIC      AIC    posterior P(M_k)")
    print("  " + "-" * 66)
    for k, loge, _, _, bic, aic in rows:
        pk = np.exp(loge - best[1]) / (len(rows) * np.exp(logZ))
        print(f"  {k}   {k + 1}   {loge:13.4f}  {bic:8.3f}  {aic:8.3f}   {pk:14.4f}")
    print("Read the row that is actually highest: with these 12 points and a")
    print("coefficient prior of width 1, the evidence mildly prefers the QUADRATIC,")
    print("although the data were generated by a straight line. Model selection is")
    print("not the same question as 'which model is true', and a finite sample can")
    print("disagree with the truth. The AIC column is flatter still: AIC estimates")
    print("expected predictive performance, not the probability of a model, and it")
    print("does not pay the full price for the prior volume an extra coefficient")
    print("brings. Section 7 shows what happens as the sample grows.")

    section("3. The Laplace approximation and its measured error")
    print("log p(y|k) ~ log[p(y|c_hat) p(c_hat|k)] + (d/2) log 2pi - 0.5 log|H|")
    print("   k   exact log evidence   Laplace     difference")
    print("   " + "-" * 56)
    for k in range(MAX_ORDER + 1):
        exact = log_evidence_analytic(y, k)
        c_map, H = map_coefficients(y, k)
        d = k + 1
        rss = float(np.sum((y - design(k) @ c_map) ** 2))
        loglik = -0.5 * n * np.log(2 * np.pi * SIGMA ** 2) - rss / (2 * SIGMA ** 2)
        logprior = -0.5 * np.sum(c_map ** 2) / TAU ** 2 \
            - 0.5 * d * np.log(2 * np.pi * TAU ** 2)
        sign, logdetH = np.linalg.slogdet(H)
        lap = loglik + logprior + 0.5 * d * np.log(2 * np.pi) - 0.5 * logdetH
        print(f"   {k}   {exact:19.4f}   {lap:9.4f}   {lap - exact:+11.6f}")
    print("The Laplace approximation is exact here because the integrand is")
    print("Gaussian: the measured difference is at the level of double-precision")
    print("solver error. Where the integrand is not Gaussian the same formula is")
    print("an approximation whose error must be reported, not assumed away.")

    section("4. The Occam factor: evidence is a likelihood times a volume ratio")
    print("   k   best-fit log-lik   log p(y|k)   Occam factor = p(y|k)/e^loglik")
    print("   " + "-" * 68)
    for k in range(MAX_ORDER + 1):
        loge = log_evidence_analytic(y, k)
        c_map, _ = map_coefficients(y, k)
        rss = float(np.sum((y - design(k) @ c_map) ** 2))
        loglik = -0.5 * n * np.log(2 * np.pi * SIGMA ** 2) - rss / (2 * SIGMA ** 2)
        print(f"   {k}   {loglik:13.4f}   {loge:11.4f}   {np.exp(loge - loglik):8.5f}")
    print("The best-fit likelihood improves with order, because a higher order can")
    print("fit at least as well. The evidence does not follow it down: the Occam")
    print("factor, the ratio in the last column, falls by roughly an order of")
    print("magnitude for each added coefficient. That falling ratio is the price of")
    print("the extra prior volume, and it is Occam's razor stated as arithmetic")
    print("rather than as taste. Note that the factor is still below 1 for every")
    print("order: the prior width 1 is broad for this problem, so even the best")
    print("model's evidence is much smaller than its best-fit likelihood.")

    section("5. Independent check: numerical integration of the evidence")
    # Grid integration over the coefficients for k = 0 and k = 1.
    for k in (0, 1):
        if k == 0:
            g = np.linspace(-3.0, 3.0, 200001)
            dg = g[1] - g[0]
            R = y[None, :] - g[:, None]
            logpost = -0.5 * np.sum(R ** 2, axis=1) / SIGMA ** 2 \
                - 0.5 * g ** 2 / TAU ** 2 - n / 2 * np.log(2 * np.pi * SIGMA ** 2) \
                - 0.5 * np.log(2 * np.pi * TAU ** 2)
            m = logpost.max()
            Z = np.exp(logpost - m).sum() * dg * np.exp(m)
        else:
            g0 = np.linspace(-3.0, 3.0, 1501)
            g1 = np.linspace(-3.0, 3.0, 1501)
            dg = g0[1] - g0[0]
            A, B = np.meshgrid(g0, g1, indexing="ij")
            R = y[None, None, :] - A[..., None] - B[..., None] * X[None, None, :]
            logpost = -0.5 * np.sum(R ** 2, axis=-1) / SIGMA ** 2 \
                - 0.5 * (A ** 2 + B ** 2) / TAU ** 2 \
                - n / 2 * np.log(2 * np.pi * SIGMA ** 2) \
                - 0.5 * 2 * np.log(2 * np.pi * TAU ** 2)
            m = logpost.max()
            Z = np.exp(logpost - m).sum() * dg * dg * np.exp(m)
        exact = np.exp(log_evidence_analytic(y, k))
        print(f"  k = {k}: grid-integrated evidence {Z:.6e}, analytic {exact:.6e}, "
              f"relative error {abs(Z / exact - 1):.2e}")
    print("Two independent routes to the same number: the analytic Gaussian")
    print("integral and brute-force quadrature. They agree to the quadrature error.")

    section("6. Sensitivity to the prior width: the Jeffreys-Lindley effect")
    print("Bayes factor for M_1 against M_0 as the coefficient prior width changes")
    print("   tau    log10 BF(1 vs 0)   posterior P(M_0)   posterior P(M_1)")
    print("   " + "-" * 62)
    for tau in (0.1, 0.3, 1.0, 3.0, 10.0, 100.0):
        l0 = log_evidence_analytic(y, 0, tau)
        l1 = log_evidence_analytic(y, 1, tau)
        bf = (l1 - l0) / np.log(10.0)
        p1 = 1.0 / (1.0 + 10.0 ** (-bf))
        print(f"  {tau:5.1f}   {bf:16.4f}   {1 - p1:15.4f}   {p1:15.4f}")
    print("As the prior on the extra coefficient is widened without limit, the")
    print("evidence stops favouring the model that is actually true and drifts")
    print("toward the simpler model. The Bayes factor is not a prior-free measure")
    print("of evidence: p(y|M) is an average of the likelihood over the prior, so")
    print("it always depends on that prior. Report the prior width with the number.")


    section("7. Does the evidence find the true model as the sample grows?")
    print("Same model family and prior width; only the number of data changes.")
    print("   n   log10 BF(2 vs 1)   P(k=0)   P(k=1)   P(k=2)   P(k=3)")
    print("   " + "-" * 66)
    rng = np.random.default_rng(20261014)
    for nn in (12, 24, 48, 96):
        xx = np.linspace(-1.0, 1.0, nn)
        yy = A0 + A1 * xx + SIGMA * rng.standard_normal(nn)
        lz = np.array([log_evidence_analytic(yy, k, x=xx)
                       for k in range(MAX_ORDER + 1)])
        pk = np.exp(lz - lz.max())
        pk /= pk.sum()
        bf21 = (lz[2] - lz[1]) / np.log(10.0)
        print(f"  {nn:3d}   {bf21:16.4f}   {pk[0]:6.4f}   {pk[1]:6.4f}   "
              f"{pk[2]:6.4f}   {pk[3]:6.4f}")
    print("The Occam penalty for an extra coefficient grows with the sample size")
    print("like (d/2) log n, while the spurious improvement in the best-fit")
    print("likelihood does not. By n = 48 on this realisation the evidence has")
    print("moved to the model that is true. But at n = 96 it moves back to the")
    print("quadratic: consistency is a statement about the truth as n grows, and a")
    print("single finite sample can still disagree. Model selection is a decision")
    print("made on one data set, and it should be reported as such.")


if __name__ == "__main__":
    main()
