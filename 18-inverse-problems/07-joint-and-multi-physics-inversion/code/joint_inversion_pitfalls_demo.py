#!/usr/bin/env python3
"""Three measured pitfalls of joint inversion: relative weighting, inconsistent
physics, and over-coupling.

Run with the project venv:

    /Users/miroslav/Documents/workspace/geophysics/.venv/bin/python joint_inversion_pitfalls_demo.py

All models and data are SYNTHETIC.  The operators and the assumed reference
model are chosen teaching ingredients; no number below is a measurement.

Contents
--------
1. Relative weighting: the misfit trade-off and where the joint solution
   collapses onto a single-data-set solution.
2. Inconsistent physics: two data sets that cannot both be explained.
3. Over-coupling: a strong pull towards an assumed reference model.
"""

import numpy as np

RNG = np.random.default_rng(20261014)

N = 20                            # model cells
SIGMA = 0.05                      # data standard deviation (teaching units)
LAMBDA_SMOOTH = 0.05              # smoothness weight


def section(title: str) -> None:
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def operators():
    """A1: 8 broad kernels; A2: 16 localised kernels.  SYNTHETIC teaching
    operators, deliberately different in conditioning."""
    z = np.arange(N, dtype=float)
    z1 = np.linspace(1.0, 18.0, 8)
    z2 = np.linspace(1.0, 18.0, 16)
    A1 = np.exp(-(z1[:, None] - z[None, :]) ** 2 / (2 * 4.0 ** 2))
    A2 = np.exp(-(z2[:, None] - z[None, :]) ** 2 / (2 * 1.2 ** 2))
    return A1, A2


def smoothness():
    D = np.zeros((N - 1, N))
    for k in range(N - 1):
        D[k, k] = -1.0
        D[k, k + 1] = 1.0
    return D


def invert(A1, A2, d1, d2, D, w1=1.0, w2=1.0, m_ref=None, mu=0.0):
    """Weighted least squares with an optional quadratic pull towards m_ref."""
    lhs = (w1 * A1.T @ A1 + w2 * A2.T @ A2
           + LAMBDA_SMOOTH * (D.T @ D + 1e-6 * np.eye(N)) + mu * np.eye(N))
    rhs = w1 * A1.T @ d1 + w2 * A2.T @ d2
    if m_ref is not None:
        rhs = rhs + mu * m_ref
    return np.linalg.solve(lhs, rhs)


def rmse(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))


def main():
    A1, A2 = operators()
    D = smoothness()
    i = np.arange(N, dtype=float)
    m_true = 0.5 + 0.4 * np.sin(2 * np.pi * i / N)
    d1 = A1 @ m_true + SIGMA * RNG.standard_normal(A1.shape[0])
    d2 = A2 @ m_true + SIGMA * RNG.standard_normal(A2.shape[0])

    section("1. Relative weighting: the misfit trade-off")
    m_only1 = invert(A1, A2, d1, d2, D, w1=1.0, w2=0.0)
    m_only2 = invert(A1, A2, d1, d2, D, w1=0.0, w2=1.0)
    print(f"  SYNTHETIC truth: a unit sine on {N} cells; sigma = {SIGMA:.2f}")
    print(f"  single-data-set solutions: error(A1 only) = {rmse(m_only1, m_true):.4f}, "
          f"error(A2 only) = {rmse(m_only2, m_true):.4f}")
    print(f"  the A1-only solution fits A2 at chi = "
          f"{rmse(A2 @ m_only1, d2) / SIGMA:.2f} per datum; the A2-only solution")
    print(f"  fits A1 at chi = {rmse(A1 @ m_only2, d1) / SIGMA:.2f} per datum.")
    print()
    print("  w1/w2      chi1     chi2    error    dist-to-A1-only  dist-to-A2-only")
    for w in (1e-3, 1e-2, 1e-1, 1.0, 1e1, 1e2, 1e3):
        m = invert(A1, A2, d1, d2, D, w1=w, w2=1.0)
        print(f"  {w:7.3f}   "
              f"{rmse(A1 @ m, d1) / SIGMA:6.2f}   {rmse(A2 @ m, d2) / SIGMA:6.2f}   "
              f"{rmse(m, m_true):.4f}   {rmse(m, m_only1):.4f}          "
              f"{rmse(m, m_only2):.4f}")
    print(f"  at w1 = 1e-3 the joint solution sits {rmse(invert(A1, A2, d1, d2, D, w1=1e-3, w2=1.0), m_only2):.4f}")
    print("  from the A2-only solution: data set 1 has been discarded.")
    print(f"  at w1 = 1e3 it sits "
          f"{rmse(invert(A1, A2, d1, d2, D, w1=1e3, w2=1.0), m_only1):.4f} from the "
          f"A1-only solution:")
    print("  data set 2 has been discarded.  In between, both chi values are near")
    print("  1 and the model error is smallest.  The weight is a claim about the")
    print("  data errors; a sweep is how you find out whether the claim matters.")

    section("2. Inconsistent physics: two data sets that cannot both be explained")
    # data set 2 is generated by a DIFFERENT truth: the two physics disagree.
    m_alt = 0.5 + 0.4 * np.sin(2 * np.pi * i / N + 0.9)
    d2_alt = A2 @ m_alt + SIGMA * RNG.standard_normal(A2.shape[0])
    m_inco = invert(A1, A2, d1, d2_alt, D, w1=1.0, w2=1.0)
    m_sep1 = invert(A1, A2, d1, d2_alt, D, w1=1.0, w2=0.0)
    m_sep2 = invert(A1, A2, d1, d2_alt, D, w1=0.0, w2=1.0)
    print(f"  data set 1 comes from the sine; data set 2 from a phase-shifted sine")
    print(f"  (phase 0.9 rad) -- two different Earths, by construction.")
    print(f"  separate inversions: chi(A1 | m1) = "
          f"{rmse(A1 @ m_sep1, d1) / SIGMA:.2f}, "
          f"chi(A2 | m2) = {rmse(A2 @ m_sep2, d2_alt) / SIGMA:.2f}")
    print(f"  joint inversion:    chi(A1 | m)  = "
          f"{rmse(A1 @ m_inco, d1) / SIGMA:.2f}, "
          f"chi(A2 | m)  = {rmse(A2 @ m_inco, d2_alt) / SIGMA:.2f}")
    print(f"  the two separate models differ by {rmse(m_sep1, m_sep2):.4f} rms,")
    print(f"  which is {rmse(m_sep1, m_sep2) / rmse(m_sep1, m_true):.1f} times the")
    print("  error of the better one.  The joint inversion cannot make both chi")
    print("  equal 1: the inconsistency is in the physics, not in the noise, and")
    print("  the residual is the only place it shows up.  A joint inversion with")
    print("  residuals left unexplained is not a failure of the solver; it is a")
    print("  measurement of a real inconsistency that must be reported.")

    section("3. Over-coupling: a strong pull towards an assumed reference model")
    shift = 0.25
    m_ref = m_true + shift
    print(f"  assumed reference model = truth + {shift:.2f} (a systematic error,")
    print("  e.g. a mis-tied datum or a legacy model used as a hard constraint)")
    print("  mu        error       distance-to-reference   chi1     chi2")
    for mu in (0.0, 0.1, 1.0, 10.0, 100.0, 1000.0):
        m = invert(A1, A2, d1, d2, D, w1=1.0, w2=1.0, m_ref=m_ref, mu=mu)
        print(f"  {mu:8.1f}   {rmse(m, m_true):.4f}   {rmse(m, m_ref):.4f}          "
              f"    {rmse(A1 @ m, d1) / SIGMA:5.2f}   {rmse(A2 @ m, d2) / SIGMA:5.2f}")
    print(f"  a small pull (mu = 0.1-1) happens to LOWER the model error, because")
    print("  the wrong reference still acts as shrinkage toward the prior mean; the")
    print("  chi values rise while the error falls, which is the honest warning that")
    print("  a lower error against a synthetic truth is not a licence.  Beyond that")
    print(f"  the model converges onto the reference and its error converges to the")
    print(f"  systematic error of the reference ({shift:.2f}), while both chi values")
    print("  grow without bound.  'Over-coupled' does not mean a numerically")
    print("  unstable weight; it means a weight that makes the model express the")
    print("  assumption rather than the data.  Every chi above is a gate: a coupling")
    print("  that pushes chi far above 1 has stopped inverting.")


if __name__ == "__main__":
    main()
